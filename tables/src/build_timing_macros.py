"""Build tables/macros_timing.tex from tables/timing_summary.tsv. Numbers are never typed by hand.

timing_summary.tsv is the output of tools/xabl_timing.py (branch xre_abl) run on HOST_A for the adopted setting
(lambda 0.1, K 40): MSCA Native / anchor term only / XRE, seed 1, 3 training epochs each on one GPU used by nothing
else (other processes on that GPU were paused), mean training seconds per epoch excluding the first epoch, peak allocated
memory during training, and one validation pass. Source copy: <RUN_ROOT_B>/P04_main_runs/timing_l010_k40.
MES (2026-10-10, r20_R1/MANU): when timing_summary.tsv has rows labelled MES (tools/xabl_timing.py at P04_novctrl_wt 6bea495,
Native objx_s <ds>_native and MES xres0 <ds>_xres_xeoa0_l010_k40, seed 1, 3 epochs, GPU with no other process; source
HOST_A <DATA_ROOT>/MANU/timing/out_a1), the ratios use MES instead of XRE; the macro names stay.
Usage: python tables/src/build_timing_macros.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TSV = ROOT / 'timing_summary.tsv'
OUT = ROOT / 'macros_timing.tex'
NAMES = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific'}


def main():
    with open(TSV, newline='') as f:
        rows = list(csv.DictReader(f, delimiter='\t'))
    cell = {}
    for r in rows:
        ds = r['dataset'].split('@')[0]
        cell[(r['label'], ds)] = r
    arm = 'MES' if any(k[0] == 'MES' for k in cell) else 'XRE'
    ratios_t, ratios_m, lines = [], [], ['% Generated by tables/src/build_timing_macros.py from tables/timing_summary.tsv '
                                         f'(proposed row: {arm}).']
    for ds, name in NAMES.items():
        nat, xre = cell[('Native', ds)], cell.get(('MES', ds)) or cell[('XRE', ds)]
        rt = float(xre['mean_train_sec_excl_e0']) / float(nat['mean_train_sec_excl_e0'])
        rm = float(xre['peak_train_alloc_mib']) / float(nat['peak_train_alloc_mib'])
        ratios_t.append(rt)
        ratios_m.append(rm)
        lines += [f'\\newcommand{{\\timeRatio{name}}}{{{rt:.2f}}}',
                  f'\\newcommand{{\\memRatio{name}}}{{{rm:.2f}}}',
                  f'\\newcommand{{\\timeNative{name}}}{{{float(nat["mean_train_sec_excl_e0"]):.1f}}}',
                  f'\\newcommand{{\\timeXre{name}}}{{{float(xre["mean_train_sec_excl_e0"]):.1f}}}']
    lines += [f'\\newcommand{{\\timeRatioMin}}{{{min(ratios_t):.1f}}}',
              f'\\newcommand{{\\timeRatioMax}}{{{max(ratios_t):.1f}}}',
              f'\\newcommand{{\\memIncMin}}{{{round((min(ratios_m) - 1) * 100)}}}',
              f'\\newcommand{{\\memIncMax}}{{{round((max(ratios_m) - 1) * 100)}}}']
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print('wrote', OUT, 'time ratio', [f'{x:.2f}' for x in ratios_t], 'mem ratio', [f'{x:.2f}' for x in ratios_m])


if __name__ == '__main__':
    main()
