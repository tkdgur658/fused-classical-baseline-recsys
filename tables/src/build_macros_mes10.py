"""Build tables/macros_mes10.tex and tables/appendix_mes10.tex: the MES10 verdict (PREREG_MES10, study; author decision,
revision log 25). Added 2026-10-17. Numbers are never typed by hand.

Sources (copies of HOST_A study/MES10, read-only):
  tables/src/data/mes10_verdict.json   summary/mes10_verdict.json (code/mes10_verdict.py): per contrast (M-F, S-F, S-M) and metric
                                       (R@20, N@20) the paired t-test over seeds (ten for M-F, five otherwise), Holm over the four datasets
  tables/src/data/mes10_perseed.csv    summary/mes10_perseed.csv: every run (arm, dataset, seed, R@20, N@20), M seeds 1-5 = reported runs
  tables/src/data/mes10_cpucheck_baby.out   tests/real.out (CPU check of arm S on the reported MES checkpoint, Baby seed 1, 40 edges)
  tables/src/data/mes10_cpucheck_sports.out tests/a1_real_sports.out (same check after amendment A1, Sports seed 1, three layers)
Arms: M = MES (masked view, the reported runs and seeds 6-10), F = the full-view control at the same lambda and K with matched
coefficient mass, S = F with the direct self summand subtracted algebraically from the full-view score of each held-out positive.
Usage: python tables/src/build_macros_mes10.py
"""
import csv
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from numwords import num_word  # noqa: E402

ROOT = HERE.parent
DATA = HERE / 'data'
DS = ['baby', 'pantry', 'scientific', 'sports']
NAME = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports'}
BS = chr(92)
OUT = ['% Generated by tables/src/build_macros_mes10.py from tables/src/data/mes10_verdict.json, mes10_perseed.csv and the two CPU-check',
       '% outputs of PREREG_MES10 (revision log 25). Do not edit by hand. Counts 0-10 are spelled out.']


def mac(n, v):
    assert re.fullmatch(r'[A-Za-z]+', n), n
    OUT.append(BS + 'newcommand{' + BS + n + '}{' + str(v) + '}')


def join(items):
    if not items:
        return 'none'
    return items[0] if len(items) == 1 else ', '.join(items[:-1]) + (',' if len(items) > 2 else '') + ' and ' + items[-1]


def last_json(path):
    txt = Path(path).read_text(encoding='utf-8', errors='replace')
    i = txt.index('\n{') + 1
    j = txt.rindex('}') + 1
    return json.loads(txt[i:j])


def main():
    V = json.load(open(DATA / 'mes10_verdict.json', encoding='utf-8'))
    C = V['contrasts']
    runs = list(csv.DictReader(open(DATA / 'mes10_perseed.csv', newline='', encoding='utf-8')))
    seeds = {(r['arm'], r['dataset']) : set() for r in runs}
    for r in runs:
        seeds[(r['arm'], r['dataset'])].add(int(r['seed']))
    nM = {len(seeds[('M', d)]) for d in DS}
    nF = {len(seeds[('F', d)]) for d in DS}
    nS = {len(seeds[('S', d)]) for d in DS}
    assert len(nM) == len(nF) == len(nS) == 1
    nM, nF, nS = nM.pop(), nF.pop(), nS.pop()
    assert nM == nF and not V['verdict']['incomplete']
    mac('mtNSeedsMF', num_word(nM))
    mac('mtNSeedsS', num_word(nS))
    mac('mtNRuns', str(sum(1 for r in runs if r['status'] == 'DONE')))
    mac('mtNDs', num_word(len(DS)))
    for key, tag in (('M-F', 'MF'), ('S-F', 'SF'), ('S-M', 'SM')):
        for met, mt in (('R@20', 'R'), ('N@20', 'N')):
            res = C[f'{key} {met}']['results']
            assert sorted(r['dataset'] for r in res) == DS
            pos = [NAME[r['dataset']] for r in res if r['reject'] and r['diff'] > 0]
            neg = [NAME[r['dataset']] for r in res if r['reject'] and r['diff'] < 0]
            mac(f'mt{tag}{mt}NSig', num_word(len(pos)))
            mac(f'mt{tag}{mt}NNeg', num_word(len(neg)))
            mac(f'mt{tag}{mt}SigDs', join(pos))
            mac(f'mt{tag}{mt}NegDs', join(neg))
            mac(f'mt{tag}{mt}NPos', num_word(sum(r['diff'] > 0 for r in res)))
            d = [r['diff'] for r in res]
            # revision log 26: typeset signs ($+$, $-$) because Table S10 is replaced by sentences that quote these ranges
            mac(f'mt{tag}{mt}Min', f'{min(d):+.4f}'.replace('+', '$+$').replace('-', '$-$'))
            mac(f'mt{tag}{mt}Max', f'{max(d):+.4f}'.replace('+', '$+$').replace('-', '$-$'))
            sig = [r for r in res if r['reject']]
            mac(f'mt{tag}{mt}PHolmMax', f"{max(r['p_holm'] for r in sig):.3f}" if sig else '--')
            # revision log 29 (item 8a): smallest Holm-adjusted p of the row (all datasets), for "Holm p >= ..." sentences
            mac(f'mt{tag}{mt}PHolmMin', f"{min(r['p_holm'] for r in res):.3f}")
    # verdict rule of the prereg, read from the json
    mac('mtVerdict', V['verdict']['consequence'].lower())
    assert V['verdict']['n_MgtF_holm_sig'] == sum(r['reject'] and r['diff'] > 0 for r in C['M-F R@20']['results'])
    # CPU check of arm S: residual of the algebraic subtraction against an exact edge removal, as a share of the mean |S|
    b = last_json(DATA / 'mes10_cpucheck_baby.out')['baby_seed1_trained']
    s = last_json(DATA / 'mes10_cpucheck_sports.out')['sports_seed1_trained']
    rb, rs = 100 * b['resid_total_over_mean_abs_S'], 100 * s['resid_total_over_mean_abs_S']
    mac('mtResidBaby', f'{rb:.1f}')
    mac('mtResidSports', f'{rs:.1f}')
    mac('mtResidLo', f'{min(rb, rs):.1f}')
    mac('mtResidHi', f'{max(rb, rs):.1f}')
    mac('mtCorrLo', f"{min(b['corr_S_vs_exact_drop'], s['corr_S_vs_exact_drop']):.2f}")
    mac('mtCorrHi', f"{max(b['corr_S_vs_exact_drop'], s['corr_S_vs_exact_drop']):.2f}")
    mac('mtCheckEdges', num_word(b['n_edges']) if b['n_edges'] <= 10 else str(b['n_edges']))
    assert b['n_edges'] == s['n_edges']
    (ROOT / 'macros_mes10.tex').write_text('\n'.join(OUT) + '\n', encoding='utf-8', newline='\n')

    # supplementary table: every contrast, both metrics, difference x 1e-3 with significance after Holm
    def cell(r):
        x = 1e3 * r['diff']
        s_ = ('$+$' if x >= 0 else '$-$') + f'{abs(x):.2f}'
        if r['reject']:
            s_ = f'\\textbf{{{s_}}}'
        return s_
    L = ['% Generated by tables/src/build_macros_mes10.py (MES10 verdict, PREREG_MES10). Do not edit numbers by hand.',
         '\\begin{table}[t]',
         '\\caption{MES10: masked view (M, the MES runs), full-view control at the same $\\lambda$ and $K$ with matched coefficient mass (F), and '
         'the full view with the direct self summand subtracted algebraically (S) on MSCA. Each cell is $10^3$ times the mean test difference, '
         f'with seeds 1--{nM} for M$-$F and seeds 1--{nS} for S$-$F and S$-$M, and bold marks a two-sided paired $t$-test that is significant '
         'after Holm correction over the four datasets of each row. Baby uses the data copy of the reported MES runs (the canonical build of '
         'Table~\\ref{tab:babybuild}).}',
         '\\label{tab:mes10}', '\\centering', '\\footnotesize', '\\setlength{\\tabcolsep}{3.5pt}',
         '\\begin{tabular}{llcccc}', '\\toprule', 'Contrast & Metric & Baby & Pantry & Scientific & Sports \\\\', '\\midrule']
    for key in ('M-F', 'S-F', 'S-M'):
        for met in ('R@20', 'N@20'):
            res = {r['dataset']: r for r in C[f'{key} {met}']['results']}
            lab = key.replace('-', '$-$')
            L.append(f'{lab} & {met} & ' + ' & '.join(cell(res[d]) for d in DS) + ' \\\\')
        if key != 'S-M':
            L.append('\\midrule')
    L += ['\\bottomrule', '\\end{tabular}', '\\end{table}', '']
    (ROOT / 'appendix_mes10.tex').write_text('\n'.join(L), encoding='utf-8', newline='\n')
    print('\n'.join(OUT))


if __name__ == '__main__':
    main()
