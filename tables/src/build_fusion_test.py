"""Post-hoc paired test of MSCA + MES (+)F against MSCA (+)F (revision log 17, D-14), the same test as the MES-F verdict
(study/MESF/code/mesf_verdict.py): two-sided paired t over seeds 1-5 on test Recall@20, Holm over the datasets with five
seeds of both rows. Post-hoc analysis: PREREG_MES9 judged only the count of raised cells (50 of 50).
Source: tables/src/data/fusion_cells_9ds_mes.csv (= study/results copy; duplicate rows must be identical and are dropped).
Writes tables/src/data/fusion_test.json and tables/macros_fusiontest.tex. Numbers are never typed by hand.
Usage: python tables/src/build_fusion_test.py
"""
import csv, json
from pathlib import Path
from scipy import stats

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'src' / 'data' / 'fusion_cells_9ds_mes.csv'
TUNED = ['baby', 'pantry', 'scientific', 'sports']
WORD = ['none', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten']
BS = chr(92)


def holm(ps):
    order = sorted(range(len(ps)), key=lambda i: ps[i])
    adj, run = [0.0] * len(ps), 0.0
    for r, i in enumerate(order):
        run = max(run, min(1.0, (len(ps) - r) * ps[i]))
        adj[i] = run
    return adj


def test(ds, cell):
    rows = []
    for d in ds:
        a = [cell[('MSCA+MES', d, s)] for s in range(1, 6)]
        b = [cell[('MSCA', d, s)] for s in range(1, 6)]
        t, p = stats.ttest_rel(a, b)
        rows.append(dict(ds=d, diff=sum(a) / 5 - sum(b) / 5, t=float(t), p=float(p), wins=sum(x > y for x, y in zip(a, b))))
    for r, pa in zip(rows, holm([r['p'] for r in rows])):
        r['p_holm'] = pa
    return rows


def main():
    cell, seen = {}, {}
    with open(SRC, newline='', encoding='utf-8') as f:
        for r in csv.DictReader(f):
            k = (r['model'], r['dataset'], int(r['seed']))
            if r['model'] not in ('MSCA', 'MSCA+MES') or not r['fused_r20']:
                continue
            if k in seen:
                assert seen[k] == r, ('conflicting duplicate', k)
                continue
            seen[k] = r
            cell[k] = float(r['fused_r20'])
    both = sorted({d for (m, d, s) in cell if all((mm, d, ss) in cell for mm in ('MSCA', 'MSCA+MES') for ss in range(1, 6))},
                  key=lambda d: (d not in TUNED, TUNED.index(d) if d in TUNED else d))
    fam_all, fam_tuned = test(both, cell), test(TUNED, cell)
    n_sig = sum(r['p_holm'] < .05 for r in fam_all)
    n_sig_t = sum(r['p_holm'] < .05 for r in fam_tuned)
    out = dict(datasets=both, family_all=fam_all, family_tuned=fam_tuned, n_sig_all=n_sig, n_sig_tuned=n_sig_t)
    (ROOT / 'src' / 'data' / 'fusion_test.json').write_text(json.dumps(out, indent=1), encoding='utf-8')
    for r in fam_all:
        print(f"{r['ds']:12s} diff {r['diff']:+.4f} p {r['p']:.4f} p_holm {r['p_holm']:.4f} wins {r['wins']}/5")
    print('tuned family:', [(r['ds'], round(r['p_holm'], 4)) for r in fam_tuned])
    pmin = min(r['p'] for r in fam_all)
    lines = ['% Generated by tables/src/build_fusion_test.py from fusion_cells_9ds_mes.csv. Do not edit by hand.',
             BS + 'newcommand{' + BS + 'ftNDs}{' + WORD[len(both)] + '}',
             BS + 'newcommand{' + BS + 'ftNSig}{' + WORD[n_sig] + '}',
             BS + 'newcommand{' + BS + 'ftPMin}{' + f'{pmin:.2f}' + '}', '']
    (ROOT / 'macros_fusiontest.tex').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
