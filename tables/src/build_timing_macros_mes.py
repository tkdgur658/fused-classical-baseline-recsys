"""Four-dataset MES timing (PREREG_MESCKPT section 10): tables/src/data/timing_summary_mes.tsv and tables/macros_timing_mes.tex.

Rows Baby, Pantry, Scientific = tables/timing_summary.tsv (10/10 measurement, tools/xabl_timing.py at P04_novctrl_wt dba2ba3,
Native objx_s <ds>_native and MES xres0 main-table configs, seed 1, 3 epochs, one GPU used by nothing else).
Row Sports = new measurement 2026-10-16 with the same tool and commit (Native sports_native, MES sports_xres_xeoa0_l010_k80),
read from the two timing_summary.tsv files written by the server step (study/results/mesckpt/timing_raw/out_sports/<pkg>/).
Macro names are those of macros_timing.tex (timeXre* holds the MES value) plus the Sports quantities; Min / Max run over four datasets.
Usage: python tables/src/build_timing_macros_mes.py <sports_native_tsv> <sports_mes_tsv>
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAMES = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports'}


def rd(p):
    with open(p, newline='') as f:
        return list(csv.DictReader(f, delimiter='\t'))


def main():
    rows = [r for r in rd(ROOT / 'timing_summary.tsv') if r['label'] in ('Native', 'MES')]
    for p in sys.argv[1:3]:
        rows += rd(p)
    hdr = list(rows[0])
    out = ROOT / 'src' / 'data' / 'timing_summary_mes.tsv'
    out.write_text('\n'.join(['\t'.join(hdr)] + ['\t'.join(r[h] for h in hdr) for r in rows]) + '\n', encoding='utf-8', newline='\n')
    cell = {(r['label'], r['dataset'].split('@')[0]): r for r in rows}
    rt, rm, L = [], [], ['% Generated by tables/src/build_timing_macros_mes.py from tables/src/data/timing_summary_mes.tsv (MES, four datasets).']
    for ds, n in NAMES.items():
        a, b = cell[('Native', ds)], cell[('MES', ds)]
        t = float(b['mean_train_sec_excl_e0']) / float(a['mean_train_sec_excl_e0'])
        m = float(b['peak_train_alloc_mib']) / float(a['peak_train_alloc_mib'])
        rt.append(t); rm.append(m)
        L += [f'\\newcommand{{\\timeRatio{n}}}{{{t:.2f}}}', f'\\newcommand{{\\memRatio{n}}}{{{m:.2f}}}',
              f'\\newcommand{{\\timeNative{n}}}{{{float(a["mean_train_sec_excl_e0"]):.1f}}}',
              f'\\newcommand{{\\timeXre{n}}}{{{float(b["mean_train_sec_excl_e0"]):.1f}}}']
    L += [f'\\newcommand{{\\timeRatioMin}}{{{min(rt):.1f}}}', f'\\newcommand{{\\timeRatioMax}}{{{max(rt):.1f}}}',
          f'\\newcommand{{\\memIncMin}}{{{round((min(rm) - 1) * 100)}}}', f'\\newcommand{{\\memIncMax}}{{{round((max(rm) - 1) * 100)}}}']
    (ROOT / 'macros_timing_mes.tex').write_text('\n'.join(L) + '\n', encoding='utf-8', newline='\n')
    print('time ratio', [f'{x:.3f}' for x in rt], 'mem ratio', [f'{x:.3f}' for x in rm])


if __name__ == '__main__':
    main()
