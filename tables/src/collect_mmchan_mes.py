"""Channel split of the self-message for MSCA and MES (closes the 4d g) TODO "modality-wise split of this share"; FIGURE_TODO.md
(b) b.3 steps 1-2, checkpoint analysis only, no retraining). Reads remote files, trains nothing.

Sources (one run per seed, seeds 1-5, CPU inference on HOST_A):
  MES  = HOST_A <RUN_ROOT_B>/P04_newprin/mmchan/summary_mes_long.csv (mmchan/summ_mes.py = summ.msca_cell, the
         metrics and user bootstrap of summ.py, imported unchanged) over the cells of the MAIN-table MES checkpoints (xres0;
         Baby baby_xres_xeoa0_l030_k40, Pantry l010_k20, Scientific l020_k40, Sports l010_k80): mmchan2.py -> mmchan/out_mes
         (Baby, Pantry, Scientific) and the 3-layer mmchan_sports/mmchan3_nl.py -> mmchan_sports/out3_mes (Sports), driver
         mmchan/driver_mes.sh, training pairs and negatives = P04_newprin/prop2{,_sports}/out/<ds>_mes_s<k>.
         summ_mes.py stops unless, per cell, the restored test Recall@20 / NDCG@20 equal result.json (4 dp), the channel
         terms add up to the self-message (block sum < 1e-9), s = c + S (< 1e-9), S equals the prop2 value (< 1e-4), the
         user / item channel split adds up to e_u / e_p (< 1e-4), and the training pairs and split hashes equal those of the
         MSCA cell of the same dataset and seed.
  MSCA = rows model MSCA, arm native of tables/mmchan_perseed.csv (Baby, Pantry, Scientific; mmchan2.py, P04_listana
         checkpoints) and of tables/mmchan_topk_perseed.csv (Sports; mmchan3_nl.py on the Table I runs), the same
         checkpoints as Fig. selfmsg; restricted to the metrics of the MES rows.
Outputs:
  tables/mmchan_mes_perseed.csv  columns of mmchan_perseed.csv (dataset, model, arm, seed, metric, value, lo, hi, n_pairs,
                                 n_users), arm native (MSCA) or mes.
  tables/macros_mmchan_mes.tex   share of the self-message carried by each channel, in percent, mean over seeds 1-5:
      \\mmShare<Ch><Arm><Ds>       Ch in Collab, Cooc (co-occurrence view), Image, Text; Arm in Msca, Mes; Ds in Baby,
                                   Pantry, Sci, Sports
      \\mmShare<Ch><Arm>Min / Max  range of the four dataset means
      \\mmDown<Ch>                 seed pairs (of 20) in which the MES share is below the MSCA share
  Not input in main.tex yet: add \\input{tables/macros_mmchan_mes.tex} next to the other macro files.
Usage (repository root): python -s tables/src/collect_mmchan_mes.py
"""
import csv
import io
import statistics as st
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
T = ROOT / 'tables'
REMOTE = '<RUN_ROOT_B>/P04_newprin/mmchan/summary_mes_long.csv'
DS = [('baby', 'Baby'), ('pantry', 'Pantry'), ('scientific', 'Sci'), ('sports', 'Sports')]
CH = [('collab', 'Collab'), ('struct', 'Cooc'), ('image', 'Image'), ('text', 'Text')]
ARMS = [('native', 'Msca'), ('mes', 'Mes')]
SEEDS = [1, 2, 3, 4, 5]
COLS = ['dataset', 'model', 'arm', 'seed', 'metric', 'value', 'lo', 'hi', 'n_pairs', 'n_users']


def main():
    out = subprocess.run(['ssh', '-o', 'BatchMode=yes', 'HOST_A', f'cat {REMOTE}'], capture_output=True, check=True)
    mes = list(csv.DictReader(io.StringIO(out.stdout.decode('utf-8'))))
    metrics = {r['metric'] for r in mes}
    nat = []
    for f, dss in (('mmchan_perseed.csv', {'baby', 'pantry', 'scientific'}), ('mmchan_topk_perseed.csv', {'sports'})):
        for r in csv.DictReader(open(T / f, newline='', encoding='utf-8')):
            if r['model'] == 'MSCA' and r['arm'] == 'native' and r['dataset'] in dss and r['metric'] in metrics:
                nat.append(r)
    rows = nat + mes
    key = {(r['dataset'], r['arm'], int(r['seed']), r['metric']): r for r in rows}
    assert len(key) == len(rows), 'duplicate rows'
    for d, _ in DS:   # both arms complete for every dataset and seed
        for a, _ in ARMS:
            for s in SEEDS:
                for c, _ in CH:
                    assert (d, a, s, f'chS_share_{c}') in key, (d, a, s, c)
    with open(T / 'mmchan_mes_perseed.csv', 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=COLS, lineterminator='\n', extrasaction='ignore')
        w.writeheader()
        w.writerows(rows)
    print('wrote tables/mmchan_mes_perseed.csv', len(rows), 'rows')

    v = lambda d, a, s, c: 100 * float(key[(d, a, s, f'chS_share_{c}')]['value'])
    lines = ['% Generated by tables/src/collect_mmchan_mes.py: channel shares (%) of the self-message, mean over seeds 1-5,',
             '% MSCA (Msca) and MES (Mes) checkpoints, same training pairs; not yet input in main.tex.']
    mac = lambda n, x: lines.append(f'\\newcommand{{\\{n}}}{{{x}}}')
    f1 = lambda x: '0.0' if round(x, 1) == 0 else f'{x:.1f}'
    for c, C in CH:
        for a, A in ARMS:
            means = []
            for d, D in DS:
                m = st.mean(v(d, a, s, c) for s in SEEDS)
                means.append(m)
                mac(f'mmShare{C}{A}{D}', f1(m))
            mac(f'mmShare{C}{A}Min', f1(min(means)))
            mac(f'mmShare{C}{A}Max', f1(max(means)))
        mac(f'mmDown{C}', str(sum(v(d, 'mes', s, c) < v(d, 'native', s, c) for d, _ in DS for s in SEEDS)))
    (T / 'macros_mmchan_mes.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print('wrote tables/macros_mmchan_mes.tex')
    for d, D in DS:
        print(D, '  '.join(f"{C} {st.mean(v(d, 'native', s, c) for s in SEEDS):.1f}->{st.mean(v(d, 'mes', s, c) for s in SEEDS):.1f}"
                           for c, C in CH))


if __name__ == '__main__':
    main()
