"""Grid-end check of the top-K loss temperature (reviewer question: tau selected at an end of its grid).

For every MSCA-block cell of Table tab:main whose seed-1 validation choice of tau lies at an end of the pre-specified grid
(SSM tau 0.5 on Baby, Pantry, Scientific, and Sports, PSL tau 0.05 on Scientific and Sports, SL@K tau 0.1 on
Scientific), one seed-1 run uses the next value beyond that end (SSM 1.0, PSL 0.025, SL@K 0.05). The table keeps the
pre-specified grids; this script only reports the change of validation Recall@20 (boundary run minus selected run).
Source: HOST_A <RUN_ROOT_B>/P04_e1e2/e1e2_collect.txt, block "== E2 top-K tau boundary" (written by
collect_e1e2.py in that directory from the best_valid_primed metrics of each result.json, seed 1).
Outputs
  tables/tau_boundary.csv       loss, dataset, tau_sel, vr20_sel, vn20_sel, tau_b, vr20_b, vn20_b, d_vr20
  tables/macros_tauboundary.tex macro names tb... (no digits):
    tbNCells   number of end-selected cells (word)       tbNUp     cells whose boundary run is higher (word)
    tbDiffMin  smallest change (signed, 4 dp)            tbDiffMax largest change (signed, 4 dp)
    tbMaxUp    largest increase (4 dp, no sign)
Usage (repository root): python -s tables/src/build_tau_boundary.py              (ssh to HOST_A)
                         python -s tables/src/build_tau_boundary.py --no-collect (from tables/tau_boundary.csv)
"""
import csv
import re
import subprocess
import sys
from pathlib import Path

TABLES = Path(__file__).resolve().parents[1]
CSV = TABLES / 'tau_boundary.csv'
MAC = TABLES / 'macros_tauboundary.tex'
SRC = '<RUN_ROOT_B>/P04_e1e2/e1e2_collect.txt'
WORDS = 'none one two three four five six seven eight nine ten'.split()
FIELDS = ['loss', 'dataset', 'tau_sel', 'vr20_sel', 'vn20_sel', 'tau_b', 'vr20_b', 'vn20_b', 'd_vr20']


def collect():
    txt = subprocess.run(['ssh', 'HOST_A', f'cat {SRC}'], capture_output=True, text=True, check=True).stdout
    block = txt.split('== E2 top-K tau boundary', 1)[1]
    rows = []
    for ln in block.splitlines():
        m = re.match(r'(\w+)/(\w+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s+([+-][\d.]+)', ln)
        if m:
            rows.append(dict(zip(FIELDS, m.groups())))
    assert rows, 'no E2 rows found'
    for r in rows:   # the printed difference must match the printed values
        assert abs(float(r['vr20_b']) - float(r['vr20_sel']) - float(r['d_vr20'])) < 1e-9, r
    with open(CSV, 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=FIELDS, lineterminator='\n')
        w.writeheader()
        w.writerows(rows)
    return rows


def main():
    if '--no-collect' in sys.argv:
        rows = list(csv.DictReader(open(CSV, newline='', encoding='utf-8')))
    else:
        rows = collect()
    d = [float(r['d_vr20']) for r in rows]
    up = [x for x in d if x > 0]
    fmt = lambda v: f'{v:+.4f}'.replace('-', '$-$')   # noqa: E731
    out = ['% Generated by tables/src/build_tau_boundary.py from tables/tau_boundary.csv (HOST_A ' + SRC + ').',
           '% Do not edit by hand. Seed-1 validation Recall@20 of the run one grid step beyond the selected end value of',
           '% tau minus the selected run, for the MSCA-block top-K cells of Table I selected at a grid end.']
    for k, v in (('tbNCells', WORDS[len(d)]), ('tbNUp', WORDS[len(up)]), ('tbDiffMin', fmt(min(d))),
                 ('tbDiffMax', fmt(max(d))), ('tbMaxUp', f'{max(up):.4f}' if up else '0')):
        out.append(f'\\newcommand{{\\{k}}}{{{v}}}')
    MAC.write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
