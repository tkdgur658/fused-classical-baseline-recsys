def nprime():
    # revision log 18-2 (MES numbers only): the learned ranker of N' is MES on eight datasets (R2NULL3, no MicroLens run).
    # Before 18-2: r2null2.json (E + R + A design, nine datasets) and n3p.json.
    r2 = json.load(open(DATA / 'r2null3.json', encoding='utf-8'))
    n3 = json.load(open(DATA / 'n3p_mes.json', encoding='utf-8'))
    assert n3['source_sha'] == r2['code_sha256']
    for d, v in n3['per_ds'].items():   # the re-drawn intervals reproduce r2null3.json
        assert v['reproduces_r2null3'] and v['W_p'] == r2['per_ds'][d]['W']['p'], d
    w = [(d, v['W']['p']) for d, v in r2['per_ds'].items() if v.get('status') == 'OK' and v.get('W')]
    adj = sigtest.holm([p for _, p in w])
    rows = [dict(family="N' winner test W (permutation, B = 1000)", contrast='validation winner = test winner', a='', b='',
                 dataset=d, metric='agreement', n='', diff='', p=p, m=len(w), p_holm=pa, reject=int(pa <= sigtest.ALPHA),
                 bonferroni_0056=int(p <= 0.05 / 9)) for (d, p), pa in zip(w, adj)]
    keep(rows)
    sig = [r['dataset'] for r in rows if r['reject']]
    mac('sgWNSig', cnt(len(sig)))
    mac('sgWSigDs', phrase([NAME[d] for d in sig]))
    mac('sgWNDs', num_word(len(rows)))
    # 18-2: p-values of the prose (unadjusted permutation p, B = 1000)
    ps_sig = sorted({f"{r['p']:.3f}" for r in rows if r['reject']})
    ps_oth = [r['p'] for r in rows if not r['reject']]
    mac('sgWPSig', ps_sig[0] if len(ps_sig) == 1 else '--')
    mac('sgWNOther', num_word(len(ps_oth)))
    mac('sgWPOtherMin', f'{min(ps_oth):.3f}' if ps_oth else '--')
    mac('sgWPOtherMax', f'{max(ps_oth):.3f}' if ps_oth else '--')
    mac('sgWNotDs', phrase([NAME[r['dataset']] for r in rows if not r['reject']], 'none'))
    mac('sgWNBonf', cnt(sum(r['bonferroni_0056'] for r in rows)))   # preregistered level 0.05/9 of R2NULL2 / R2NULL3
    nn = [(d, v) for d, v in n3['per_ds'].items() if v.get('status') == 'OK']
    adj = sigtest.holm([v['p_n3'] for _, v in nn])
    rows = [dict(family="N' decoy null N3 (one-sided empirical, B = 200)", contrast='g_O above decoy null', a='', b='',
                 dataset=d, metric='g_O', n='', diff=v['g_O'] - v['n3_hi'], p=v['p_n3'], m=len(nn), p_holm=pa,
                 reject=int(pa <= sigtest.ALPHA)) for (d, v), pa in zip(nn, adj)]
    keep(rows)
    sig = [r['dataset'] for r in rows if r['reject']]
    mac('sgNThreeNSig', cnt(len(sig)))
    mac('sgNThreeNDs', num_word(len(rows)))
    mac('sgNThreeNotDs', phrase([NAME[r['dataset']] for r in rows if not r['reject']], 'none'))
    mac('sgNThreeSigDs', phrase([NAME[d] for d in sig]))
    mac('sgNThreePMin', f"{min(v['p_n3'] for _, v in nn):.3f}")
    mac('sgNThreePHolmMax', f"{max(r['p_holm'] for r in rows if r['reject']):.3f}" if sig else '--')


