"""Significance counts of the prose under the single test family (revision log 18-3, 2026-10-16; rule in tables/src/sigtest.py):
two-sided paired t-test over seeds 1-5 (runs of one seed paired), one family = one contrast across the datasets of its
table or figure, Holm over these datasets, alpha 0.05. The per-user headroom N' keeps its permutation (W) and decoy (N3)
nulls, with Holm over datasets in place of the earlier Bonferroni level 0.05/9. Numbers are never typed by hand.

Reads (all local):
  tables/sigtests_table1.csv          (build_table1_main.py)  each row of Table tab:main against Proposed (MES)
  tables/table1_perseed.csv, topk_perseed.csv               top-K losses and neighbor plug-ins against MSCA
  tables/ctrl_perseed.csv             (build_ctrl.py)         contrasts (1), (2), (7), (8), interaction, additive losses
  tables/wdcmp_perseed.csv, mes_perseed.csv                 weight decay (E + R + A and MES with decay against MSCA with decay)
  tables/xre_perseed.csv, mes_perseed.csv, table1_perseed.csv, table2_runs.tsv   other backbones (Table tab:transfer)
  tables/src/data/fusion_cells_9ds_mes.csv                  F against the unfused model, pre-fusion MES - MSCA
  tables/src/data/mesf_hf_verdict.json                       MES-F against MES (+)F
  tables/hyp_nbrpop.csv                                      hit-rate change MSCA -> MES per dataset, row and quintile (post hoc)
  tables/src/data/r2null3.json                               winner test W of N' (permutation p, B = 1000), learned ranker = MES,
                                                             eight datasets (copy of study/results/r2null3.json; revision log 18-2)
  tables/src/data/n3p_mes.json                               decoy null N3 of N' (one-sided empirical p, B = 200; written on
                                                             HOST_A by study/R2NULL3_P18/n3p_mes.py = tables/src/data/n3p_mes.py,
                                                             which re-draws the N3 replicates of r2null3.py and reproduces its
                                                             intervals exactly). Before 18-2: teaser/r2null2.json and n3p.json
                                                             (E + R + A design, nine datasets).
Writes tables/sigtests_counts.csv (every test) and tables/macros_sig.tex (prefix sg).
Usage: python -s tables/src/build_sigcounts.py   (after build_table1_main.py and build_ctrl.py)
"""
import csv
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import sigtest  # noqa: E402
from numwords import num_word  # noqa: E402

T = Path(__file__).resolve().parents[1]
DATA = T / 'src' / 'data'
DS4 = ['baby', 'pantry', 'scientific', 'sports']
NAME = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports', 'clothing': 'Clothing',
        'instruments': 'Instruments', 'arts': 'Arts', 'office': 'Office', 'microlens': 'MicroLens'}
SEEDS = [1, 2, 3, 4, 5]
ALL_ROWS = []
OUT = ['% Generated by tables/src/build_sigcounts.py (revision log 18-3). Do not edit by hand.',
       '% Significance counts: two-sided paired t-test over seeds 1-5, Holm over the datasets of one contrast, alpha 0.05;',
       '% N\' nulls (W permutation, N3 decoy) with Holm over datasets. Every test is listed in tables/sigtests_counts.csv.']


def mac(n, v):
    assert re.fullmatch(r'[A-Za-z]+', n), n
    OUT.append(f'\\newcommand{{\\{n}}}{{{v}}}')


def cnt(k):
    return 'none' if k == 0 else num_word(k)


def phrase(names, none='none of the datasets'):
    if not names:
        return none
    if len(names) == 1:
        return names[0]
    return ', '.join(names[:-1]) + (' and ' if len(names) == 2 else ', and ') + names[-1]


def keep(rows):
    ALL_ROWS.extend(rows)
    return rows


def perseed(path, key, filt=lambda r: True, metric='r20'):
    """{key(r): {seed: value}}"""
    out = {}
    for r in csv.DictReader(open(path, newline='', encoding='utf-8')):
        if filt(r):
            d = out.setdefault(key(r), {})
            s = int(r['seed'])
            assert s not in d, ('duplicate seed', path.name, key(r), s)
            d[s] = float(r[metric])
    return out


# ---------------------------------------------------------------- Table tab:main (from build_table1_main.py)
def table1():
    t1 = list(csv.DictReader(open(T / 'sigtests_table1.csv', encoding='utf-8')))
    for r in t1:
        r['p'], r['p_holm'], r['diff'] = float(r['p']), float(r['p_holm']), float(r['diff'])
        r['reject'] = int(r['reject'])
    keep([dict(r, family='table1 (from sigtests_table1.csv)') for r in t1])

    def get(bb, row, m):
        return {r['dataset']: r for r in t1 if r['contrast'] == f'{bb}: {row} - MES' and r['metric'] == m}
    # unfused gain of MES over the backbone (MES - backbone > 0 <=> backbone - MES < 0)
    for bb, B in (('MSCA', 'Unf'), ('COHESION', 'Coh'), ('SMORE', 'Smo')):
        for m, M in (('r20', ''), ('n20', 'Ndcg')):
            g = get(bb, 'Native', m)
            sig = [d for d in DS4 if g[d]['reject'] and g[d]['diff'] < 0]
            mac(f'sg{B}{M}NSig', cnt(len(sig)))
            mac(f'sg{B}{M}SigDs', phrase([NAME[d] for d in sig]))
    mac('sgUnfNDs', num_word(len(DS4)))
    # MSCA block: MES above every other objective (the eight non-backbone rows)
    others = ['SL@K', 'PSL', 'SSM', 'INA', 'MDVT', 'MG', 'DA-MRS', 'UltraGCN-LI']
    for m, M in (('r20', ''), ('n20', 'Ndcg')):
        all_sig = [d for d in DS4 if all(get('MSCA', o, m)[d]['reject'] and get('MSCA', o, m)[d]['diff'] < 0 for o in others)]
        n_cells = sum(get('MSCA', o, m)[d]['reject'] and get('MSCA', o, m)[d]['diff'] < 0 for o in others for d in DS4)
        mac(f'sgAll{M}NSig', cnt(len(all_sig)))
        mac(f'sgAll{M}SigDs', phrase([NAME[d] for d in all_sig]))
        mac(f'sgAll{M}NCells', str(n_cells))
    mac('sgAllNPairs', str(len(others) * len(DS4)))
    # COHESION / SMORE blocks: columns where MES is significantly above every other row of the block
    tot = 0
    for bb, B in (('COHESION', 'Coh'), ('SMORE', 'Smo')):
        rows = sorted({r['contrast'].split(': ')[1].rsplit(' - MES', 1)[0] for r in t1 if r['contrast'].startswith(bb + ':')})
        cols = [(d, m) for d in DS4 for m in ('r20', 'n20')]
        n = sum(all(get(bb, o, m)[d]['reject'] and get(bb, o, m)[d]['diff'] < 0 for o in rows) for d, m in cols)
        mac(f'sgCs{B}NColsAllSig', cnt(n))
        tot += n
    mac('sgCsNColsAllSig', cnt(tot))


# ---------------------------------------------------------------- top-K losses and neighbor plug-ins against MSCA
def plugins():
    p1 = perseed(T / 'table1_perseed.csv', lambda r: (r['row'], r['dataset']), lambda r: r['backbone'] == 'MSCA')
    p1.update(perseed(T / 'topk_perseed.csv', lambda r: (r['row'], r['dataset']), lambda r: r['backbone'] == 'MSCA'))
    res = {}
    for row in ('SL@K', 'PSL', 'SSM', 'UltraGCN-LI', 'INA'):
        res[row] = {r['dataset']: r for r in keep(sigtest.contrast(
            {d: p1[(row, d)] for d in DS4}, {d: p1[('Native', d)] for d in DS4}, DS4, fam='tab:main MSCA vs backbone',
            name=f'{row} - MSCA', a=row, b='MSCA', metric='r20'))}
    tk = [d for d in DS4 if all(res[k][d]['reject'] and res[k][d]['diff'] < 0 for k in ('SL@K', 'PSL', 'SSM'))]
    mac('sgTkBelowNSig', cnt(len(tk)))
    mac('sgTkBelowSigDs', phrase([NAME[d] for d in tk]))
    # neighbor plug-ins on the datasets of \nbDs (macros_xmask.tex)
    xm = dict(re.findall(r'\\newcommand\{\\(\w+)\}\{(.*)\}', (T / 'macros_xmask.tex').read_text(encoding='utf-8')))
    nbds = [d for d in DS4 if NAME[d] in xm['nbDs']]
    k = sum(res[r][d]['reject'] for r in ('UltraGCN-LI', 'INA') for d in nbds)
    mac('sgNbNSig', cnt(k))
    mac('sgNbNCells', num_word(2 * len(nbds)))


# ---------------------------------------------------------------- controlled variants (ctrl_perseed.csv of build_ctrl.py)
def ctrl():
    V = {}
    for r in csv.DictReader(open(T / 'ctrl_perseed.csv', encoding='utf-8')):
        V.setdefault((r['row'], r['dataset']), {})[int(r['seed'])] = float(r['r20'])

    def fam(a, b, name):
        return {r['dataset']: r for r in keep(sigtest.contrast({d: V[(a, d)] for d in DS4}, {d: V[(b, d)] for d in DS4}, DS4,
                                                                fam='tab:ctrl / Fig. ctrl_forest', name=name, a=a, b=b,
                                                                metric='r20'))}
    out = {}
    out['maskX'] = fam('wo_A1', 'wo_A1_masked', '(1) (E + R) - (E + R, full view)')
    out['maskA'] = fam('XRE', 'wo_masked', '(2) (E + R + A) - (E + R + A, full view)')
    out['dnsbpr'] = fam('mdns', 'mbpr', '(7) (A + masked DNS) - (A + masked BPR)')
    out['entret'] = fam('xeo', 'xto', '(5) (E + A) - (R + A)')
    out['mesfv'] = fam('MES', 'MES_fv', 'E - (E, full view)')   # row E of tab:ctrl (lambda 0.1, K 40) against its full view
    pr = fam('xph', 'XRE', '(E + R + A, history-free probes) - (E + R + A)')
    mac('sgProbeNSig', cnt(sum(pr[d]['reject'] for d in DS4)))
    # interaction: (2) - (1) within each seed = paired t of the two per-seed masking effects
    ia = {d: {s: V[('XRE', d)][s] - V[('wo_masked', d)][s] for s in SEEDS} for d in DS4}
    ib = {d: {s: V[('wo_A1', d)][s] - V[('wo_A1_masked', d)][s] for s in SEEDS} for d in DS4}
    out['inter'] = {r['dataset']: r for r in keep(sigtest.contrast(ia, ib, DS4, fam='tab:ctrl / Fig. ctrl_forest',
                                                                  name='interaction (2) - (1)', a='(2)', b='(1)',
                                                                  metric='r20'))}
    for key, M, sign in (('maskX', 'MaskX', 1), ('maskA', 'MaskA', -1), ('dnsbpr', 'DnsBpr', 1), ('inter', 'Inter', -1),
                         ('entret', 'EntRet', 1), ('mesfv', 'MesFv', 1)):
        sig = [d for d in DS4 if out[key][d]['reject'] and sign * out[key][d]['diff'] > 0]
        mac(f'sg{M}NSig', cnt(len(sig)))
        mac(f'sg{M}SigDs', phrase([NAME[d] for d in sig]))
    # additive top-K losses: below E + R + A, below MSCA, above the replacing loss (Recall@20, 12 dataset-loss pairs)
    n_xre = n_nat = n_rep = 0
    for k in ('ssm', 'psl', 'slk'):
        a = fam(f'add_{k}', 'XRE', f'(8) BPR + mu {k} - (E + R + A)')
        n = fam(f'add_{k}', 'Native', f'BPR + mu {k} - MSCA')
        p = fam(f'add_{k}', f'rep_{k}', f'BPR + mu {k} - {k} replacing BPR')
        n_xre += sum(a[d]['reject'] and a[d]['diff'] < 0 for d in DS4)
        n_nat += sum(n[d]['reject'] and n[d]['diff'] < 0 for d in DS4)
        n_rep += sum(p[d]['reject'] and p[d]['diff'] > 0 for d in DS4)
    mac('sgTopkBelowXreNSig', cnt(n_xre) if n_xre != 12 else 'all 12')
    mac('sgTopkBelowNativeNSig', cnt(n_nat))
    mac('sgTopkAboveRepNSig', cnt(n_rep))
    # cross-check against ctrl_contrasts.csv (same runs, same rule)
    cc = {(r['family'], r['a'], r['b'], r['dataset'], r['metric']): r for r in csv.DictReader(open(T / 'ctrl_contrasts.csv', encoding='utf-8'))
          if r['kind'] == 'family'}
    for (f, a, b) in (('maskX', 'wo_A1', 'wo_A1_masked'), ('maskA', 'XRE', 'wo_masked'), ('dnsbpr', 'mdns', 'mbpr'), ('entret', 'xeo', 'xto')):
        for d in DS4:
            ref, me = cc[(f, a, b, d, 'R@20')], out[f][d]
            assert abs(float(ref['p_holm']) - me['p_holm']) < 1e-5 and int(ref['holm_reject']) == me['reject'], (f, d)
    return out


# ---------------------------------------------------------------- weight decay
def weight_decay():
    W = perseed(T / 'wdcmp_perseed.csv', lambda r: (r['arm'], r['dataset']))
    M = perseed(T / 'mes_perseed.csv', lambda r: (r['row'], r['dataset']), lambda r: r['backbone'] == 'MSCA' and r['row'] in ('MES_wd',))
    # 18-2: MES without weight decay against MSCA with it (row MES of mes_perseed.csv = the validation-selected MES)
    M.update(perseed(T / 'mes_perseed.csv', lambda r: ('MES_wd0', r['dataset']), lambda r: r['backbone'] == 'MSCA' and r['row'] == 'MES'))
    for a, src, M_ in (('XRE_wd', W, 'Wd'), ('MES_wd', M, 'WdMes'), ('XRE_wd0', W, 'WdOvt'), ('MES_wd0', M, 'WdMesOvt')):
        f = {r['dataset']: r for r in keep(sigtest.contrast({d: src[(a, d)] for d in DS4}, {d: W[('MSCA_wd', d)] for d in DS4},
                                                           DS4, fam='weight decay', name=f'{a} - MSCA_wd', a=a, b='MSCA_wd',
                                                           metric='r20'))}
        sig = [d for d in DS4 if f[d]['reject'] and f[d]['diff'] > 0]
        mac(f'sg{M_}NSig', cnt(len(sig)))
        mac(f'sg{M_}SigDs', phrase([NAME[d] for d in sig]))
        if M_ == 'WdMesOvt':   # 18-2: a significant loss is reported as well
            mac(f'sg{M_}NSigDown', cnt(sum(f[d]['reject'] and f[d]['diff'] < 0 for d in DS4)))


# ---------------------------------------------------------------- other backbones (Table tab:transfer, three datasets)
def transfer():
    ds3 = ['baby', 'pantry', 'scientific']
    X = perseed(T / 'xre_perseed.csv', lambda r: (r['backbone'], r['row'], r['dataset']))
    Mx = perseed(T / 'mes_perseed.csv', lambda r: (r['backbone'], r['row'], r['dataset']), lambda r: r['row'] == 'MES')
    nat = perseed(T / 'table1_perseed.csv', lambda r: (r['backbone'], r['dataset']), lambda r: r['row'] == 'Native')
    # MENTOR backbone row of the transfer table = the MENTOR runs of Table tab:sota (table2_runs.tsv, chosen runs)
    for r in csv.DictReader(open(T / 'table2_runs.tsv', newline='', encoding='utf-8'), delimiter='\t'):
        if r['model'] == 'MENTOR' and r['chosen'] == '1' and r['dataset'] in ds3:
            nat.setdefault(('MENTOR', r['dataset']), {})[int(r['seed'])] = float(r['test_r20'])
    tex = (T / 'appendix_transfer.tex').read_text(encoding='utf-8')
    mes_below, mes_above, mes_sig = [], [], 0   # 18-2: cells where the mean Recall@20 of MES lies below / above the backbone
    for bb in ('MENTOR', 'FREEDOM', 'MMGCN'):
        # backbone row: the printed Backbone (X) values must equal the per-seed means used here
        base = {d: nat.get((bb, d)) or X[(bb, 'Native', d)] for d in ds3}
        printed = re.search(r'Backbone \(' + bb + r'\) & ([^\n]*)\\\\', tex).group(1).split(' & ')[0::2]
        for d, pv in zip(ds3, printed):
            assert abs(sum(base[d].values()) / len(base[d]) - float(re.sub(r'[^0-9.]', '', pv))) < 5e-5, (bb, d, pv)
        for row, src, R in (('XRE', X, 'Xre'), ('wo_masked', X, 'Fv'), ('MES', Mx, 'Mes')):
            f = {r['dataset']: r for r in keep(sigtest.contrast({d: src[(bb, row, d)] for d in ds3}, base, ds3,
                                                               fam='tab:transfer', name=f'{bb}: {row} - backbone', a=row,
                                                               b=bb, metric='r20'))}
            up = [d for d in ds3 if f[d]['reject'] and f[d]['diff'] > 0]
            down = [d for d in ds3 if f[d]['reject'] and f[d]['diff'] < 0]
            B = bb[0] + bb[1:].lower()
            mac(f'sgTr{R}{B}NUp', cnt(len(up)))
            mac(f'sgTr{R}{B}UpDs', phrase([NAME[d] for d in up]))
            mac(f'sgTr{R}{B}NDown', cnt(len(down)))
            if row == 'MES':
                # printed MES row of the transfer table must equal the per-seed means used here
                pm = re.search(r'Backbone: ' + bb + r'[^\n]*\n(?:[^\n]*\n)*?MES & ([^\n]*)\\\\', tex).group(1).split(' & ')[0::2]
                for d, pv in zip(ds3, pm):
                    assert abs(f[d]['mean_a'] - float(re.sub(r'[^0-9.]', '', pv))) < 5e-5, (bb, d, pv)
                mes_below += [(bb, d) for d in ds3 if f[d]['diff'] < 0]
                mes_above += [(bb, d) for d in ds3 if f[d]['diff'] > 0]
                mes_sig += sum(f[d]['reject'] for d in ds3)
    mac('sgTrNDs', num_word(len(ds3)))
    # e.g. "MENTOR on Baby and Pantry, FREEDOM on Baby, and MMGCN on Pantry"
    grp = [f"{bb} on {phrase([NAME[d] for b2, d in mes_below if b2 == bb])}" for bb in ('MENTOR', 'FREEDOM', 'MMGCN')
           if any(b2 == bb for b2, _ in mes_below)]
    mac('sgTrMesBelowCells', phrase(grp, 'none'))
    mac('sgTrMesNBelow', cnt(len(mes_below)))
    mac('sgTrMesNAbove', cnt(len(mes_above)))
    mac('sgTrMesNCells', num_word(len(mes_below) + len(mes_above)))
    mac('sgTrMesNSig', cnt(mes_sig))


# ---------------------------------------------------------------- fused baseline F
def fusion():
    cell = {}
    for r in csv.DictReader(open(DATA / 'fusion_cells_9ds_mes.csv', newline='', encoding='utf-8')):
        if not r['fused_r20'] or r.get('gate_ok', '1') != '1':
            continue
        k = (r['model'], r['dataset'], int(r['seed']))
        if k in cell:
            assert cell[k] == (float(r['base_r20']), float(r['fused_r20'])), ('conflicting duplicate', k)
        cell[k] = (float(r['base_r20']), float(r['fused_r20']))
    models = sorted({m for m, _, _ in cell})
    n_pairs = n_sig = 0
    n_sig4 = n_pairs4 = 0
    for m in models:
        ds = sorted({d for mm, d, _ in cell if mm == m})
        fused = {d: {s: cell[(m, d, s)][1] for (mm, dd, s) in cell if mm == m and dd == d} for d in ds}
        base = {d: {s: cell[(m, d, s)][0] for (mm, dd, s) in cell if mm == m and dd == d} for d in ds}
        f = keep(sigtest.contrast(fused, base, ds, fam='F (Fig. 1, Tables sota and fuse_added)', name=f'{m} (+)F - {m}',
                                  a=f'{m} (+)F', b=m, metric='r20'))
        n_pairs += len(f)
        n_sig += sum(r['reject'] and r['diff'] > 0 for r in f)
        n_pairs4 += sum(r['dataset'] in DS4 for r in f)
        n_sig4 += sum(r['reject'] and r['diff'] > 0 and r['dataset'] in DS4 for r in f)
    mac('sgFNPairs', str(n_pairs))
    mac('sgFNSig', str(n_sig))
    mac('sgFNPairsFour', str(n_pairs4))
    mac('sgFNSigFour', str(n_sig4))
    # pre-fusion margin of MSCA + MES over MSCA in the fusion runs (datasets with five seeds of both rows)
    both = [d for d in DS4 + ['clothing', 'instruments'] if all((m, d, s) in cell for m in ('MSCA', 'MSCA+MES') for s in SEEDS)]
    f = {r['dataset']: r for r in keep(sigtest.contrast({d: {s: cell[('MSCA+MES', d, s)][0] for s in SEEDS} for d in both},
                                                       {d: {s: cell[('MSCA', d, s)][0] for s in SEEDS} for d in both}, both,
                                                       fam='fusion runs, unfused', name='MSCA + MES - MSCA (pre-fusion)',
                                                       a='MSCA+MES', b='MSCA', metric='r20'))}
    sig = [d for d in both if f[d]['reject'] and f[d]['diff'] > 0]
    mac('sgPreNSig', cnt(len(sig)))
    mac('sgPreSigDs', phrase([NAME[d] for d in sig]))
    mac('sgPreNDs', num_word(len(both)))
    mac('sgPreNSigFour', cnt(sum(d in DS4 for d in sig)))
    mac('sgPreNSigAdded', cnt(sum(d not in DS4 for d in sig)))
    # fused margin, recomputed with sigtest (must equal build_fusion_test.py)
    g = keep(sigtest.contrast({d: {s: cell[('MSCA+MES', d, s)][1] for s in SEEDS} for d in both},
                              {d: {s: cell[('MSCA', d, s)][1] for s in SEEDS} for d in both}, both,
                              fam='fusion runs, fused (= build_fusion_test.py)', name='MSCA + MES (+)F - MSCA (+)F',
                              a='MSCA+MES (+)F', b='MSCA (+)F', metric='r20'))
    ft = json.load(open(DATA / 'fusion_test.json', encoding='utf-8'))
    for r, q in zip(g, ft['family_all']):
        assert r['dataset'] == q['ds'] and abs(r['p'] - q['p']) < 1e-9 and abs(r['p_holm'] - q['p_holm']) < 1e-9
    mac('sgFtNSigFour', cnt(sum(r['reject'] for r in g if r['dataset'] in DS4)))   # the four datasets of Table tab:sota


# ---------------------------------------------------------------- MES-F against MES (+)F
def mesf():
    v = json.load(open(DATA / 'mesf_hf_verdict.json', encoding='utf-8'))
    ps = v['per_seed']
    to = lambda k: {d: dict(zip(SEEDS, ps[k][d])) for d in DS4}   # noqa: E731
    f = keep(sigtest.contrast(to('mesf'), to('mes_f'), DS4, fam='MES-F', name='MES-F - MES (+)F', a='MES-F', b='MES (+)F', metric='r20'))
    mac('sgMfVsMesNSig', cnt(sum(r['reject'] and r['diff'] < 0 for r in f)))
    g = keep(sigtest.contrast(to('mesf'), to('msca_f'), DS4, fam='MES-F (= mesf_verdict.py)', name='MES-F - MSCA (+)F',
                              a='MES-F', b='MSCA (+)F', metric='r20'))
    for r, q in zip(g, v['rows']):   # the preregistered verdict uses the same rule
        assert r['dataset'] == q['ds'] and abs(r['p'] - q['p']) < 1e-9 and abs(r['p_holm'] - q['p_holm']) < 1e-9, (r, q)
    mac('sgMfBelowNSig', cnt(sum(r['reject'] and r['diff'] < 0 for r in g)))


# ---------------------------------------------------------------- hit-rate change by neighbor row and popularity quintile (post hoc)
def nbrpop():
    H = {}
    for r in csv.DictReader(open(T / 'hyp_nbrpop.csv', encoding='utf-8')):
        if r['graph'] != 'cooc':
            continue
        H.setdefault((r['link'], r['quintile'], r['dataset']), {})[int(r['seed'])] = (float(r['hit20_a']), float(r['hit20_b']))
    res = {}
    for link in ('nbr', 'non'):
        for q in ('q1', 'q2', 'q3', 'q4', 'q5'):
            a = {d: {s: H[(link, q, d)][s][1] for s in SEEDS} for d in DS4}   # MES
            b = {d: {s: H[(link, q, d)][s][0] for s in SEEDS} for d in DS4}   # MSCA
            res[(link, q)] = {r['dataset']: r for r in keep(sigtest.contrast(
                a, b, DS4, fam='Fig. nbrpop (post hoc)', name=f'MES - MSCA hit@20, {link} {q}', a='MES', b='MSCA', metric='hit20'))}
    up_nbr = sum(res[('nbr', q)][d]['reject'] and res[('nbr', q)][d]['diff'] > 0 for q in ('q1', 'q2', 'q3', 'q4', 'q5') for d in DS4)
    mac('sgNpNbrUpNSig', cnt(up_nbr))
    lose = sum(res[(l, q)][d]['reject'] and res[(l, q)][d]['diff'] < 0 for l in ('nbr', 'non') for q in ('q3', 'q4') for d in DS4)
    mac('sgNpMidDownNSig', cnt(lose))
    mid_up = sum(res[('nbr', q)][d]['reject'] and res[('nbr', q)][d]['diff'] > 0 for q in ('q3', 'q4') for d in DS4)
    mac('sgNpMidNbrUpNSig', cnt(mid_up))
    # Q5: neighbor gain minus other-target gain within each seed
    ga = {d: {s: H[('nbr', 'q5', d)][s][1] - H[('nbr', 'q5', d)][s][0] for s in SEEDS} for d in DS4}
    gb = {d: {s: H[('non', 'q5', d)][s][1] - H[('non', 'q5', d)][s][0] for s in SEEDS} for d in DS4}
    f = keep(sigtest.contrast(ga, gb, DS4, fam='Fig. nbrpop (post hoc)', name='Q5: neighbor gain - other gain', a='nbr', b='non', metric='hit20'))
    mac('sgNpQFiveNSig', cnt(sum(r['reject'] and r['diff'] > 0 for r in f)))


