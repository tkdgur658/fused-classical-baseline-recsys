"""Supplementary table of the post hoc complementarity and stratified decomposition (revision log 19, 2026-10-16):
tables/appendix_complement.tex (tab:complement). Same input and checks as build_gs5_macros.py (tables/src/data/gs5_stats.json,
re-tested with sigtest.py). Per dataset: share of the classical top-20 test hits that MSCA + MES misses, share of that missed part
that the fusion F recovers, and the stratified pre-fusion MSCA + MES minus MSCA differences with p and Holm-adjusted p.
Numbers are never typed by hand.  Usage: python tables/src/build_table_complement.py
"""
from pathlib import Path

from build_gs5_macros import DS, ROOT, load, count_phrase, sgn
from numwords import num_word

NAMES = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports'}


def fp(p):
    return f'{p:.3f}'


def main():
    J = load()
    n = len(DS)
    nsig = {k: sum(J[d][k]['reject'] for d in DS) for k in ('A', 'B', 'overall', 'AmB')}
    phmin_amb = min(J[d]['AmB']['p_holm'] for d in DS)
    L = ['% Generated by tables/src/build_table_complement.py from tables/src/data/gs5_stats.json. Do not edit numbers by hand.',
         '\\begin{table*}[t]',
         '\\caption{Post hoc split of the test targets by the classical ranker of F, on the four tuned datasets. A target is '
         'classical-hit when the classical combination of F ranks it within the top 20 and classical-miss otherwise. '
         'Missed gives the share of the classical-hit targets that MSCA + MES leaves outside its own top 20, and Recovered the '
         'share of these that F brings back, both as means over seeds 1--5. The remaining columns give the Recall@20 difference of '
         'MSCA + MES over MSCA before fusion that each stratum contributes, in units of the user-weighted target mass, thus the two '
         'strata add up to the total difference, with the unadjusted $p$ of the two-sided paired $t$-test over seeds 1--5 and '
         'the Holm-adjusted $p_H$ over the four datasets of each stratum. After Holm correction, the difference is significant '
         f'on {count_phrase(nsig["A"], n)} datasets for classical-hit targets, on {count_phrase(nsig["B"], n)} for classical-miss '
         f'targets, and on {count_phrase(nsig["overall"], n)} in total, and the contrast of the two strata is significant on '
         f'{count_phrase(nsig["AmB"], n)} (smallest $p_H$ {fp(phmin_amb)}). The split was made after the results were known.}}',
         '\\label{tab:complement}', '\\centering', '\\footnotesize', '\\setlength{\\tabcolsep}{4pt}',
         '\\begin{tabular}{lrrrrrrrrrr}', '\\toprule',
         ' & \\multicolumn{2}{c}{Complementarity (\\%)} & \\multicolumn{3}{c}{Classical-hit targets} & '
         '\\multicolumn{3}{c}{Classical-miss targets} & \\multicolumn{2}{c}{Total} \\\\',
         '\\cmidrule(lr){2-3}\\cmidrule(lr){4-6}\\cmidrule(lr){7-9}\\cmidrule(lr){10-11}',
         'Dataset & Missed & Recovered & $\\Delta$ & $p$ & $p_H$ & $\\Delta$ & $p$ & $p_H$ & $\\Delta$ & $p_H$ \\\\', '\\midrule']
    for d in DS:
        j = J[d]
        L.append(f"{NAMES[d]} & {100 * j['mes_conly_share']:.1f} & {100 * j['mes_capture']:.1f} & "
                 f"{sgn(j['A']['diff'])} & {fp(j['A']['p'])} & {fp(j['A']['p_holm'])} & "
                 f"{sgn(j['B']['diff'])} & {fp(j['B']['p'])} & {fp(j['B']['p_holm'])} & "
                 f"{sgn(j['overall']['diff'])} & {fp(j['overall']['p_holm'])} \\\\")
    L += ['\\bottomrule', '\\end{tabular}', '\\end{table*}']
    (ROOT / 'appendix_complement.tex').write_text('\n'.join(L) + '\n', encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
