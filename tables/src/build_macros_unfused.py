"""Build tables/macros_unfused.tex: the unfused Recall@20 gain of MSCA + MES over MSCA on the four tuned datasets of
Table tab:sota, read from the per-seed sources of that table (tables/table1_perseed.csv, MSCA row 'Native';
tables/mes_perseed.csv, MSCA row 'MES'), as the difference of the unrounded five-seed means.
Added 2026-10-16 (revision log 14-c). Numbers are never typed by hand.
Macros: \\tOneGainLo, \\tOneGainHi (unsigned, four decimals), \\tOneGainList (Baby/Pantry/Scientific/Sports, signed).
Usage: python tables/src/build_macros_unfused.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATASETS = ['baby', 'pantry', 'scientific', 'sports']
BS = chr(92)


def means(path, row):
    acc = {}
    with open(path, newline='', encoding='utf-8') as f:
        for r in csv.DictReader(f):
            if r['backbone'] == 'MSCA' and r['row'] == row and r['dataset'] in DATASETS:
                acc.setdefault(r['dataset'], {})[int(r['seed'])] = float(r['r20'])
    for d in DATASETS:
        assert sorted(acc[d]) == [1, 2, 3, 4, 5], (path, row, d, sorted(acc.get(d, {})))
    return {d: sum(acc[d].values()) / 5 for d in DATASETS}


def main():
    base = means(ROOT / 'table1_perseed.csv', 'Native')
    mes = means(ROOT / 'mes_perseed.csv', 'MES')
    gain = {d: mes[d] - base[d] for d in DATASETS}
    assert all(g > 0 for g in gain.values()), gain
    lo, hi = min(gain.values()), max(gain.values())
    for d in DATASETS:
        print(f'{d}: MSCA {base[d]:.5f} MES {mes[d]:.5f} gain {gain[d]:+.5f}')
    lines = ['% Generated by tables/src/build_macros_unfused.py from table1_perseed.csv and mes_perseed.csv. Do not edit by hand.',
             BS + 'newcommand{' + BS + 'tOneGainLo}{' + f'{lo:.4f}' + '}',
             BS + 'newcommand{' + BS + 'tOneGainHi}{' + f'{hi:.4f}' + '}',
             BS + 'newcommand{' + BS + 'tOneGainList}{' + '/'.join(f'{gain[d]:+.4f}' for d in DATASETS) + '}']
    # revision log 32 (decision ): the unfused gains that lie inside the equivalence margin of the fused contrast (TOST margin 0.002, macros_msca10.tex xnMargin)
    import re
    margin = float(re.search(r'xnMargin\}\{([0-9.]+)\}', (ROOT / 'macros_msca10.tex').read_text(encoding='utf-8')).group(1))
    nm = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports'}
    inside = [d for d in DATASETS if gain[d] < margin]
    sg = lambda x: f'{x:+.4f}'.replace('+', '$+$').replace('-', '$-$')
    j = lambda xs: xs[0] if len(xs) == 1 else (' and '.join(xs) if len(xs) == 2 else ', '.join(xs[:-1]) + ', and ' + xs[-1])
    lines += [BS + 'newcommand{' + BS + 'tOneGainBelowDs}{' + j([nm[d] for d in inside]) + '}',
              BS + 'newcommand{' + BS + 'tOneGainBelowList}{' + j([sg(gain[d]) for d in inside]) + '}', '']
    (ROOT / 'macros_unfused.tex').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print('range', f'{lo:.4f}', f'{hi:.4f}')


if __name__ == '__main__':
    main()
