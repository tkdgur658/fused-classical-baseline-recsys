"""G-S5 macros (revision log 19, 2026-10-16): tables/macros_gs5.tex (prefix gs). Post hoc stratified decomposition of the pre-fusion
advantage of MSCA + MES over MSCA: classical-hit targets (rank_C <= 20) against classical-miss targets (rank_C > 20).
Input: tables/src/data/gs5_stats.json (HOST_A study/MESC/gate_s5/gs5_stats.json from code/mesc_gs5_stats.py, copy kept in
tables/src/data/gs5_stats_source.py; CPU only, read-only inputs study/MESC/gate/dumps of the existing fusion checkpoints,
4 tuned datasets x seeds 1-5). The per-seed differences stored in the file are re-tested here with sigtest.py (two-sided paired t,
Holm over the four datasets of each stratum) and asserted equal to the stored p and p_holm, so the printed counts follow the one
test family of the manuscript. Numbers are never typed by hand.
Usage: python tables/src/build_gs5_macros.py
"""
import json
from pathlib import Path

import sigtest
from numwords import num_word

ROOT = Path(__file__).resolve().parents[1]
DS = ['baby', 'pantry', 'scientific', 'sports']


def sgn(x, nd=4):
    return f'$-${abs(x):.{nd}f}' if round(x, nd) < 0 else f'$+${x:.{nd}f}'


def join(xs):
    xs = list(xs)
    return xs[0] if len(xs) == 1 else (' and '.join(xs) if len(xs) == 2 else ', '.join(xs[:-1]) + ', and ' + xs[-1])


def count_phrase(k, n):
    """k of n datasets in prose: 'none of the four' is avoided; zero is written 'zero of four'."""
    return 'all ' + num_word(n) if k == n else f'{num_word(k)} of {num_word(n)}'


def load():
    J = json.load(open(ROOT / 'src' / 'data' / 'gs5_stats.json', encoding='utf-8'))
    # re-test the stored per-seed differences against zero (paired t of the two models equals the one-sample t of the difference)
    for key in ('A', 'B', 'overall', 'AmB'):
        res = [sigtest.paired(J[d][key]['per_seed'], [0.0] * 5) for d in DS]
        sigtest.family(res)
        for d, r in zip(DS, res):
            s = J[d][key]
            assert abs(r['diff'] - s['diff']) < 1e-12 and abs(r['p'] - s['p']) < 1e-9 and abs(r['p_holm'] - s['p_holm']) < 1e-9, (d, key)
            assert int(r['reject']) == s['reject'], (d, key)
    for d in DS:
        assert abs(J[d]['A']['diff'] + J[d]['B']['diff'] - J[d]['overall']['diff']) < 1e-12     # the strata add up
        assert abs(J[d]['share_A'] + J[d]['share_B'] - 1) < 1e-12
    return J


def main():
    J = load()
    n = len(DS)
    nsig = {k: sum(J[d][k]['reject'] for d in DS) for k in ('A', 'B', 'overall', 'AmB')}
    pmin = {k: min(J[d][k]['p'] for d in DS) for k in ('A', 'B', 'overall', 'AmB')}
    phmin = {k: min(J[d][k]['p_holm'] for d in DS) for k in ('A', 'B', 'overall', 'AmB')}
    shA = [100 * J[d]['share_A'] for d in DS]
    shB = [100 * J[d]['share_B'] for d in DS]
    hit = [100 * J[d]['massA'] for d in DS]
    miss = [100 * J[d]['mes_conly_share'] for d in DS]
    cap = [100 * J[d]['mes_capture'] for d in DS]
    over = sum(1 for x in shA if x > 100)
    assert over == sum(1 for d in DS if J[d]['B']['diff'] < 0)          # the prose ties shares above 100% to a negative classical-miss difference
    pos_A = sum(1 for d in DS if J[d]['A']['diff'] > 0)
    M = {
        'gsNDs': num_word(n),
        'gsDiffA': join(sgn(J[d]['A']['diff']) for d in DS),
        'gsDiffB': join(sgn(J[d]['B']['diff']) for d in DS),
        'gsDiffAll': join(sgn(J[d]['overall']['diff']) for d in DS),
        'gsNPosA': count_phrase(pos_A, n),
        'gsNSigA': count_phrase(nsig['A'], n), 'gsNSigB': count_phrase(nsig['B'], n),
        'gsNSigAll': count_phrase(nsig['overall'], n), 'gsNSigAmB': count_phrase(nsig['AmB'], n),
        'gsPMinA': f'{pmin["A"]:.3f}', 'gsPMinB': f'{pmin["B"]:.3f}', 'gsPMinAll': f'{pmin["overall"]:.3f}',
        'gsPHolmMinA': f'{phmin["A"]:.3f}', 'gsPHolmMinB': f'{phmin["B"]:.3f}', 'gsPHolmMinAmB': f'{phmin["AmB"]:.3f}',
        'gsShareALo': f'{min(shA):.0f}', 'gsShareAHi': f'{max(shA):.0f}',
        'gsShareBLo': f'{min(shB):.0f}', 'gsShareBHi': f'{max(shB):.0f}',
        'gsNShareOver': num_word(over),
        'gsHitLo': f'{min(hit):.1f}', 'gsHitHi': f'{max(hit):.1f}',
        'gsMissLo': f'{min(miss):.0f}', 'gsMissHi': f'{max(miss):.0f}',
        'gsCapLo': f'{min(cap):.0f}', 'gsCapHi': f'{max(cap):.0f}',
    }
    L = ['% Generated by tables/src/build_gs5_macros.py from tables/src/data/gs5_stats.json. Do not edit by hand.']
    L += [f'\\newcommand{{\\{k}}}{{{v}}}' for k, v in M.items()]
    (ROOT / 'macros_gs5.tex').write_text('\n'.join(L) + '\n', encoding='utf-8')
    print('\n'.join(f'{k} = {v}' for k, v in M.items()))
    print('n significant (Holm over datasets):', nsig, 'min p:', pmin, 'min p_holm:', phmin)


if __name__ == '__main__':
    main()
