"""revision log 18-2 (MES numbers only, author decision 1): post-hoc check whether users with short histories gain most from MES.
Reads tables/src/data/hyp_strat_hist_mes.csv (MESCKPT U3: MSCA = arm native, MES = arm mes, same seed, seeds 1-5, bins le7 =
at most seven training interactions and ge8 = eight or more). Relative gain per seed = 100 (MES - MSCA) / MSCA of the bin.
Counts the datasets where the mean relative gain of le7 exceeds that of ge8, per metric, and tests le7 gain - ge8 gain with
the single test family of tables/src/sigtest.py (paired t over seeds 1-5, Holm over the four datasets).
The mean relative gains must equal \\hzHistRecRel{LeSeven,GeEight}<DS> of tables/macros_hyp_strathist_mes.tex (one decimal).
Writes tables/macros_strathist_mes_count.tex (prefix shm). Numbers are never typed by hand.
Usage: python -s tables/src/build_strathist_mes_count.py
"""
import csv
import re
import statistics as st
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import sigtest  # noqa: E402
from numwords import num_word  # noqa: E402

T = Path(__file__).resolve().parents[1]
SRC = T / 'src' / 'data' / 'hyp_strat_hist_mes.csv'
DS = ['baby', 'pantry', 'scientific', 'sports']
NAME = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports'}
SEEDS = [1, 2, 3, 4, 5]


def phrase(names, none='none of the datasets'):
    if not names:
        return none
    if len(names) == 1:
        return names[0]
    return ', '.join(names[:-1]) + (' and ' if len(names) == 2 else ', and ') + names[-1]


def cnt(k):
    return 'none' if k == 0 else num_word(k)


def main():
    V = {}
    for r in csv.DictReader(open(SRC, encoding='utf-8')):
        V[(r['dataset'], r['arm'], int(r['seed']), r['bin'])] = (float(r['recall20']), float(r['ndcg20']))
    ref = dict(re.findall(r'\\newcommand\{\\(\w+)\}\{(.*)\}', (T / 'macros_hyp_strathist_mes.tex').read_text(encoding='utf-8')))
    out = ['% Generated by tables/src/build_strathist_mes_count.py from tables/src/data/hyp_strat_hist_mes.csv (MESCKPT U3, MES).',
           '% Post hoc: relative gain of MES over MSCA for users with at most seven (le7) against eight or more (ge8) training',
           '% interactions; tests le7 gain - ge8 gain, paired t over seeds 1-5, Holm over the four datasets (tables/src/sigtest.py).']
    for m, M, key in ((0, 'Rec', 'Rec'), (1, 'Ndcg', 'Ndcg')):
        rel = {b: {d: {s: 100 * (V[(d, 'mes', s, b)][m] - V[(d, 'native', s, b)][m]) / V[(d, 'native', s, b)][m] for s in SEEDS}
                   for d in DS} for b in ('le7', 'ge8')}
        for d in DS:
            for b, B in (('le7', 'LeSeven'), ('ge8', 'GeEight')):
                mean = st.mean(rel[b][d].values())
                printed = float(ref[f'hzHist{key}Rel{B}{NAME[d]}'])
                assert abs(round(mean, 1) - printed) < 0.051, (M, d, b, mean, printed)
        res = sigtest.contrast(rel['le7'], rel['ge8'], DS, fam='supp: history length (post hoc)',
                               name='MES gain le7 - MES gain ge8', a='le7', b='ge8', metric=M)
        short = [r['dataset'] for r in res if r['diff'] > 0]
        sig = [r['dataset'] for r in res if r['reject'] and r['diff'] > 0]
        sig_rev = [r['dataset'] for r in res if r['reject'] and r['diff'] < 0]
        out += [f'\\newcommand{{\\shm{M}NShort}}{{{cnt(len(short))}}}',
                f'\\newcommand{{\\shm{M}ShortDs}}{{{phrase([NAME[d] for d in short])}}}',
                f'\\newcommand{{\\shm{M}NSig}}{{{cnt(len(sig))}}}',
                f'\\newcommand{{\\shm{M}NSigRev}}{{{cnt(len(sig_rev))}}}']
        print(M, [(r['dataset'], round(r['diff'], 2), round(r['p'], 4), round(r['p_holm'], 4)) for r in res])
    (T / 'macros_strathist_mes_count.tex').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
