"""Prose macros of the cold-target paragraph (Section IV-B, C analysis) and of the E + R + A routing paragraph of the
supplement (revision log 18-1, 2026-10-16): tables/macros_coldroute.tex (prefixes cc, re). Numbers are never typed by hand.

Inputs (copies of HOST_A result files, sha256 in revision log 18-1)
  tables/src/data/c1.json   <RUN_ROOT>/COLD/results/c1.json (c1.py, code sha 9e251da0): per model x dataset x seed hits of test
                            targets with zero training degree, tie-aware hitT@20, ratio = hits / random hits; judge.main per
                            model with its group (learned, classic, fill, ...), diag.<ds>.n_cold
  tables/src/data/r2s1.json <RUN_ROOT>/R2/results/r2s1.json (E + R + A as the learned ranker, nine datasets): g_O (oracle
                            headroom), g_F (validation-selected static z-fusion), g_router (activity-quintile router)
  tables/src/data/r2z.json  <RUN_ROOT>/R2/results/r2z.json: test AUROC of eight structural user properties
Usage: python tables/src/build_coldroute_macros.py
"""
import json
from pathlib import Path

from numwords import num_word

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'src' / 'data'
DS9 = ['baby', 'pantry', 'scientific', 'sports', 'clothing', 'instruments', 'arts', 'office', 'microlens']
FOUR = ['baby', 'pantry', 'scientific', 'sports']
NAMES = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports', 'clothing': 'Clothing',
         'instruments': 'Instruments', 'arts': 'Arts', 'office': 'Office', 'microlens': 'MicroLens'}
LAB = {'lightgcn': 'LightGCN', 'native': 'MSCA', 'mes': 'MES', 'xre': 'E + R + A',
       'freedom': 'FREEDOM', 'lgmrec': 'LGMRec', 'mentor': 'MENTOR', 'smore': 'SMORE', 'cohesion': 'COHESION',
       'pgl': 'PGL', 'diffmm': 'DiffMM'}


# revision log 33: names in the main text (MES is read as MSCA + MES there, E + R + A is not defined in the main text)
MAIN_NAME = {'mes': 'MSCA + MES', 'xre': 'the earlier MSCA design of supplementary Section~\\ref{supp:ctrl}'}


def join(xs):
    xs = list(xs)
    if not xs:
        return 'none'
    return xs[0] if len(xs) == 1 else (' and '.join(xs) if len(xs) == 2 else ', '.join(xs[:-1]) + ', and ' + xs[-1])


def pct(x):
    return f'{100 * x:.1f}'


def main():
    c1 = json.load(open(DATA / 'c1.json', encoding='utf-8'))
    J = c1['judge']['main']
    ncold = {d: c1['diag'][d]['n_cold'] for d in DS9}
    # revision log 18-F: run xretn of c1 has no code definition, thus it is left out (author, as in Table tab:neardup)
    learned = [m for m, v in J.items() if v['group'] == 'learned' and m != 'xretn']
    assert set(learned) == set(LAB), learned
    cov = {m: [d for d in DS9 if d in J[m]['per_ds']] for m in learned}
    exc = {}                                                    # dataset -> [(model, ratio, seeds with hits)]
    for m in learned:
        for d in cov[m]:
            p = J[m]['per_ds'][d]
            if p['hits_mean'] > 0:
                nh = sum(1 for s in c1['cells'][m][d].values() if s['hits'] > 0)
                exc.setdefault(d, []).append((m, p['ratio_mean'], nh, p['n_seeds']))
    allhit = {d: [e for e in v if e[2] == e[3]] for d, v in exc.items()}
    somehit = {d: [e for e in v if e[2] < e[3]] for d, v in exc.items()}
    full9 = [m for m in learned if len(cov[m]) == 9 and m not in {e[0] for v in exc.values() for e in v}]
    ik = J['iknn_txt']['per_ds']
    ik_pos = [d for d in DS9 if ik[d]['ratio_mean'] > 0]
    ik_all5 = all(ik[d]['seeds_hold'] == ik[d]['n_seeds'] for d in ik_pos)
    ik_zero = [d for d in DS9 if ik[d]['ratio_mean'] == 0]
    exc_ratios = [e[1] for e in allhit.get('clothing', [])]   # Clothing: models that hit in every seed
    M = ['% Generated by tables/src/build_coldroute_macros.py from tables/src/data/c1.json, r2s1.json, r2z.json. Do not edit by hand.',
         f'% cold targets per dataset: ' + ', '.join(f'{d} {ncold[d]}' for d in DS9),
         f'% learned-model hits on cold targets (model, ratio, seeds with hits / seeds): {exc}',
         f'\\newcommand{{\\ccNMin}}{{{num_word(min(ncold.values()))}}}',
         f'\\newcommand{{\\ccNMax}}{{{num_word(max(ncold.values()))}}}',
         f'\\newcommand{{\\ccNLearned}}{{{num_word(len(learned))}}}',
         # revision log 33 (review 3, minor): the sentence that gives the count names the learned recommenders it counts (same list, same length)
         '\\newcommand{\\ccLearnedList}{' + join(MAIN_NAME.get(m, LAB[m]) for m in [m for m in learned if m != 'xre'] + [m for m in learned if m == 'xre']) + '}',
         f'\\newcommand{{\\ccCovMin}}{{{num_word(min(len(v) for v in cov.values()))}}}',
         f'\\newcommand{{\\ccCovMax}}{{{num_word(max(len(v) for v in cov.values()))}}}',
         f'\\newcommand{{\\ccZeroAllNine}}{{{join(LAB[m] for m in full9)}}}',
         f'\\newcommand{{\\ccExcDs}}{{{join(NAMES[d] for d in DS9 if d in exc)}}}',
         f'\\newcommand{{\\ccClothingAll}}{{{join(LAB[e[0]] for e in allhit.get("clothing", []))}}}',
         f'\\newcommand{{\\ccClothingSome}}{{{join(f"{LAB[e[0]]} in {num_word(e[2])} of {num_word(e[3])} seeds" for e in somehit.get("clothing", []))}}}',
         f'\\newcommand{{\\ccArtsAll}}{{{join(LAB[e[0]] for e in allhit.get("arts", []))}}}',
         f'\\newcommand{{\\ccArtsX}}{{{allhit["arts"][0][1]:.1f}}}' if len(allhit.get('arts', [])) == 1 else '',
         f'\\newcommand{{\\ccClothingXMin}}{{{min(exc_ratios):.0f}}}',
         f'\\newcommand{{\\ccClothingXMax}}{{{max(exc_ratios):.0f}}}',
         '\\newcommand{\\ccClothingXRange}{' + (f'{min(exc_ratios):.0f}' if f'{min(exc_ratios):.0f}' == f'{max(exc_ratios):.0f}'
                                               else f'{min(exc_ratios):.0f} to {max(exc_ratios):.0f}') + '}',
         '\\newcommand{\\ccIknnList}{' + join('%.3g$\\times$ on %s' % (ik[d]['ratio_mean'], NAMES[d]) for d in ik_pos) + '}',
         f'\\newcommand{{\\ccIknnAllSeeds}}{{{"in all five seeds" if ik_all5 else "not in every seed"}}}',
         f'\\newcommand{{\\ccIknnZeroDs}}{{{join(NAMES[d] for d in ik_zero)}}}',
         f'\\newcommand{{\\ccIknnZeroNMin}}{{{num_word(min(ncold[d] for d in ik_zero))}}}',
         f'\\newcommand{{\\ccIknnZeroNMax}}{{{num_word(max(ncold[d] for d in ik_zero))}}}',
         f'\\newcommand{{\\ccIknnFourDs}}{{{join(NAMES[d] for d in FOUR if d in ik_pos)}}}',
         f'\\newcommand{{\\ccIknnFourN}}{{{num_word(sum(d in ik_pos for d in FOUR))}}}']
    # E + R + A routing (r2s1, r2z)
    s1 = json.load(open(DATA / 'r2s1.json', encoding='utf-8'))
    z = json.load(open(DATA / 'r2z.json', encoding='utf-8'))
    per = s1['per_ds']
    dss = [d for d in DS9 if d in per]
    gO = [per[d]['g_O'] for d in dss]; gF = [per[d]['g_F'] for d in dss]; gR = [per[d]['g_R'] for d in dss]
    share = [f / o for f, o in zip(gF, gO)]
    au = [z['per_ds'][d]['single'][zz]['auc_test'] for d in dss for zz in z['zn']]
    M += [f'% r2s1 per dataset (g_O, g_F, g_router): ' + ', '.join(f'{d} {per[d]["g_O"]:.4f}/{per[d]["g_F"]:.4f}/{per[d]["g_R"]:.4f}' for d in dss),
          f'\\newcommand{{\\reNDs}}{{{num_word(len(dss))}}}',
          f'\\newcommand{{\\reGoMin}}{{{pct(min(gO))}}}', f'\\newcommand{{\\reGoMax}}{{{pct(max(gO))}}}',
          f'\\newcommand{{\\reGfMin}}{{{pct(min(gF))}}}', f'\\newcommand{{\\reGfMax}}{{{pct(max(gF))}}}',
          f'\\newcommand{{\\reShareMin}}{{{100 * min(share):.0f}}}', f'\\newcommand{{\\reShareMax}}{{{100 * max(share):.0f}}}',
          f'\\newcommand{{\\reGrMin}}{{{pct(min(gR))}}}', f'\\newcommand{{\\reGrMax}}{{{pct(max(gR))}}}',
          f'\\newcommand{{\\reAucMin}}{{{min(au):.2f}}}', f'\\newcommand{{\\reAucMax}}{{{max(au):.2f}}}',
          f'\\newcommand{{\\reNProps}}{{{num_word(len(z["zn"]))}}}', '']
    (ROOT / 'macros_coldroute.tex').write_text('\n'.join(x for x in M if x != ''), encoding='utf-8', newline='\n')
    print('\n'.join(M))


if __name__ == '__main__':
    main()
