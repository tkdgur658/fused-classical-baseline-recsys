"""Prose macros of the neighbor x popularity paragraph ("Which test targets carry the gain?", Fig. nbrpop; post hoc).
revision log 26 (author decision): the counts and the two gains that were typed in the paragraph become macros (prefix np).
Reads tables/hyp_nbrpop.csv (byte-identical to tables/src/data/hyp_nbrpop_mes.csv, see nbrpop_check_mes.txt): graph 'cooc',
rows nbr (co-occurrence neighbors of a training-history item) and non (other targets), popularity quintiles q1..q5, seeds 1-5, gain_pp
= change of the top-20 hit rate from MSCA to MES in percentage points. Cell values are means over seeds; "agreeing in sign" means
that all five seeds have the same sign. The significance counts of the same paragraph stay in tables/macros_sig.tex (sgNp*).
Counts 0-10 are spelled out (numwords.num_word).
Usage: python -s tables/src/build_nbrpop_macros.py   -> tables/macros_nbrpop.tex
"""
import csv
import hashlib
import statistics as st
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from numwords import num_word  # noqa: E402

T = HERE.parent
DS = ['baby', 'pantry', 'scientific', 'sports']
NAME = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports'}
Q = ['q1', 'q2', 'q3', 'q4', 'q5']
SEEDS = [1, 2, 3, 4, 5]


def main():
    src = T / 'hyp_nbrpop.csv'
    H = {}
    for r in csv.DictReader(open(src, encoding='utf-8')):
        if r['graph'] != 'cooc':
            continue
        H.setdefault((r['link'], r['quintile'], r['dataset']), {})[int(r['seed'])] = float(r['gain_pp'])
    assert all(len(v) == 5 and set(v) == set(SEEDS) for v in H.values()) and len(H) == 40
    mean = lambda l, q, d: st.mean(H[(l, q, d)].values())            # noqa: E731
    agree = lambda l, q, d: len({v > 0 for v in H[(l, q, d)].values()}) == 1   # noqa: E731
    out = ['% Generated by tables/src/build_nbrpop_macros.py from tables/hyp_nbrpop.csv (sha256 ' + hashlib.sha256(src.read_bytes()).hexdigest()[:8] + '...), revision log 26.',
           '% Do not edit by hand. Post hoc: neighbor x popularity cells of Fig. nbrpop (MSCA -> MES); counts 0-10 are spelled out.']

    def mac(n, v):
        out.append(f'\\newcommand{{\\{n}}}{{{v}}}')

    nbr_up = sum(mean('nbr', q, d) > 0 for q in Q for d in DS)
    mac('npNbrUp', num_word(nbr_up))
    mac('npNbrCells', num_word(len(Q) * len(DS)))
    lose = [(l, q, d) for l in ('nbr', 'non') for q in ('q3', 'q4') for d in DS if mean(l, q, d) < 0]
    mac('npMidLose', num_word(len(lose)))
    mac('npMidCells', num_word(2 * 2 * len(DS)))
    mac('npMidLoseAgree', num_word(sum(agree(*k) for k in lose)))
    mid_up = [(q, d) for q in ('q3', 'q4') for d in DS if mean('nbr', q, d) > 0]
    mac('npMidNbrUp', num_word(len(mid_up)))
    mac('npMidNbrCells', num_word(2 * len(DS)))
    # most popular fifth: neighbor gain above other-target gain; seeds agreeing in sign on the neighbor row
    above = sum(mean('nbr', 'q5', d) > mean('non', 'q5', d) for d in DS)
    mac('npQFiveAbove', 'all ' + num_word(len(DS)) if above == len(DS) else num_word(above) + ' of ' + num_word(len(DS)))
    mac('npQFiveAgree', num_word(sum(agree('nbr', 'q5', d) for d in DS)))
    dis = [d for d in DS if not agree('nbr', 'q5', d)]
    assert len(dis) == 1, dis
    mac('npQFiveExcDs', NAME[dis[0]])
    mac('npQFiveExcGain', f'$+{mean("nbr", "q5", dis[0]):.2f}$')
    mac('npBabyQThree', f'$+{mean("nbr", "q3", "baby"):.2f}$')
    (T / 'macros_nbrpop.tex').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
