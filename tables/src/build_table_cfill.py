"""Specification and cost of the classical fill C (revision log 18-1, 2026-10-16): tables/appendix_cfill.tex (tab:cfill),
tables/macros_cfill.tex (prefix cf), tables/sigtests_cfill.csv. Numbers are never typed by hand.

Definition (A_DESIGN/queue/strat_core.py route_lists and a_strat.py, unchanged): for every test user, the top-20 list keeps
the first 18 items of the learned ranking and fills the last two slots with the two highest-scoring eligible items among
the items with at most two training edges (degree strata 0 and 1-2) that are not already in the 18-item head. Two fills:
  q2_ext     ItemKNN-CBF score (text kNN-10 graph, as in F)
  q2_fcombo  z(RP3beta) + z(ItemKNN-CBF), the classical combination of F
Hit multiple = hit rate of test targets with at most two training edges / rate expected from a random list of 20 among
the eligible items. Cost = overall test Recall@20 (all test users) of the filled list minus that of the learned list.
Test: tables/src/sigtest.py (two-sided paired t over seeds 1-5, Holm over the datasets of each backbone and fill),
post hoc (no preregistered hypothesis on the cost).
Input: tables/src/data/step1/c_fill_perseed.json (HOST_A study/STEP1/code/c_fill_extract.py, read-only extraction of
A_DESIGN/results/<backbone>__<ds>__s<seed>.json and TABLE_FUSION/cells/*.json); cross-checked against
tables/src/data/teaser/d3_per_seed.json (the source of Fig. 1, panel C).
Usage: python tables/src/build_table_cfill.py
"""
import json
import math
import statistics as st
from pathlib import Path

import sigtest
from numwords import k_of_n, num_word

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'src' / 'data'
BB = [('native', 'MSCA'), ('xre', 'E + R + A'), ('mes', 'MES')]
ARMS = [('q2_ext', 'ItemKNN-CBF'), ('q2_fcombo', 'combination')]
ORDER = ['baby', 'pantry', 'scientific', 'sports', 'clothing', 'instruments', 'arts', 'office']
NAMES = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports', 'clothing': 'Clothing',
         'instruments': 'Instruments', 'arts': 'Arts', 'office': 'Office'}
TF = {'mes': 'MSCA + MES', 'native': 'MSCA', 'cohesion': 'COHESION', 'smore': 'SMORE', 'pgl': 'PGL', 'diffmm': 'DiffMM',
      'lgmrec': 'LGMRec', 'freedom': 'FREEDOM'}


def join(xs):
    xs = list(xs)
    if not xs:
        return 'none'
    return xs[0] if len(xs) == 1 else (' and '.join(xs) if len(xs) == 2 else ', '.join(xs[:-1]) + ', and ' + xs[-1])


def main():
    J = json.load(open(DATA / 'step1' / 'c_fill_perseed.json', encoding='utf-8'))
    T = json.load(open(DATA / 'teaser' / 'd3_per_seed.json', encoding='utf-8'))
    cells = {}
    for key, c in J['cells'].items():
        bb, ds = key.split('__')
        seeds = sorted(c, key=int)
        assert seeds == ['1', '2', '3', '4', '5'] and all(c[s]['gate_ok'] for s in seeds), key
        per = {rt: {int(s): c[s][rt] for s in seeds} for rt in ('base', 'q2_ext', 'q2_fcombo')}
        for rt in per:                                         # same per-seed values as the teaser source
            assert all(abs(per[rt][s]['le2_x'] - T[key]['per'][rt]['le2'][s - 1]) < 1e-9 for s in per[rt]), key
            assert all(abs(per[rt][s]['test_r20'] - T[key]['per'][rt]['test'][s - 1]) < 1e-12 for s in per[rt]), key
        cells[(bb, ds)] = per
    # learned models of F on the same targets (base route of TABLE_FUSION, gate ok)
    fmods = {}
    for key, c in J['learned'].items():
        m, ds = key.split('__')
        xs = [v['le2_x'] for v in c.values() if v['gate_ok'] and v['le2_x'] is not None]
        if xs:
            fmods.setdefault(ds, {})[m] = st.mean(xs)
    x = lambda per, rt: st.mean(per[rt][s]['le2_x'] for s in per[rt])
    # best learned model of the three backbones per dataset (the comparison of the C claim)
    best3 = {}
    for (bb, ds), per in cells.items():
        best3[ds] = max(best3.get(ds, 0.0), x(per, 'base'))
    rows, tests = [], []
    for bb, lab in BB:
        dss = [d for d in ORDER if (bb, d) in cells]
        for arm, alab in ARMS:
            pa = {d: {s: cells[(bb, d)][arm][s]['test_r20'] for s in sigtest.SEEDS} for d in dss}
            pb = {d: {s: cells[(bb, d)]['base'][s]['test_r20'] for s in sigtest.SEEDS} for d in dss}
            res = sigtest.contrast(pa, pb, dss, fam=f'cfill_{bb}_{arm}', name='fill - learned', a=f'{lab} + C({alab})',
                                   b=lab, metric='R@20 all users')
            tests += res
    tix = {(t['a'], t['dataset']): t for t in tests}
    hold = {arm: 0 for arm, _ in ARMS}
    hold_both = 0
    L = ['% Generated by tables/src/build_table_cfill.py from tables/src/data/step1/c_fill_perseed.json. Do not edit numbers by hand.',
         '\\begin{table}[t]',
         '\\caption{Classical fill C. Each test list keeps the first 18 items of the learned ranking and fills the last two '
         'slots with the two highest-scoring items among those with at most two training edges, scored by ItemKNN-CBF or by '
         'the classical combination of F. $n$ counts the test targets with at most two training edges, and the next three '
         'columns give their hits in units of the hits expected from a random list for the learned model and the two fills. '
         'The last two columns give the change in overall Recall@20 over all test users, $\\times 10^{3}$, with $^{\\ast}$ '
         'for a significant change in a post-hoc ' + sigtest.RULE_TEXT + '. All entries average seeds 1--5.}',
         '\\label{tab:cfill}', '\\centering', '\\footnotesize', '\\setlength{\\tabcolsep}{3.0pt}',
         '\\begin{tabular}{lrrrrrr}', '\\toprule',
         ' & & \\multicolumn{3}{c}{Hits ($\\times$ random)} & \\multicolumn{2}{c}{$\\Delta$R@20 ($\\times 10^{3}$)} \\\\',
         '\\cmidrule(lr){3-5}\\cmidrule(lr){6-7}',
         'Dataset & $n$ & Learned & CBF & Comb. & CBF & Comb. \\\\']
    for bb, lab in BB:
        L += ['\\midrule', f'\\multicolumn{{7}}{{l}}{{\\emph{{{lab}}}}} \\\\']
        for d in [d for d in ORDER if (bb, d) in cells]:
            per = cells[(bb, d)]
            n = per['base'][1]['le2_n']
            vals = [x(per, 'base'), x(per, 'q2_ext'), x(per, 'q2_fcombo')]
            ok_both = True
            for arm, alab in ARMS:
                ok = x(per, arm) > 3 and x(per, arm) > 2 * best3[d]
                hold[arm] += ok; ok_both &= ok
            hold_both += ok_both
            cost = []
            for arm, alab in ARMS:
                t = tix[(f'{lab} + C({alab})', d)]
                cost.append(f"${1e3 * t['diff']:+.1f}" + ('^{\\ast}' if t['reject'] else '') + '$')
            L.append(f"{NAMES[d]} & {n:,} & " + ' & '.join(f'{v:.2f}' for v in vals) + ' & ' + ' & '.join(cost) + ' \\\\')
    L += ['\\bottomrule', '\\end{tabular}', '\\end{table}', '']
    (ROOT / 'appendix_cfill.tex').write_text('\n'.join(L), encoding='utf-8', newline='\n')
    sigtest.write_csv(ROOT / 'sigtests_cfill.csv', tests)
    ncell = len(cells)
    fills = [x(per, arm) for per in cells.values() for arm, _ in ARMS]
    learn = [best3[d] for (_, d) in cells]
    rng = lambda ds: [x(cells[(bb, ds)], 'base') for bb, _ in BB if (bb, ds) in cells]
    costs = [t['diff'] for t in tests]
    nsig = sum(t['reject'] for t in tests)
    nsig_down = sum(t['reject'] and t['diff'] < 0 for t in tests)
    # fills against every learned model of F on the six datasets with F cells
    f_ok = [d for d in fmods if all(x(cells[(bb, d)], arm) > 2 * max(fmods[d].values())
                                    for bb, _ in BB if (bb, d) in cells for arm, _ in ARMS)]
    nper = sorted({cells[k]['base'][1]['le2_n'] for k in cells})
    M = ['% Generated by tables/src/build_table_cfill.py from tables/src/data/step1/c_fill_perseed.json. Do not edit by hand.',
         f'\\newcommand{{\\cfNCells}}{{{ncell}}}',
         f'\\newcommand{{\\cfHoldPhrase}}{{{k_of_n(hold_both, ncell)}}}',
         f'\\newcommand{{\\cfNHoldBoth}}{{{num_word(hold_both)}}}',
         f'\\newcommand{{\\cfNHoldCbf}}{{{num_word(hold["q2_ext"])}}}',
         f'\\newcommand{{\\cfNHoldComb}}{{{num_word(hold["q2_fcombo"])}}}',
         f'\\newcommand{{\\cfFillMin}}{{{min(fills):.1f}}}',
         f'\\newcommand{{\\cfFillMax}}{{{max(fills):.1f}}}',
         f'\\newcommand{{\\cfLearnMin}}{{{min(learn):.2f}}}',
         f'\\newcommand{{\\cfLearnMax}}{{{max(learn):.2f}}}',
         f'\\newcommand{{\\cfPantryLo}}{{{min(rng("pantry")):.1f}}}',
         f'\\newcommand{{\\cfPantryHi}}{{{max(rng("pantry")):.1f}}}',
         f'\\newcommand{{\\cfSportsLo}}{{{min(rng("sports")):.1f}}}',
         f'\\newcommand{{\\cfSportsHi}}{{{max(rng("sports")):.1f}}}',
         f'\\newcommand{{\\cfNTargetsMin}}{{{nper[0]:,}}}',
         f'\\newcommand{{\\cfNTargetsMax}}{{{nper[-1]:,}}}',
         f'\\newcommand{{\\cfNTests}}{{{len(tests)}}}',
         f'\\newcommand{{\\cfNCostNeg}}{{{k_of_n(sum(c < 0 for c in costs), len(tests))}}}',
         f'\\newcommand{{\\cfCostMin}}{{{min(-c for c in costs if c < 0):.4f}}}',
         f'\\newcommand{{\\cfCostMax}}{{{max(-c for c in costs if c < 0):.4f}}}',
         f'\\newcommand{{\\cfNCostSig}}{{{num_word(nsig) if nsig else "none"}}}',
         f'\\newcommand{{\\cfNCostSigDown}}{{{num_word(nsig_down) if nsig_down else "none"}}}',
         f'\\newcommand{{\\cfNFDs}}{{{num_word(len(fmods))}}}',
         f'\\newcommand{{\\cfNFDsHold}}{{{k_of_n(len(f_ok), len(fmods))}}}',
         f'\\newcommand{{\\cfNFModels}}{{{num_word(len(TF))}}}', '']
    (ROOT / 'macros_cfill.tex').write_text('\n'.join(M), encoding='utf-8', newline='\n')
    print('\n'.join(L[14:])); print('\n'.join(M))
    print('F-model maxima per dataset:', {d: round(max(v.values()), 2) for d, v in fmods.items()})


if __name__ == '__main__':
    main()
