"""Build tables/appendix_neardup.tex (supplementary Table tab:neardup, revision log 18-D, 2026-10-16): hit multiple of each model on
the new near-duplicate targets, by dataset. Numbers are never typed by hand.
Input: tables/src/data/w2_003.json (copy of HOST_A <RUN_ROOT>/W2/results/W2-003.json, written by W2/code/w2_agg003.py), key `detail`:
  detail.<ds>.n                       number of near-duplicate targets (text cosine >= 0.95 to a history item, at most two training edges)
  detail.<ds>.models.<m>.x_rnd        hit rate at 20 of the targets, mean over seeds, divided by the hit rate of a random list
  detail.<ds>.models.<m>.hits         hits per seed (its length is the number of seeds of the cell)
  detail.<ds>.models.<m>.survive      >= 3 x random in at least 80% of the seeds (W2-003 criterion)
  detail.<ds>.models.<m>.collapse     <= 1.5 x random in at least 80% of the seeds (W2-003 criterion)
The class fractions of the prose (tables/macros_neardup.tex: collapse 82%, survive 78%) are recounted here from the same flags and
asserted equal to the file's own fields. Pantry holds no such target and gets no column.
Usage: python tables/src/build_table_neardup.py
"""
import json
from pathlib import Path

from numwords import num_word

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'src' / 'data'
OUT = ROOT / 'appendix_neardup.tex'
BS = chr(92)
NAMES = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports', 'clothing': 'Clothing',
         'instruments': 'Instruments', 'arts': 'Arts', 'office': 'Office'}
# row order: models that inject content through propagation only, models with a kNN item graph or feature path, other baselines, MSCA variants
MODELS = [('lightgcn', 'LightGCN'), ('lgmrec', 'LGMRec'), ('diffmm', 'DiffMM'), ('freedom', 'FREEDOM'), ('mentor', 'MENTOR'),
          ('smore', 'SMORE'), ('cohesion', 'COHESION'), ('pgl', 'PGL'), ('native', 'MSCA'), ('xre', 'E + R + A'), ('mes', 'MES')]
# revision log 18-F: runs xretn and mscaA5 of W2-003 have no code definition, thus they are left out of the table (author).
DROP = {'xretn', 'mscaA5'}
CLASS_A, CLASS_B = ('lightgcn', 'lgmrec', 'diffmm'), ('freedom', 'mentor')
PANEL = 4   # datasets per stacked panel (the table never uses \resizebox)


def main():
    w3 = json.load(open(DATA / 'w2_003.json', encoding='utf-8'))
    det = w3['detail']
    dss = sorted((d for d in det if det[d]['n'] > 0), key=lambda d: -det[d]['n'])
    empty = [d for d in det if det[d]['n'] == 0]
    ca = [m for d in det.values() for k, m in d['models'].items() if k in CLASS_A]
    cb = [m for d in det.values() for k, m in d['models'].items() if k in CLASS_B]
    fa = sum(m['collapse'] for m in ca) / len(ca)
    fb = sum(m['survive'] for m in cb) / len(cb)
    assert abs(fa - w3['frac_classA_collapse']) < 1e-12 and abs(fb - w3['frac_classB_survive']) < 1e-12
    used = {k for d in dss for k in det[d]['models']}
    assert used - DROP <= {k for k, _ in MODELS}, used - DROP - {k for k, _ in MODELS}
    seeds = [len(m['hits']) for d in dss for k, m in det[d]['models'].items() if k not in DROP]
    smin, smax = min(seeds), max(seeds)
    ncell = sum(1 for d in dss for k in det[d]['models'] if k not in DROP)

    def cell(m, d):
        c = det[d]['models'].get(m)
        if c is None:
            return '--'
        v = f"{c['x_rnd']:.1f}"
        if c['survive']:
            return BS + 'textbf{' + v + '}'
        return v + ('$^{' + BS + 'dagger}$' if c['collapse'] else '')

    cap = ('Hit multiple of each model on new near-duplicate targets, by dataset. '
           'A target counts when its text cosine similarity to a history item of its user is at least $0.95$ and it has at most two training edges, and $n$ gives the number of such targets. '
           'Each entry is the hit rate in the top 20 of these targets, divided by the hit rate of a random list of 20 items, as the mean over the available seeds (' + num_word(smin) + ' to ' + num_word(smax) + ' per cell). '
           'Bold marks at least three times the random rate and $^{' + BS + 'dagger}$ at most one and a half times, each in at least $80' + BS + '%$ of the seeds, and a dash marks a model without runs on the dataset. '
           + ', '.join(NAMES[d] for d in empty) + ' holds no such target.')
    lines = ['% Generated by tables/src/build_table_neardup.py from tables/src/data/w2_003.json (W2-003, nd_low group). Do not edit numbers by hand.',
             BS + 'begin{table}[t]', BS + 'caption{' + cap + '}', BS + 'label{tab:neardup}', BS + 'centering', BS + 'footnotesize',
             BS + 'setlength{' + BS + 'tabcolsep}{4pt}', BS + 'begin{tabular}{l' + 'r' * PANEL + '}']
    for pi in range(0, len(dss), PANEL):
        panel = dss[pi:pi + PANEL]
        pad = ' &' * (PANEL - len(panel))
        lines += [BS + 'toprule' if pi == 0 else BS + 'midrule[' + BS + 'heavyrulewidth]',
                  'Model & ' + ' & '.join(NAMES[d] for d in panel) + pad + ' ' + BS + BS,
                  '$n$ & ' + ' & '.join(str(det[d]['n']) for d in panel) + pad + ' ' + BS + BS,
                  BS + 'midrule']
        for m, label in MODELS:
            if any(m in det[d]['models'] for d in panel):
                lines.append(f'{label} & ' + ' & '.join(cell(m, d) for d in panel) + pad + ' ' + BS + BS)
    lines += [BS + 'bottomrule', BS + 'end{tabular}', BS + 'end{table}', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print('wrote', OUT.name, len(dss), 'datasets,', ncell, 'cells, seeds', smin, 'to', smax)


if __name__ == '__main__':
    main()
