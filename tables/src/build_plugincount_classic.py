"""Plug-in counts for fact 2 of thesis B (CLASSIC, 2026-10-16; recount of the draft numbers 2/60 up and 13/60 down).

Cells = five plug-in objectives (INA-style, MDVT, MG, DA-MRS, UltraGCN L_I) x three backbones (MSCA, COHESION, SMORE) x four
datasets (Baby, Pantry, Scientific, Sports) = sixty cells.  A cell is significant when the plug-in differs from its own backbone
(row Native) in Recall@20 under the single test family of tables/src/sigtest.py: two-sided paired t-test over seeds 1-5
(the two runs of one seed paired), Holm correction over the datasets of the contrast (one contrast = one plug-in on one backbone,
four datasets), alpha 0.05.  Reads tables/table1_perseed.csv (MSCA) and tables/cohsmo_perseed.csv (COHESION, SMORE).
Writes tables/macros_plugincount.tex (prefix pc; counts 0-10 spelled out) and tables/src/data/classic_plugincount.csv (every test).
Usage: python -s tables/src/build_plugincount_classic.py
"""
import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import sigtest  # noqa: E402
from numwords import num_word  # noqa: E402

T = Path(__file__).resolve().parents[1]
DATA = Path(__file__).resolve().parent / 'data'
DS4 = ['baby', 'pantry', 'scientific', 'sports']
NAME = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports'}
PLUG = [('INA', 'INA-style'), ('MDVT', 'MDVT'), ('MG', 'MG'), ('DA-MRS', 'DA-MRS'), ('UltraGCN-LI', 'UltraGCN')]
BACK = ['MSCA', 'COHESION', 'SMORE']
SEEDS = [1, 2, 3, 4, 5]


def cnt(k):
    return num_word(k) if k <= 10 else str(k)


per = {}
for f in ('table1_perseed.csv', 'cohsmo_perseed.csv'):
    for r in csv.DictReader(open(T / f, newline='', encoding='utf-8')):
        if r['dataset'] in DS4:
            per.setdefault((r['backbone'], r['row'], r['dataset']), {})[int(r['seed'])] = float(r['r20'])
res = []
for b in BACK:
    for p, _ in PLUG:
        for d in DS4:
            assert sorted(per[(b, p, d)]) == SEEDS and sorted(per[(b, 'Native', d)]) == SEEDS, (b, p, d)
        res += sigtest.contrast({d: per[(b, p, d)] for d in DS4}, {d: per[(b, 'Native', d)] for d in DS4}, DS4,
                                fam='plug-in vs own backbone (Table tab:main)', name=f'{b}: {p} - Native', a=p, b=b, metric='r20')
        for r in res[-len(DS4):]:
            r['backbone'], r['plugin'] = b, p
up = [r for r in res if r['reject'] and r['diff'] > 0]
down = [r for r in res if r['reject'] and r['diff'] < 0]
mean_up = [r for r in res if r['diff'] > 0]
with open(DATA / 'classic_plugincount.csv', 'w', newline='', encoding='utf-8') as f:
    cols = ['backbone', 'plugin', 'dataset', 'n', 'mean_a', 'mean_b', 'diff', 'ci_lo', 'ci_hi', 't', 'p', 'm', 'p_holm', 'reject', 'wins_a']
    w = csv.DictWriter(f, cols, lineterminator='\n', extrasaction='ignore'); w.writeheader()
    for r in res:
        w.writerow({k: (f'{r[k]:.6g}' if isinstance(r[k], float) else r[k]) for k in cols})
OUT = ['% Generated by tables/src/build_plugincount_classic.py (CLASSIC, 2026-10-16). Do not edit by hand.',
       '% Plug-in objective against its own backbone, Recall@20, paired t over seeds 1-5, Holm over the four datasets of each contrast.']


def mac(n, v):
    assert re.fullmatch(r'[A-Za-z]+', n), n
    OUT.append(f'\\newcommand{{\\{n}}}{{{v}}}')


def phrase(cells):
    return ', '.join(f"{NAME[r['dataset']]} ({r['plugin']} on {r['backbone']})" for r in cells) if cells else 'none'


mac('pcNPlug', num_word(len(PLUG)))
mac('pcNBack', num_word(len(BACK)))
mac('pcNDs', num_word(len(DS4)))
mac('pcNCells', str(len(res)))
mac('pcNUp', cnt(len(up)))
mac('pcNDown', cnt(len(down)))
mac('pcNMeanUp', cnt(len(mean_up)))
mac('pcNMeanDown', cnt(len(res) - len(mean_up) - sum(r['diff'] == 0 for r in res)))
mac('pcUpCells', phrase(up))
dm = [r for r in down if r['plugin'] == 'DA-MRS']
mac('pcNDownDamrs', cnt(len(dm)))
mac('pcNDownOther', cnt(len(down) - len(dm)))
for b in BACK:
    mac('pcNDown' + b.capitalize(), cnt(sum(r['backbone'] == b for r in down)))
    mac('pcNUp' + b.capitalize(), cnt(sum(r['backbone'] == b for r in up)))
(T / 'macros_plugincount.tex').write_text('\n'.join(OUT) + '\n', encoding='utf-8', newline='\n')
print('\n'.join(OUT))
print('down by plugin:', {p: sum(r['plugin'] == p for r in down) for p, _ in PLUG})
print('down by backbone:', {b: sum(r['backbone'] == b for r in down) for b in BACK})
print('up:', [(r['backbone'], r['plugin'], r['dataset'], round(r['diff'], 4), round(r['p_holm'], 4)) for r in up])
