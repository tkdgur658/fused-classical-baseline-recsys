"""Specification table of the fused baseline F (revision log 18-1, 2026-10-16): tables/appendix_fspec.tex (tab:fspec) and
tables/macros_fspec.tex (prefix fs). Numbers are never typed by hand.

Inputs
  tables/src/data/step1/f_standalone_<ds>.json  HOST_A study/STEP1/code/f_standalone.py (sha in each file; CPU, deterministic):
      standalone test Recall@20 / NDCG@20 of RP3beta, ItemKNN-CBF, and their z-score combination, the W1 validation grid of
      RP3beta (alpha x beta, topK 200) with its chosen setting, and a gate of the tie-adjusted RP3beta Recall@20 against W1.
  tables/src/data/fusion_cells_9ds_mes.csv  per model x dataset x seed the fusion weight w chosen on validation Recall@20
      (TABLE_FUSION/code/tf_queue.py: argmax over f_combo_<w>, ties to the smaller w), the cells behind Tables sota/fuse_added.
The classical rankers are training-free and deterministic, thus one value per dataset (no seeds); the fusion weight is
chosen per seed and per model.  Usage: python tables/src/build_table_fspec.py
"""
import csv
import json
import statistics as st
from pathlib import Path

from numwords import num_word

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'src' / 'data'
DS = ['baby', 'pantry', 'scientific', 'sports', 'clothing', 'instruments', 'arts', 'office', 'microlens']      # revision log 32: MicroLens added (nine datasets); before: eight
NAMES = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports', 'clothing': 'Clothing',
         'instruments': 'Instruments', 'arts': 'Arts', 'office': 'Office', 'microlens': 'MicroLens'}
WS = [0.05, 0.1, 0.2, 0.3, 0.5, 0.7, 1.0, 1.5]      # tf_fuse.py WS


def join(xs):
    xs = list(xs)
    if not xs:
        return 'none'
    return xs[0] if len(xs) == 1 else (' and '.join(xs) if len(xs) == 2 else ', '.join(xs[:-1]) + ', and ' + xs[-1])


def fmt_w(w):
    return f'{w:g}'


def main():
    J = {d: json.load(open(DATA / 'step1' / f'f_standalone_{d}.json', encoding='utf-8')) for d in DS if d != 'microlens'}
    # revision log 32 (decision ): MicroLens has no STEP1 file, its standalone rankers come from CLASSIC E1a (classic_ds.py, same W1 grid, tie-adjusted
    # gate); for the eight other datasets the E1a values are asserted equal to the STEP1 values
    E1 = {d: json.load(open(DATA / f'classic_e1a_{d}.json', encoding='utf-8')) for d in DS}
    for d in DS:
        e = E1[d]
        if d == 'microlens':
            J[d] = dict(dataset=d, gate_rp3b_tieadj_vs_w1=e['gates']['rp3b']['ok'], rp3b_grid=e['grid_rows']['rp3b'], rp3b_chosen=e['rp3b_cfg'], knn=10,
                        rankers=dict(rp3b=e['rankers']['rp3b'], iknn=e['rankers']['iknn'], combo=e['rankers']['F']))
        else:
            assert e['rp3b_cfg'] == J[d]['rp3b_chosen'], d
            for k, k2 in (('rp3b', 'rp3b'), ('iknn', 'iknn'), ('combo', 'F')):
                for m in ('test_r20', 'test_n20'):
                    assert abs(e['rankers'][k2][m] - J[d]['rankers'][k][m]) < 5e-5, (d, k, m)
    for d, j in J.items():
        assert j['dataset'] == d and j['gate_rp3b_tieadj_vs_w1'], d
        best = max(j['rp3b_grid'], key=lambda g: g['valid_r20'])
        assert best['cfg'] == j['rp3b_chosen'], (d, best, j['rp3b_chosen'])
        assert j['knn'] == 10
    W, seen = {d: [] for d in DS}, {}
    for r in csv.DictReader(open(DATA / 'fusion_cells_9ds_mes.csv', newline='', encoding='utf-8')):
        k = (r['model'], r['dataset'], r['seed'])
        if r['dataset'] not in W or r['gate_ok'] != '1' or not r['fused_r20']:
            continue
        if k in seen:
            assert seen[k] == r, ('conflicting duplicate', k)
            continue
        seen[k] = r
        w = float(r['weight']); assert w in WS, w
        seen[k] = w
    # revision log 32: the fused cells of the CLASSIC queue (classic_e1b_cells.csv, combo_w) join the TABLE_FUSION cells (85 cells in both, equal weights asserted);
    # before: only fusion_cells_9ds_mes.csv, eight datasets, 242 cells
    for r in csv.DictReader(open(DATA / 'classic_e1b_cells.csv', newline='', encoding='utf-8')):
        k = (r['model'], r['dataset'], r['seed'])
        if r['dataset'] not in W or r['gate_ok'] != '1' or not r['combo_r20']:
            continue
        w = float(r['combo_w']); assert w in WS, w
        if k in seen:
            assert seen[k] == w, ('weight differs between TABLE_FUSION and CLASSIC', k)
        seen[k] = w
    for k, w in seen.items():
        W[k[1]].append(w)
    allw = [w for d in DS for w in W[d]]
    L = ['% Generated by tables/src/build_table_fspec.py from tables/src/data/step1/f_standalone_<ds>.json and '
         'fusion_cells_9ds_mes.csv. Do not edit numbers by hand.',
         '\\begin{table*}[t]',
         '\\caption{Classical rankers of the fused baseline F. RP3$\\beta$ uses the setting of $\\alpha$ and $\\beta$ chosen by '
         'validation Recall@20 from a grid of four, with 200 kept transitions per item. ItemKNN-CBF scores an item by its '
         'cosine weights to the history items in the 10-nearest-neighbor graph of the text features and has no tuned '
         'parameter. Combination adds the per-user z-scores of both. Each ranker is training-free and deterministic, thus '
         'every entry is one value per dataset, with ties in the list broken by the item index. The last column gives the '
         'fusion weight $w$ of F chosen per model and seed by validation Recall@20, as its median and range over the '
         'model and seed cells of Tables~\\ref{tab:sota} and~\\ref{tab:fuse_added}, whose number Cells gives.}',
         '\\label{tab:fspec}', '\\centering', '\\footnotesize', '\\setlength{\\tabcolsep}{3.2pt}',
         '\\begin{tabular}{lcrrrrrrrl}', '\\toprule',
         ' & \\multicolumn{3}{c}{RP3$\\beta$} & \\multicolumn{2}{c}{ItemKNN-CBF} & \\multicolumn{2}{c}{Combination} & & \\\\',
         '\\cmidrule(lr){2-4}\\cmidrule(lr){5-6}\\cmidrule(lr){7-8}',
         'Dataset & $\\alpha$, $\\beta$ & R@20 & N@20 & R@20 & N@20 & R@20 & N@20 & Cells & $w$ of F \\\\', '\\midrule']
    combo_best = []
    for d in DS:
        j = J[d]; c = j['rp3b_chosen']; rk = j['rankers']
        vals = [rk[r][m] for r in ('rp3b', 'iknn', 'combo') for m in ('test_r20', 'test_n20')]
        cells = ' & '.join(f'{v:.4f}' for v in vals)
        w = W[d]
        wtxt = f'{fmt_w(st.median(w))} ({fmt_w(min(w))}--{fmt_w(max(w))})'
        L.append(f"{NAMES[d]} & {fmt_w(c['alpha'])}, {fmt_w(c['beta'])} & {cells} & {len(w)} & {wtxt} \\\\")
        if rk['combo']['test_r20'] > max(rk['rp3b']['test_r20'], rk['iknn']['test_r20']):
            combo_best.append(d)
    L += ['\\bottomrule', '\\end{tabular}', '\\end{table*}', '']
    (ROOT / 'appendix_fspec.tex').write_text('\n'.join(L), encoding='utf-8', newline='\n')
    for d in DS:                                   # outside combo_best, RP3beta alone is the strongest of the three
        if d not in combo_best:
            rk = J[d]['rankers']; assert rk['rp3b']['test_r20'] == max(rk[r]['test_r20'] for r in rk), d
    chosen = {(J[d]['rp3b_chosen']['alpha'], J[d]['rp3b_chosen']['beta']) for d in DS}
    grid = J[DS[0]]['rp3b_grid']
    assert all([g['cfg'] for g in J[d]['rp3b_grid']] == [g['cfg'] for g in grid] for d in DS)
    alphas = sorted({g['cfg']['alpha'] for g in grid}); betas = sorted({g['cfg']['beta'] for g in grid}); topk = {g['cfg']['topK'] for g in grid}
    assert len(topk) == 1
    nc = len(combo_best)
    M = ['% Generated by tables/src/build_table_fspec.py. Do not edit by hand.',
         f'\\newcommand{{\\fsNDs}}{{{num_word(len(DS))}}}',
         f'\\newcommand{{\\fsWGrid}}{{{", ".join(fmt_w(w) for w in WS)}}}',
         f'\\newcommand{{\\fsNW}}{{{num_word(len(WS))}}}',
         f'\\newcommand{{\\fsWMin}}{{{fmt_w(min(allw))}}}',
         f'\\newcommand{{\\fsWMax}}{{{fmt_w(max(allw))}}}',
         f'\\newcommand{{\\fsWMedian}}{{{fmt_w(st.median(allw))}}}',
         f'\\newcommand{{\\fsNCells}}{{{len(allw)}}}',
         f'\\newcommand{{\\fsNRpSettings}}{{{num_word(len(chosen))}}}',
         f'\\newcommand{{\\fsAlphaGrid}}{{{", ".join(fmt_w(x) for x in alphas)}}}',
         f'\\newcommand{{\\fsBetaGrid}}{{{", ".join(fmt_w(x) for x in betas)}}}',
         f'\\newcommand{{\\fsTopK}}{{{topk.pop()}}}',
         f'\\newcommand{{\\fsNGrid}}{{{num_word(len(grid))}}}',
         f'\\newcommand{{\\fsAlphaSel}}{{{fmt_w(next(iter(chosen))[0]) if len(chosen) == 1 else "varies"}}}',
         f'\\newcommand{{\\fsBetaSel}}{{{fmt_w(next(iter(chosen))[1]) if len(chosen) == 1 else "varies"}}}',
         f'\\newcommand{{\\fsComboBestN}}{{{num_word(nc)}}}',
         f'\\newcommand{{\\fsComboBestDs}}{{{join(NAMES[d] for d in combo_best)}}}',
         f'\\newcommand{{\\fsComboNotDs}}{{{join(NAMES[d] for d in DS if d not in combo_best)}}}', '']
    (ROOT / 'macros_fspec.tex').write_text('\n'.join(M), encoding='utf-8', newline='\n')
    print('\n'.join(L[-14:])); print('\n'.join(M))


if __name__ == '__main__':
    main()
