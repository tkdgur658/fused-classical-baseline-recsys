"""Write tables/macros_mmchan.tex: numbers of the problem-statement sentences on the message channels of the
self-message (Proposition 1) and on the ID-only LightGCN reference. Every value is computed here from tables/mmchan_*.csv.

Input
  tables/mmchan_perseed.csv  per (dataset, model, arm, seed, metric): value and user-bootstrap 95% CI (1000 resamples of
                             the evaluation users, seed 0). Produced by <RUN_ROOT_B>/P04_newprin/mmchan
                             (mmchan2.py for MSCA Native / XRE seeds 1-5, lgcn_self.py for LightGCN, summ.py).
                             LightGCN checkpoints: Baby s1, Pantry s1-s3, Scientific s1 (MMRec_clean), same split and same
                             training-positive sample as the MSCA cells (checked by hashes). Sports s1-s5 (MMRec_clean,
                             HOST_B; P04_sports_abl_HOST_B/runs_lgcn) via mmchan_sports (lgcn_self_nl.py,
                             summ_sports.py, split hashes equal to the MSCA Sports cells), appended by collect_mmchan.py.
Definitions (training positive (u, p), at most five per evaluation user, one uniform negative per pair)
  * S = R_up m_up^T e_p (self-message), m_up = gbar_p + 0.4 sum_v (1 - pi_uv) h^v_p with message channels
    collab (gbar_p), struct (co-occurrence view), image, text.  Channel share = sum_pairs S_c / sum_pairs S.
  * Share of the training score = sum S / sum s_up.  LightGCN: e_u = W_u/3 + sum_i R_ui m_i, the user ID term W_u/3 is
    no message, lgcnMsgShare = sum S / sum (s_up - W_u/3 . e_p), lgcnEgo = sum (W_u/3 . e_p) / sum s_up.
  * Kept gradient = E[w_full] / E[w_cav], w = sigma(s_un - s_up) and sigma(s_un - c_up) (Proposition 2).
  * Top-40 drop = share of training positives in the top 40 (candidates = non-history items + p) on the full score
    minus the same share after a closed-form removal: of the whole quantum and the item-side echo (LOO), or of the
    image and text messages of p only (looMM).
  * Neighbour echo = mean over the text-kNN neighbours j of p outside the history of R_up m_up^T e_j / sd_u, sd_u = std of
    the user scores over the candidates.  Random = same for 20 random non-history items.
  * Slots = top-20 items adjacent (any item-item graph) to p, minus the same count after the removal.
  * Link = share of top-20 items (or test targets) adjacent to >= 1 history item in the image or text kNN graph.
  * Gap share = (top-20 mean minus test-target mean) of the user-side image + text channel score, over the same gap of
    the full score, both / sd_u.
Conventions: MSCA ranges run over the 20 Native cells (Baby, Pantry, Scientific, Sports x seeds 1-5) unless the name has a
dataset suffix, which takes the mean over seeds 1-5. Sports has no mmchan2 cells: its MSCA Native rows are those of
tables/mmchan_topk_perseed.csv (Table I Sports Native runs, same metric definitions). LightGCN ranges and
mmcLgcnSeedsAll use the LightGCN cells present (no Sports cell until mmchan_sports/add_lgcn_sports.sh has run; the
per-dataset mmcLgcn*<DS> macros of a dataset without cells are not written). plg* and obj* macros run over Baby, Pantry
and Scientific only (no plug-in cells for Sports); their top-K part is restricted to the same datasets.
Shares are percentages rounded to integers, ratios two decimals.
The script stops if a macro name also appears in another tables/macros_*.tex file.
Usage: python -s tables/src/build_mmchan_macros.py
"""
import csv
import re
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
T = ROOT / 'tables'
OUT = T / 'macros_mmchan.tex'
DS = [('baby', 'Baby'), ('pantry', 'Pantry'), ('scientific', 'Scientific'), ('sports', 'Sports')]
DS_PLG = DS[:3]          # plug-in checkpoints (mmchan_plg_perseed.csv) exist for Baby, Pantry, Scientific only
SEEDS = [1, 2, 3, 4, 5]


def main():
    with open(T / 'mmchan_perseed.csv', newline='', encoding='utf-8') as f:
        rows = list(csv.DictReader(f))
    V = {(r['dataset'], r['model'], r['arm'], int(r['seed']), r['metric']): float(r['value']) for r in rows}
    with open(T / 'mmchan_topk_perseed.csv', newline='', encoding='utf-8') as f:
        rows3 = list(csv.DictReader(f))
    V3 = {(r['dataset'], r['arm'], int(r['seed']), r['metric']): float(r['value']) for r in rows3}
    # MSCA Native of a dataset without mmchan2 cells (Sports): the Native cells of the top-K summary (summ3.py rows =
    # summ.msca_cell metrics of the Table I Native runs, plus the EFLEC metrics), same metric names and bootstrap.
    for d, _ in DS:
        if not any(k[0] == d and k[1] == 'MSCA' for k in V):
            for (d3, a3, s3, m3), v in V3.items():
                if d3 == d and a3 == 'native':
                    V[(d, 'MSCA', 'native', s3, m3)] = v
    out = ['% Generated by tables/src/build_mmchan_macros.py. Do not edit by hand.',
           '% Source: tables/mmchan_perseed.csv (Sports MSCA Native: tables/mmchan_topk_perseed.csv).']

    def mac(name, val):
        out.append(f'\\newcommand{{\\{name}}}{{{val}}}')

    i0 = lambda x: f'{x:.0f}'
    f2 = lambda x: f'{x:.2f}'
    f1 = lambda x: f'{x:.1f}'

    def msca(d, metric, arm='native'):
        return [V[(d, 'MSCA', arm, s, metric)] for s in SEEDS]

    def allc(fn):
        return [x for d, _ in DS for x in fn(d)]

    def rng(name, xs, fmt):
        mac(f'{name}Min', fmt(min(xs)))
        mac(f'{name}Max', fmt(max(xs)))

    def per_ds(name, fn, fmt):
        for d, D in DS:
            mac(f'{name}{D}', fmt(st.mean(fn(d))))

    share = lambda chs: (lambda d: [100 * sum(V[(d, 'MSCA', 'native', s, f'chS_share_{c}')] for c in chs) for s in SEEDS])
    # ---------------- channel split of the self-message (Native)
    for nm, chs in (('mmcCollab', ['collab']), ('mmcStruct', ['struct']), ('mmcImage', ['image']), ('mmcText', ['text']),
                    ('mmcModal', ['image', 'text']), ('mmcView', ['struct', 'image', 'text'])):
        rng(nm + 'Share', allc(share(chs)), i0)
        per_ds(nm + 'Share', share(chs), i0)
    rng('mmcNegImage', allc(lambda d: [100 * x for x in msca(d, 'chS_negfrac_image')]), f1)
    rng('mmcNegOther', allc(lambda d: [100 * max(V[(d, 'MSCA', 'native', s, f'chS_negfrac_{c}')] for c in ('collab', 'struct', 'text'))
                                       for s in SEEDS]), f1)
    rng('mmcScoreShare', allc(lambda d: [100 * x for x in msca(d, 'S_share_of_s')]), i0)
    # ---------------- removal of the image and text messages of p (closed form) vs the whole quantum
    drop = lambda key: (lambda d: [100 * (V[(d, 'MSCA', 'native', s, 'full:train_top40')] - V[(d, 'MSCA', 'native', s, f'{key}:train_top40')])
                                   for s in SEEDS])
    rng('mmcDropModal', allc(drop('rank_looMM')), i0)
    per_ds('mmcDropModal', drop('rank_looMM'), i0)
    rng('mmcDropAll', allc(drop('rank_loo')), i0)
    per_ds('mmcDropAll', drop('rank_loo'), i0)
    # ---------------- counterfactual: user-side image and text views off (score of a different model, path attribution only)
    cf = lambda d: [100 * (V[(d, 'MSCA', 'native', s, 'full:S_share_of_s')] - V[(d, 'MSCA', 'native', s, 'noMM:S_share_of_s')]) for s in SEEDS]
    rng('mmcCfShareDrop', allc(cf), f1)
    # ---------------- neighbour echo and top-20 slots
    for g, G in (('text', 'Text'), ('image', 'Image'), ('struct', 'Struct')):
        per_ds(f'mmcEcho{G}', lambda d, g=g: msca(d, f'echo_{g}_total'), f2)
        per_ds(f'mmcEchoModal{G}', lambda d, g=g: [V[(d, 'MSCA', 'native', s, f'echo_{g}_image')] + V[(d, 'MSCA', 'native', s, f'echo_{g}_text')]
                                                   for s in SEEDS], f2)
    rng('mmcEchoRand', allc(lambda d: msca(d, 'echo_rand_total')), f2)
    for g, G in (('text', 'Text'), ('image', 'Image'), ('struct', 'Struct')):
        rng(f'mmcEcho{G}', allc(lambda d, g=g: msca(d, f'echo_{g}_total')), f2)
    slot = lambda var: (lambda d: [V[(d, 'MSCA', 'native', s, 'slot_full_any')] - V[(d, 'MSCA', 'native', s, f'slot_{var}_any')] for s in SEEDS])
    per_ds('mmcSlotAll', slot('mAll'), f1)
    per_ds('mmcSlotModal', slot('mMM'), f1)
    rng('mmcSlotAll', allc(slot('mAll')), f1)
    rng('mmcSlotModal', allc(slot('mMM')), f1)
    # ---------------- crowding toward modality neighbours
    for who, W in (('top', 'Top'), ('tgt', 'Tgt'), ('rnd', 'Rnd')):
        per_ds(f'mmcLink{W}', lambda d, who=who: [100 * x for x in msca(d, f'full:link_{who}_mm')], i0)
        per_ds(f'mmcLinkOnly{W}', lambda d, who=who: [100 * x for x in msca(d, f'full:link_{who}_mmonly')], i0)
    gap = lambda d: [100 * ((V[(d, 'MSCA', 'native', s, 'chan_top_image')] + V[(d, 'MSCA', 'native', s, 'chan_top_text')])
                            - (V[(d, 'MSCA', 'native', s, 'chan_tgt_image')] + V[(d, 'MSCA', 'native', s, 'chan_tgt_text')]))
                     / (V[(d, 'MSCA', 'native', s, 'chan_top_total')] - V[(d, 'MSCA', 'native', s, 'chan_tgt_total')]) for s in SEEDS]
    rng('mmcGapModal', allc(gap), i0)
    per_ds('mmcGapModal', gap, i0)
    # ---------------- ID-only LightGCN reference (available seeds)
    def lg(d, metric):
        return [V[k] for k in V if k[0] == d and k[1] == 'LightGCN' and k[4] == metric]
    for d, D in DS:
        mac(f'mmcLgcnSeeds{D}', len(lg(d, 'S_share_of_s')))
        mac(f'mmcMscaShare{D}', i0(100 * st.mean(msca(d, 'S_share_of_s'))))
        mac(f'mmcMscaKeep{D}', f2(st.mean(msca(d, 'full:prop2_ratio'))))
        if not lg(d, 'S_share_of_s'):          # no LightGCN cell for this dataset yet (Sports until add_lgcn_sports.sh)
            sys.stderr.write(f'note: no LightGCN cells for {d}; mmcLgcn* ranges use the other datasets\n')
            continue
        mac(f'mmcLgcnShare{D}', i0(100 * st.mean(lg(d, 'S_share_of_s'))))
        mac(f'mmcLgcnMsgShare{D}', i0(100 * st.mean(lg(d, 'S_share_of_msg'))))
        mac(f'mmcLgcnEgo{D}', i0(100 * st.mean(lg(d, 'ego_share_of_s'))))
        mac(f'mmcLgcnKeep{D}', f2(st.mean(lg(d, 'full:prop2_ratio'))))
        mac(f'mmcLgcnDropAll{D}', i0(100 * st.mean([a - b for a, b in zip(lg(d, 'full:train_top40'), lg(d, 'rank_loo:train_top40'))])))
    rng('mmcLgcnShare', [100 * x for d, _ in DS for x in lg(d, 'S_share_of_s')], i0)
    rng('mmcLgcnMsgShare', [100 * x for d, _ in DS for x in lg(d, 'S_share_of_msg')], i0)
    rng('mmcLgcnEgo', [100 * x for d, _ in DS for x in lg(d, 'ego_share_of_s')], i0)
    rng('mmcLgcnKeep', [x for d, _ in DS for x in lg(d, 'full:prop2_ratio')], f2)
    rng('mmcMscaKeep', allc(lambda d: msca(d, 'full:prop2_ratio')), f2)
    rng('mmcLgcnDropAll', [100 * (a - b) for d, _ in DS for a, b in zip(lg(d, 'full:train_top40'), lg(d, 'rank_loo:train_top40'))], i0)
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from numwords import num_word   # prose count as a word (user rule 2026-10-07)
    mac('mmcLgcnSeedsAll', num_word(sum(len(lg(d, 'S_share_of_s')) for d, _ in DS)))
    # ---------------- counterfactual on the same MSCA checkpoint: user-side item-item views off (collaborative channel only)
    rng('mmcNoViewKeep', allc(lambda d: msca(d, 'collab:prop2_ratio')), f2)

    # ================= top-K loss checkpoints and the EFLEC-style removal (tables/mmchan_topk_perseed.csv, summ3.py)
    TK = ['psl', 'slk', 'ssm']
    for d, _ in DS:   # the Native cells of both summaries come from the same checkpoints and sample
        for s in SEEDS:
            a, b = V[(d, 'MSCA', 'native', s, 'S_share_of_s')], V3[(d, 'native', s, 'S_share_of_s')]
            if abs(a - b) > 1e-9:
                sys.exit(f'Native mismatch between summaries: {d} s{s} {a} {b}')
    t3 = lambda arms, metric, sc=1.0, dl=DS: [sc * V3[(d, a, s, metric)] for d, _ in dl for a in arms for s in SEEDS]
    # top-K losses: the self-message stays in the training score, and positives still crowd the top-40 list
    rng('tkShare', t3(TK, 'S_share_of_s', 100), i0)
    rng('tkSd', t3(TK, 'S_over_sd'), f1)
    rng('tkTopFull', t3(TK, 'full:train_top40', 100), i0)
    rng('tkTopLoo', t3(TK, 'rank_loo:train_top40', 100), i0)
    rng('tkTgt', t3(TK, 'full:tgt_top40', 100), i0)
    rng('mmcTgt', t3(['native'], 'full:tgt_top40', 100), i0)
    rng('mmcTopFull', t3(['native'], 'full:train_top40', 100), i0)
    rng('mmcTopLoo', t3(['native'], 'rank_loo:train_top40', 100), i0)
    # EFLEC-style removal of the collaborative channel only (Native)
    rng('efSLeft', t3(['native'], 'eflec:S_left', 100), i0)
    rng('efSLeftTk', t3(TK, 'eflec:S_left', 100), i0)
    rng('efScoreLeft', t3(['native'], 'eflec:S_left_share_of_s', 100), i0)
    rng('efAttnLeft', t3(['native'], 'eflec:attn_left', 100), i0)
    rng('efTop', t3(['native'], 'rank_looEflec:train_top40', 100), i0)
    rng('efTopTk', t3(TK, 'rank_looEflec:train_top40', 100), i0)
    gap = [100 * (V3[(d, 'native', s, 'rank_looEflec:train_top40')] - V3[(d, 'native', s, 'rank_loo:train_top40')])
           / (V3[(d, 'native', s, 'full:train_top40')] - V3[(d, 'native', s, 'rank_loo:train_top40')]) for d, _ in DS for s in SEEDS]
    rng('efDropLeft', gap, i0)       # share of the full-removal top-40 drop that the collaborative removal leaves
    # ================= original Table I plug-in checkpoints (tables/mmchan_plg_perseed.csv, summ_plg.py)
    with open(T / 'mmchan_plg_perseed.csv', newline='', encoding='utf-8') as f:
        VP = {(r['dataset'], r['arm'], int(r['seed']), r['metric']): float(r['value']) for r in csv.DictReader(f)}
    PL5 = ['mg', 'damrs', 'ina', 'mdvt', 'ultragcnli']
    tp = lambda arms, metric, sc=1.0: [sc * VP[(d, a, s, metric)] for d, _ in DS_PLG for a in arms for s in SEEDS]
    rng('plgShare', tp(PL5, 'S_share_of_s', 100), i0)                       # five plug-ins other than VI-MMRec
    rng('plgVioShare', tp(['vimmrec'], 'S_share_of_s', 100), i0)
    rng('plgTopFull', tp(PL5 + ['vimmrec'], 'full:train_top40', 100), i0)
    rng('plgVioTopFull', tp(['vimmrec'], 'full:train_top40', 100), i0)
    rng('plgTgt', tp(PL5 + ['vimmrec'], 'full:tgt_top40', 100), i0)
    rng('plgVioTgt', tp(['vimmrec'], 'full:tgt_top40', 100), i0)
    # objectives together: five plug-ins + three top-K losses (share), all six plug-ins + three losses (top-40);
    # Baby, Pantry, Scientific only (no plug-in cells for Sports), so the top-K part is restricted to the same datasets
    rng('objShare', tp(PL5, 'S_share_of_s', 100) + t3(TK, 'S_share_of_s', 100, DS_PLG), i0)
    rng('objTopFull', tp(PL5, 'full:train_top40', 100) + t3(TK, 'full:train_top40', 100, DS_PLG), i0)   # Table I rows only
    rng('objTgt', tp(PL5, 'full:tgt_top40', 100) + t3(TK, 'full:tgt_top40', 100, DS_PLG), i0)
    for d, D in DS:
        for nm, metric in (('mmcTopFull', 'full:train_top40'), ('efTop', 'rank_looEflec:train_top40'),
                           ('mmcTopLoo', 'rank_loo:train_top40'), ('mmcTgt', 'full:tgt_top40')):
            mac(f'{nm}{D}', i0(st.mean([100 * V3[(d, 'native', s, metric)] for s in SEEDS])))

    mine = set(re.findall(r'\\newcommand\{\\([A-Za-z]+)\}', '\n'.join(out)))
    for f in T.glob('macros_*.tex'):
        if f.name == OUT.name:
            continue
        clash = mine & set(re.findall(r'\\newcommand\{\\([A-Za-z]+)\}', f.read_text(encoding='utf-8')))
        if clash:
            sys.exit(f'macro names also in {f.name}: {sorted(clash)}')
    bad = [n for n in mine if re.search(r'\d', n)]
    if bad:
        sys.exit(f'digits in macro names: {bad}')
    OUT.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print('wrote', OUT, len(mine), 'macros')


if __name__ == '__main__':
    main()
