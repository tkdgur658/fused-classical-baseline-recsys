"""Prose macros of the post hoc power sentence on the post-fusion margin (revision log 18-4, 2026-10-16). Numbers are never typed by hand.

Input   tables/src/data/power_fusion_s4.json   written by tables/src/power_fusion_s4.py; view "old" = the existing fusion cells
                                               (tables/src/data/fusion_cells.csv, the numbers of the manuscript, kept by decision (a))
Output  tables/macros_power.tex
Measure per dataset: test Recall@20, MSCA + MES (+)F minus MSCA (+)F, paired over seeds 1-5 (the four tuned datasets);
MDE = minimum detectable effect at 80% power (two-sided paired t, alpha .05, noncentral t, observed SD of the differences);
equivalence = TOST within the margin +-0.002 Recall@20 at alpha .05. Post hoc, not pre-registered.
Usage: python -s tables/src/build_power_macros.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from numwords import num_word  # noqa: E402

NAME = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports'}


def join(xs):
    xs = list(xs)
    if len(xs) == 1:
        return xs[0]
    if len(xs) == 2:
        return f'{xs[0]} and {xs[1]}'
    return ', '.join(xs[:-1]) + f', and {xs[-1]}'


def main():
    j = json.load(open(ROOT / 'src' / 'data' / 'power_fusion_s4.json', encoding='utf-8'))
    v = j['views']['old']
    assert all(r['n'] == 5 for r in v.values()), {d: r['n'] for d, r in v.items()}
    mde = [r['mde_80'] for r in v.values()]
    eq = [NAME[d] for d, r in v.items() if r['tost_pass']]
    phrase = f'{join(eq)} alone' if len(eq) == 1 else (join(eq) if eq else 'none of the datasets')
    mac = [
        '% Generated by tables/src/build_power_macros.py from tables/src/data/power_fusion_s4.json, view "old" (revision log 18-4). Do not edit by hand.',
        '% POST HOC: power and equivalence (TOST) of the post-fusion margin MSCA + MES (+)F minus MSCA (+)F, test Recall@20, seeds 1-5.',
        f'\\newcommand{{\\pwMdeMin}}{{{min(mde):.4f}}}',
        f'\\newcommand{{\\pwMdeMax}}{{{max(mde):.4f}}}',
        f'\\newcommand{{\\pwPower}}{{{round(100 * j["power"])}}}',
        f'\\newcommand{{\\pwMargin}}{{{j["margin"]:g}}}',
        f'\\newcommand{{\\pwNSeeds}}{{{num_word(next(iter(v.values()))["n"])}}}',
        f'\\newcommand{{\\pwNDs}}{{{num_word(len(v))}}}',
        f'\\newcommand{{\\pwEquivDs}}{{{phrase}}}',
    ]
    (ROOT / 'macros_power.tex').write_text('\n'.join(mac) + '\n', encoding='utf-8', newline='\n')
    print('\n'.join(mac))
    for d, r in v.items():
        print(d, f"mde {r['mde_80']:.5f} tost_p {r['tost_p']:.4f} pass {r['tost_pass']}")


if __name__ == '__main__':
    main()
