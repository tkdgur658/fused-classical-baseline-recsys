"""Build tables/table_cohsmo.tex (Table I-style blocks of COHESION and SMORE: XRE, the five plug-ins of Table I, Native)
and tables/macros_cohsmo.tex from tables/cohsmo_perseed.csv (collect_cohsmo.py). Numbers are never typed by hand.

Each cell: mean over seeds 1-5 with the standard deviation over seeds (one run per seed); the best mean of each block and
column is in bold. A dataset column is printed only when every row of both blocks has five seeds on it.
The top-K loss rows (SL@K, PSL, SSM) of tables/cohsmo_topk_perseed.csv enter the best-mean macros (csNBest, csOtherLed)
cell by cell once a cell has five seeds, the same rule as the bold marks of Table I (build_table1_main.py), so the prose
and the bold marks agree. csTopKIn says how many top-K cells (of 3 rows x the macro columns x 2 backbones) are complete.
Revision 2026-10-08 (MES replaces XRE): the proposed row of both blocks is MES from tables/src/mes_source.py
(tables/mes_perseed.csv, or the PROVISIONAL stand-in cohsmo_perseed.csv row XRE = E + R + A). Its cells and every macro
derived from it (csNBest, csGain*, csGainList*, csOtherLed, csNOtherLed) are wrapped in \\tbd{} (red) while provisional;
csNCols, csNDs, csDsPhrase, csTopKIn, csTopKAll and csFinishedPhrase do not depend on it. Lines 'cohsmo:' of
tables/claims_check.txt are rewritten here.
Usage: python -s tables/src/build_table_cohsmo.py
"""
import csv
import statistics as st
from pathlib import Path

import mes_source

ROOT = Path(__file__).resolve().parents[1]
DS = [('baby', 'Baby'), ('pantry', 'Pantry'), ('scientific', 'Scientific'), ('sports', 'Sports')]
BACKBONES = [('COHESION', 'COHESION~\\cite{xu2025cohesion}'), ('SMORE', 'SMORE~\\cite{ong2025smore}')]
ROWS = [('MES', 'Proposed (MES)'), ('INA', 'INA-style~\\cite{iimrec}'), ('MDVT', 'MDVT~\\cite{mdvt}'), ('MG', 'MG~\\cite{zhong2024mg}'),
        ('DA-MRS', 'DA-MRS~\\cite{xu2024damrs}'), ('UltraGCN-LI', 'UltraGCN $\\mathcal{L}_I$~\\cite{mao2021ultragcn}'),
        ('Native', None)]   # printed labels as Table I (2026-10-06): backbone row = backbone name
TOPK_ROWS = [('SL@K', 'SL@$K$~\\cite{yang2025slk}'), ('PSL', 'PSL~\\cite{yang2024psl}'), ('SSM', 'SSM~\\cite{wu2024ssm}')]


def main():
    V = {}
    for name in ('cohsmo_perseed.csv', 'cohsmo_topk_perseed.csv'):
        if not (ROOT / name).exists():
            continue
        for r in csv.DictReader(open(ROOT / name, encoding='utf-8')):
            if r['row'] == 'XRE':
                continue   # the old XRE row enters only as the provisional MES stand-in (mes_source.py)
            V.setdefault((r['backbone'], r['row'], r['dataset']), []).append((float(r['r20']), float(r['n20'])))
    PROV = set()   # (backbone, dataset) whose MES cell is provisional
    for b, _ in BACKBONES:
        for d, _ in DS:
            sv = mes_source.seeds(b, d)
            if sv:
                V[(b, 'MES', d)] = [(sv[k]['r20'], sv[k]['n20']) for k in sorted(sv)]
            if mes_source.is_provisional(b, d):
                PROV.add((b, d))
    ds = [(d, D) for d, D in DS if all(len(V.get((b, k, d), [])) == 5 for b, _ in BACKBONES for k, _ in ROWS)]
    m = {key: (st.mean(x[0] for x in v), st.mean(x[1] for x in v), st.stdev(x[0] for x in v), st.stdev(x[1] for x in v))
         for key, v in V.items() if len(v) == 5}
    ALL = ROWS + [r for r in TOPK_ROWS]
    best = {(b, d, i): max((f'{m[(b, k, d)][i]:.4f}' for k, _ in ALL if (b, k, d) in m), key=float)
            for b, _ in BACKBONES for d, _ in ds for i in (0, 1)}
    best_tab = {(b, d, i): max(f'{m[(b, k, d)][i]:.4f}' for k, _ in ROWS) for b, _ in BACKBONES for d, _ in ds for i in (0, 1)}

    def cell(b, k, d, i):
        mu, sd = m[(b, k, d)][i], m[(b, k, d)][i + 2]
        body = f'{mu:.4f}' + f'{{\\scriptsize$\\pm${sd:.4f}}}'.replace('0.', '.', 1)
        body = f'\\textbf{{{body}}}' if f'{mu:.4f}' == best_tab[(b, d, i)] else body
        return mes_source.tbd(body, k == 'MES' and (b, d) in PROV)

    note = mes_source.caption_note([b for b, _ in BACKBONES], [d for d, _ in ds])
    lines = ['% Generated by tables/src/build_table_cohsmo.py from tables/cohsmo_perseed.csv. Do not edit numbers by hand.',
             mes_source.comment([b for b, _ in BACKBONES], [d for d, _ in DS]),
             '\\begin{table*}[t]',
             '\\caption{Recall@20 and NDCG@20 of MES and the plug-in objectives of Table~\\ref{tab:main} on COHESION and SMORE. '
             'Each cell reports the mean over seeds 1--5 with the standard deviation over seeds. All rows of a block share the '
             'author configuration of the backbone and the common training protocol, and the plug-ins keep the values of '
             'Table~\\ref{tab:main}. MES uses $\\lambda=0.1$ and $K=40$ on both backbones without tuning. '   # 2026-10-10 user decision
             'In each block and column, the best mean is in bold.' + note + '}',
             '\\label{tab:cohsmo}', '\\centering', '\\footnotesize', '\\setlength{\\tabcolsep}{3.5pt}',
             '\\begin{tabular}{l' + 'cc' * len(ds) + '}', '\\toprule',
             ' & ' + ' & '.join(f'\\multicolumn{{2}}{{c}}{{{n}}}' for _, n in ds) + ' \\\\',
             ''.join(f'\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}' for i in range(len(ds))),
             'Objective & ' + ' & '.join('R@20 & N@20' for _ in ds) + ' \\\\']
    for b, bl in BACKBONES:
        lines += ['\\midrule', f'\\multicolumn{{{1 + 2 * len(ds)}}}{{l}}{{\\textit{{Backbone: {bl}}}}} \\\\']
        for k, label in ROWS:
            lines.append(f'{label or b} & ' + ' & '.join(cell(b, k, d, i) for d, _ in ds for i in (0, 1)) + ' \\\\')
            if k == 'MES':
                lines.append('\\midrule')
    lines += ['\\bottomrule', '\\end{tabular}', '\\end{table*}', '']
    (ROOT / 'table_cohsmo.tex').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    out = ['% Generated by tables/src/build_table_cohsmo.py. Do not edit by hand.',
           mes_source.comment([b for b, _ in BACKBONES], [d for d, _ in DS])]
    prov_all = any((b, d) in PROV for b, _ in BACKBONES for d, _ in ds)
    T = (lambda x: mes_source.tbd(x)) if prov_all else (lambda x: x)
    words = {i: w for i, w in enumerate(['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine',
                                         'ten', 'eleven', 'twelve', 'thirteen', 'fourteen', 'fifteen', 'sixteen'])}
    n_cols = 2 * len(ds) * len(BACKBONES)
    n_best = sum(1 for b, _ in BACKBONES for d, _ in ds for i in (0, 1) if f"{m[(b, 'MES', d)][i]:.4f}" == best[(b, d, i)])
    out.append(f'\\newcommand{{\\csNCols}}{{{n_cols}}}')
    out.append(f'\\newcommand{{\\csNBest}}{{{T(str(n_best))}}}')
    out.append(f'\\newcommand{{\\csNDs}}{{{words[len(ds)]}}}')
    def join(xs):
        return xs[0] if len(xs) == 1 else (' and '.join(xs) if len(xs) == 2 else ', '.join(xs[:-1]) + ', and ' + xs[-1])
    out.append(f'\\newcommand{{\\csDsPhrase}}{{{join([D for _, D in ds])}}}')
    for b, _ in BACKBONES:
        gl = []
        pb = any((b, d) in PROV for d, _ in ds)
        for d, D in ds:
            g = 100 * (m[(b, 'MES', d)][0] / m[(b, 'Native', d)][0] - 1)
            out.append(f'\\newcommand{{\\csGain{b.title()}{D}}}{{{mes_source.tbd(f"{g:.1f}".replace("-", "$-$"), (b, d) in PROV)}}}')
            gl.append(f'{g:.1f}\\%'.replace('-', '$-$'))
        out.append(f'\\newcommand{{\\csGainList{b.title()}}}{{{mes_source.tbd(join(gl), pb)}}}')
    # columns in which XRE is not the best mean: 'INA-style attains the best Recall@20 of COHESION on Baby'
    name = {k: lab.split('~')[0].replace('+ ', '', 1) if lab else None for k, lab in ALL}   # None: backbone row
    led = []
    for b, _ in BACKBONES:
        for d, D in ds:
            for i, M in ((0, 'Recall@20'), (1, 'NDCG@20')):
                if f"{m[(b, 'MES', d)][i]:.4f}" != best[(b, d, i)]:
                    top = [name[k] or b for k, _ in ALL if (b, k, d) in m and f'{m[(b, k, d)][i]:.4f}' == best[(b, d, i)]]
                    led.append(f"{' and '.join(top)} attains the best {M} of {b} on {D}")
    out.append(f'\\newcommand{{\\csOtherLed}}{{{T(join(led) if led else "no other row leads a column")}}}')
    out.append(f'\\newcommand{{\\csNOtherLed}}{{{T(words[len(led)])}}}')
    n_topk = sum(1 for b, _ in BACKBONES for d, _ in ds for k, _ in TOPK_ROWS if (b, k, d) in m)
    out.append(f'\\newcommand{{\\csTopKIn}}{{{n_topk}}}')
    out.append(f'\\newcommand{{\\csTopKAll}}{{{len(TOPK_ROWS) * len(ds) * len(BACKBONES)}}}')
    # opening of the prose sentence on csNBest: the count covers the finished cells only while top-K cells are missing
    out.append('\\newcommand{\\csFinishedPhrase}{' + ('Among the finished rows, '
               if n_topk < len(TOPK_ROWS) * len(ds) * len(BACKBONES) else '') + '}')
    (ROOT / 'macros_cohsmo.tex').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    cc = ROOT / 'claims_check.txt'
    keep = [x for x in (cc.read_text(encoding='utf-8').splitlines() if cc.exists() else []) if not x.startswith('cohsmo:')]
    gains = {b: [round(100 * (m[(b, 'MES', d)][0] / m[(b, 'Native', d)][0] - 1), 1) for d, _ in ds] for b, _ in BACKBONES}
    keep += [f'cohsmo: MES (provisional={prov_all}) best mean in {n_best} of {n_cols} COHESION/SMORE columns; other leaders '
             f'{led or "none"}; R@20 gain % over the backbone {gains}; all positive: '
             f'{all(g > 0 for v in gains.values() for g in v)} (prose: MES raises the mean Recall@20 of COHESION and SMORE '
             f'on all csNDs datasets)']
    cc.write_text('\n'.join(keep) + '\n', encoding='utf-8', newline='\n')
    print('datasets', [d for d, _ in ds], 'MES best in', n_best, 'of', n_cols, 'columns', '| top-K cells in', n_topk)


if __name__ == '__main__':
    main()
