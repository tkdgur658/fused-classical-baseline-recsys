"""Collect the gradient split of the entry pair on the actual masked XRE (reviewer control E4) and write its macros.

Question: which gradient of the entry pair softplus(s(u,D) - s(u,p)) of XRE carries its gain, the one raising the held-out
positive p or the one lowering the displaced list occupant D? Arms (masked view, anchor term, retention, lambda 0.1, K 40,
2-fold alternation, held rows and 1/B scaling all unchanged; only the entry-pair gradient changes, forward values are equal):
  pos-only  <ds>_xres_xrepos_l010_k40   softplus(sg(s(u,D)) - s(u,p))   (gradient raising p only)
  occ-only  <ds>_xres_xreocc_l010_k40   softplus(s(u,D) - sg(s(u,p)))   (gradient lowering D only)
Reference: XRE <ds>_xres_xre_l010_k40 (Table I / Table III MSCA + XRE runs, qxs2/A), same seed.
Runs: HOST_A <RUN_ROOT_B>/P04_e4e5/runs_e4/xres (branch xres-gsplit 70f2d4f, parent 406a7a7; unit test 51/51 PASS:
flag off bitwise equal to the parent; README.txt and collect_e4e5.py in the work dir; notes in
<TOOLS>/hyp_figs_20261007/E1E2_RUNS.md 'E4/E5'), MSCA, Pantry and Scientific, seeds 1-5, one run per seed.
The per-seed CSV is written by collect_e4e5.py on HOST_A (one row per contrast x dataset x seed; it lists only finished runs).
Outputs
  tables/e4_perseed.csv   copy of <RUN_ROOT_B>/P04_e4e5/e4_perseed.csv (contrast, dataset, seed, ref/arm/d R@20 and
                          N@20, GPUs, best epoch, run paths)
  tables/macros_e4.tex    macro names eg..., no digits; D in Pantry, Scientific; X in R (Recall@20), N (NDCG@20);
                          C in OccXre (occ-only - XRE), PosXre (pos-only - XRE), OccPos (occ-only - pos-only):
    eg<C><X>Diff<D>   mean paired difference (signed, 4 dp, the format of macros_hyp_forest.tex)
    eg<C><X>CI<D>     95% paired t-interval (df n - 1)
    eg<C><X>P<D>      two-sided paired t-test p (scipy.stats.ttest_rel, 3 dp, '$<$0.001' below)
    eg<C><X>T<D>      paired t (2 dp)
    eg<C><X>Low<D>    seeds with a negative difference (k/n);  eg<C><X>High<D>  seeds with a positive difference (k/n)
    eg<C>Seeds<D>     number of paired seeds (digit);  egN<D> smaller seed count of the two arms (digit)
    egMean<A><X><D>   arm means over the paired seeds of that arm (A in Xre, Pos, Occ; 4 dp, leading zero dropped)
    egOrderDs         datasets on which occ-only > XRE > pos-only in mean Recall@20 (the order of Fig. h_gradsplit)
    egOccPosAllDs     datasets on which occ-only beats pos-only in Recall@20 and in NDCG@20 on every paired seed
    egOrderNDs        word count of egOrderDs;  egSeedPhrase  'five seeds on Pantry and Scientific' or the counts
    egSeedNote        caption suffix: empty with seeds 1-5 everywhere, else ', over ' + egSeedPhrase
Usage (repository root): python -s tables/src/collect_e4.py               (ssh to HOST_A, copy, then macros)
                         python -s tables/src/collect_e4.py --no-collect  (macros from tables/e4_perseed.csv)
Then: python -s figures/src/fig_h_gradsplit.py (adds the masked-XRE arms as open markers).
"""
import csv
import math
import re
import statistics as st
import subprocess
import sys
from pathlib import Path

from scipy import stats

ROOT = Path(__file__).resolve().parents[2]
TABLES = ROOT / 'tables'
OUT = TABLES / 'e4_perseed.csv'
MAC = TABLES / 'macros_e4.tex'
REMOTE = '<RUN_ROOT_B>/P04_e4e5/e4_perseed.csv'
DS = [('pantry', 'Pantry'), ('scientific', 'Scientific')]
CON = [('OccXre', 'occ-only - XRE'), ('PosXre', 'pos-only - XRE'), ('OccPos', 'occ-only - pos-only')]
WORDS = 'none one two three four five'.split()


def collect():
    subprocess.run(['ssh', '-o', 'BatchMode=yes', 'HOST_A', 'python3 <RUN_ROOT_B>/P04_e4e5/collect_e4e5.py'],
                   check=True, capture_output=True)
    txt = subprocess.run(['ssh', '-o', 'BatchMode=yes', 'HOST_A', f'cat {REMOTE}'], check=True, capture_output=True,
                         text=True).stdout
    OUT.write_text(txt.replace('\r\n', '\n'), encoding='utf-8', newline='\n')
    print('wrote', OUT, len(txt.strip().splitlines()) - 1, 'rows')


def fmt(v):
    return f'{v:+.4f}'.replace('-', '$-$')


def phrase(names):
    if not names:
        return 'none of the datasets'
    return names[0] if len(names) == 1 else ', '.join(names[:-1]) + (' and ' if len(names) == 2 else ', and ') + names[-1]


def macros():
    rows = list(csv.DictReader(open(OUT, encoding='utf-8')))
    P = {}
    for r in rows:
        key = (r['contrast'], r['dataset'], int(r['seed']))
        assert key not in P, f'duplicate {key} (one run per seed, no replicates)'
        if r['ref_gpu'] != r['arm_gpu']:   # device check (non-fatal): reference and arm should share one device
            print(f'WARNING {key}: reference and arm report different devices', file=sys.stderr)
        P[key] = r
    out = ['% Generated by tables/src/collect_e4.py from tables/e4_perseed.csv (gradient split of the entry pair on the',
           '% masked XRE, reviewer control E4; MSCA, one run per seed). Do not edit by hand. Differences are arm minus',
           '% reference on the same seed; CI = 95% paired t-interval (df n - 1); P = two-sided paired t-test (scipy ttest_rel).']

    def mac(n, v):
        assert re.fullmatch(r'[A-Za-z]+', n), n
        out.append(f'\\newcommand{{\\{n}}}{{{v}}}')
    order, nseeds, occ_all = [], {}, []
    for d, D in DS:
        seeds = {c: sorted(s for (cc, dd, s) in P if cc == name and dd == d) for c, name in CON}
        assert seeds['OccXre'] and seeds['PosXre'], f'no runs for {d}'
        mac(f'egN{D}', min(len(seeds['OccXre']), len(seeds['PosXre'])))
        nseeds[D] = (len(seeds['PosXre']), len(seeds['OccXre']))
        means = {}
        for c, name in CON:
            n = len(seeds[c])
            mac(f'eg{c}Seeds{D}', n)
            for X, col in (('R', 'r20'), ('N', 'n20')):
                a = [float(P[(name, d, s)][f'arm_{col}']) for s in seeds[c]]
                b = [float(P[(name, d, s)][f'ref_{col}']) for s in seeds[c]]
                dd = [x - y for x, y in zip(a, b)]
                mu = st.mean(dd)
                if n >= 2:
                    sd = st.stdev(dd)
                    h = stats.t.ppf(0.975, n - 1) * sd / math.sqrt(n)
                    tt = stats.ttest_rel(a, b)
                    p, t = float(tt.pvalue), float(tt.statistic)
                else:
                    h, p, t = float('nan'), float('nan'), float('nan')
                mac(f'eg{c}{X}Diff{D}', fmt(mu))
                mac(f'eg{c}{X}CI{D}', f'[{fmt(mu - h)}, {fmt(mu + h)}]')
                mac(f'eg{c}{X}P{D}', f'{p:.3f}' if p >= 0.001 else '$<$0.001')
                mac(f'eg{c}{X}T{D}', f'{t:.2f}'.replace('-', '$-$'))
                mac(f'eg{c}{X}Low{D}', f'{sum(x < 0 for x in dd)}/{n}')
                mac(f'eg{c}{X}High{D}', f'{sum(x > 0 for x in dd)}/{n}')
                print(f'{D:10s} {c} {X} n {n} mean {mu:+.5f} CI [{mu - h:+.5f}, {mu + h:+.5f}] t {t:+.2f} p {p:.4f} '
                      f'low {sum(x < 0 for x in dd)}/{n} d {[round(x, 4) for x in dd]}')
                if c in ('OccXre', 'PosXre'):
                    means[(c[:3], X)] = st.mean(a)
                    means[('Xre', X, c)] = st.mean(b)
                if c == 'OccPos' and n >= 1 and all(x > 0 for x in dd):
                    occ_all.append((D, X))
        for X in ('R', 'N'):
            mac(f'egMeanXre{X}{D}', f"{means[('Xre', X, 'PosXre')]:.4f}".replace('0.', '.', 1))
            mac(f'egMeanPos{X}{D}', f"{means[('Pos', X)]:.4f}".replace('0.', '.', 1))
            mac(f'egMeanOcc{X}{D}', f"{means[('Occ', X)]:.4f}".replace('0.', '.', 1))
        if means[('Occ', 'R')] > means[('Xre', 'R', 'OccXre')] and means[('Xre', 'R', 'PosXre')] > means[('Pos', 'R')]:
            order.append(D)
    mac('egOccPosAllDs', phrase([D for _, D in DS if (D, 'R') in occ_all and (D, 'N') in occ_all]))
    mac('egOrderDs', phrase(order))
    mac('egOrderNDs', WORDS[len(order)])
    if all(v == (5, 5) for v in nseeds.values()):
        sp = 'five seeds on ' + phrase([D for _, D in DS])
    else:
        sp = ' and '.join(f'{WORDS[min(v)]} seeds on {D}' if v[0] == v[1] else
                          f'{WORDS[v[0]]} and {WORDS[v[1]]} seeds of the two arms on {D}' for D, v in nseeds.items())
    mac('egSeedPhrase', sp)
    # caption note: empty when both arms have seeds 1-5 on both datasets (the caption already says seeds 1-5)
    mac('egSeedNote', '' if all(v == (5, 5) for v in nseeds.values()) else ', over ' + sp)
    MAC.write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print('wrote', MAC, '| order occ > XRE > pos on', order, '| seeds', nseeds)


def main():
    if '--no-collect' not in sys.argv:
        collect()
    macros()


if __name__ == '__main__':
    main()
