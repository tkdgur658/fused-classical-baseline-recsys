"""Prose macros of the post-hoc paragraph on the stochastic re-evaluation gate of the fused baseline (supplement Section supp:fc,
revision log 18-D decision 8, 2026-10-16): tables/macros_sotafill.tex (prefix sf). Numbers are never typed by hand.
Inputs:
  tables/src/data/sotafill_noise_diag.csv   copy of HOST_A <RUN_ROOT>/study/SOTAFILL diagnosis (study/PREREG_SOTAFILL.md section 6): each stored
      checkpoint re-evaluated n_draws = 20 times with random seeds 9001-9020, r20_sd = standard deviation of the recomputed test
      Recall@20, frac_pass_tol = share of the draws with |recomputed - reported| <= 5e-4 in Recall@20 and NDCG@20 (the gate of
      TABLE_FUSION tf_queue.py, unchanged). The ten jobs are the eight seeds missing from the fused block of Table tab:sota plus two
      included seeds as controls (COHESION Scientific seed 5, LGMRec Pantry seed 1).
  tables/src/data/fusion_cells_9ds_mes.csv  gate_ok = 1 rows: a diagnosed seed is `missing` when it has no such row, `included` otherwise
  tables/sigtests_counts.csv                 family 'F (Fig. 1, ...)' (build_sigcounts.py): test of F against the unfused model per pair
  tables/src/data/fusion_test.json           datasets of the pairwise test of MSCA + MES (+)F against MSCA (+)F; each of these cells
                                             must hold five seeds in both rows (asserted)
Usage: python tables/src/build_sotafill_macros.py   (after build_sigcounts.py)
"""
import csv
import json
from pathlib import Path

from numwords import num_word

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'src' / 'data'
TOL = '0.0005'   # gate tolerance of TABLE_FUSION (tf_queue.py), PREREG_SOTAFILL.md section 1
MODEL = {'cohesion': 'COHESION', 'lgmrec': 'LGMRec'}


def main():
    gate = {}
    allrows = {}
    for r in csv.DictReader(open(DATA / 'fusion_cells_9ds_mes.csv', newline='', encoding='utf-8')):
        if not r['fused_r20']:
            continue
        k = (r['model'], r['dataset'], int(r['seed']))
        allrows[k] = r
        if r.get('gate_ok', '1') == '1':
            gate[k] = r
    miss, inc = [], []
    diag = list(csv.DictReader(open(DATA / 'sotafill_noise_diag.csv', newline='', encoding='utf-8')))
    for r in diag:
        k = (MODEL[r['model']], r['dataset'], int(r['seed']))
        (inc if k in gate else miss).append(r)
    assert len(diag) == 10 and len(miss) == 8 and len(inc) == 2, (len(diag), len(miss), len(inc))
    assert {r['n_draws'] for r in diag} == {'20'}
    pairs = {(r['model'], r['dataset']) for r in miss}
    sd = [float(r['r20_sd']) for r in diag]
    pm = [100 * float(r['frac_pass_tol']) for r in miss]
    pi = [100 * float(r['frac_pass_tol']) for r in inc]
    # the pairwise fused test of MSCA + MES against MSCA uses five seeds of both rows in every dataset
    ft = json.load(open(DATA / 'fusion_test.json', encoding='utf-8'))
    for d in ft['datasets']:
        for m in ('MSCA', 'MSCA+MES'):
            assert sum((m, d, s) in gate for s in range(1, 6)) == 5 and sum((m, d, s) in allrows for s in range(1, 6)) == 5, (m, d)
    # test of F against the unfused model: pairs with fewer than five seeds
    fam = [r for r in csv.DictReader(open(ROOT / 'sigtests_counts.csv', newline='', encoding='utf-8')) if r['family'].startswith('F (')]
    low = [r for r in fam if int(r['n']) < 5]
    assert len(fam) == 50 and {(r['contrast'].split(' ')[0], r['dataset']) for r in low} == {(MODEL[m], d) for m, d in pairs}
    low_sig = [r for r in low if int(r['reject']) and float(r['diff']) > 0]
    M = ['% Generated by tables/src/build_sotafill_macros.py from tables/src/data/sotafill_noise_diag.csv, fusion_cells_9ds_mes.csv, '
         'fusion_test.json and tables/sigtests_counts.csv. Do not edit by hand.',
         f'\\newcommand{{\\sfNMissSeeds}}{{{num_word(len(miss))}}}',
         f'\\newcommand{{\\sfNIncSeeds}}{{{num_word(len(inc))}}}',
         f'\\newcommand{{\\sfNDraws}}{{{diag[0]["n_draws"]}}}',
         f'\\newcommand{{\\sfTol}}{{{TOL}}}',
         f'\\newcommand{{\\sfSdMin}}{{{min(sd):.4f}}}',
         f'\\newcommand{{\\sfSdMax}}{{{max(sd):.4f}}}',
         f'\\newcommand{{\\sfPassMissMin}}{{{round(min(pm))}}}',
         f'\\newcommand{{\\sfPassMissMax}}{{{round(max(pm))}}}',
         f'\\newcommand{{\\sfPassIncMin}}{{{round(min(pi))}}}',
         f'\\newcommand{{\\sfPassIncMax}}{{{round(max(pi))}}}',
         f'\\newcommand{{\\sfFtNDs}}{{{num_word(len(ft["datasets"]))}}}',
         f'\\newcommand{{\\sfFtSeeds}}{{{num_word(5)}}}',   # asserted above: five seeds in both rows of every dataset
         f'\\newcommand{{\\sfNPairsAll}}{{{len(fam)}}}',
         f'\\newcommand{{\\sfNLow}}{{{num_word(len(low))}}}',
         f'\\newcommand{{\\sfLowMin}}{{{num_word(min(int(r["n"]) for r in low))}}}',
         f'\\newcommand{{\\sfLowMax}}{{{num_word(max(int(r["n"]) for r in low))}}}',
         f'\\newcommand{{\\sfNLowSig}}{{{"all " if len(low_sig) == len(low) else ""}{num_word(len(low_sig))}}}', '']
    (ROOT / 'macros_sotafill.tex').write_text('\n'.join(M), encoding='utf-8', newline='\n')
    print('\n'.join(M))
    print('missing', sorted((r['model'], r['dataset'], r['seed']) for r in miss))
    print('included', sorted((r['model'], r['dataset'], r['seed']) for r in inc))


if __name__ == '__main__':
    main()
