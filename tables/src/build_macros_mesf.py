"""Build tables/macros_mesf.tex: the MES-F result of PREREG_MESF (H_F verdict, test Recall@20, seeds 1-5) and the post-hoc
alpha check (seed-1 validation Recall@20 only, outside the preregistered plan). Added 2026-10-16 (revision log 15).
Sources (copies of study/results, written by study/MESF/code/mesf_verdict.py sha db840988 and mesf_posthoc_gate.py):
  tables/src/data/mesf_hf_verdict.json, tables/src/data/mesf_posthoc_gate.json. Numbers are never typed by hand.
Usage: python tables/src/build_macros_mesf.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'src' / 'data'
DS = ['baby', 'pantry', 'scientific', 'sports']
NAME = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports'}
WORD = ['none', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten']
BS = chr(92)


def m(name, val):
    return BS + 'newcommand{' + BS + name + '}{' + val + '}'


def signed(x):
    return f'${x:+.4f}$'.replace('$-', '$' + '-')


def join(items):
    return items[0] if len(items) == 1 else ', '.join(items[:-1]) + (',' if len(items) > 2 else '') + ' and ' + items[-1]


def main():
    v = json.load(open(DATA / 'mesf_hf_verdict.json', encoding='utf-8'))
    g = json.load(open(DATA / 'mesf_posthoc_gate.json', encoding='utf-8'))
    rows = {r['ds']: r for r in v['rows']}
    assert sorted(rows) == DS and v['H_F'] == 'FAIL'
    below_sig = [d for d in DS if rows[d]['p_holm'] < .05 and rows[d]['d_msca'] < 0]
    vs_mesf = [rows[d]['mesf'] - rows[d]['mes_f'] for d in DS]
    ph_beat = [d for d in DS if max(g['table'][d]['vals']['0.1'], g['table'][d]['vals']['0.2']) > g['table'][d]['mes']]
    ph_below = [d for d in DS if max(g['table'][d]['vals']['0.1'], g['table'][d]['vals']['0.2']) < g['table'][d]['mes_plus']]
    ph_above = [d for d in DS if d not in ph_below]
    out = ['% Generated by tables/src/build_macros_mesf.py from mesf_hf_verdict.json and mesf_posthoc_gate.json. Do not edit by hand.',
           m('mfDiffList', join([signed(rows[d]['d_msca']) for d in DS])),
           m('mfNBelowSig', WORD[len(below_sig)]),
           m('mfBelowSigDs', join([NAME[d] for d in below_sig])),
           m('mfNGeMesF', WORD[v['n_ge_mes_f']]),
           m('mfNSig', WORD[v['n_sig']]),
           m('mfVsMesFMin', signed(min(vs_mesf))),
           m('mfVsMesFMax', signed(max(vs_mesf))),
           m('mfPhNBeatMes', WORD[len(ph_beat)]),
           m('mfPhBelowDs', join([NAME[d] for d in ph_below])),
           m('mfPhAboveDs', join([NAME[d] for d in ph_above])),
           '']
    (ROOT / 'macros_mesf.tex').write_text('\n'.join(out), encoding='utf-8', newline='\n')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
