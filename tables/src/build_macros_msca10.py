"""revision log 31 (MSCA10, author decision): prose macros and the margin CSV of the preregistered ten-seed extension of the
fused contrast  MSCA + MES (+) fusion  minus  MSCA (+) fusion  (PREREG_MSCA10, sha256 d54733a2...).  Writes tables/macros_msca10.tex
(prefix xn) and tables/src/data/msca10_margins.csv.  Numbers are never typed by hand; counts 0-10 are spelled out.

Sources (copies of HOST_A study/MSCA10/summary, read-only; the only new files in tables/src/data):
  msca10_perseed.csv   one row per model, dataset, seed: base / F / mix test Recall@20 and NDCG@20 (seeds 1-5 existing fusion cells,
                       seeds 6-10 new for MSCA and reused MES10 checkpoints for MSCA + MES)
  msca10_stats.csv     per window (1-10, 1-5), fusion (F, mix, base), dataset: paired t on Recall@20, Holm over the four tuned datasets
                       (p_holm_tuned, the primary family) and over all six complete datasets (p_holm_all, the auxiliary family that
                       holds Instruments and Clothing), TOST p for the margin +-0.002, MDE at 80% power
  msca10_verdict.json  the same numbers with the per-seed differences (cross-checked here with sigtest.paired)
Primary family: Baby, Pantry, Scientific, Sports (tuned lambda and K).  Instruments and Clothing (lambda 0.1, K 40, untuned) form the
auxiliary family and appear only in tables.  A cell is marked significant when its Holm-adjusted p is <= 0.05 in its own family.
NDCG@20 is tested with the same rule (sigtest.paired, Holm over the same families) for the margin rows of Table IV and V.
Usage: python -s tables/src/build_macros_msca10.py
"""
import csv
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import sigtest  # noqa: E402
from numwords import num_word  # noqa: E402

ROOT = HERE.parent
DATA = HERE / 'data'
TUNED = ['baby', 'pantry', 'scientific', 'sports']
AUX = ['instruments', 'clothing']
ALL = TUNED + AUX
NAME = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports', 'instruments': 'Instruments', 'clothing': 'Clothing'}
FUS = {'base': ('base_r20', 'base_n20'), 'F': ('F_r20', 'F_n20'), 'mix': ('mix_r20', 'mix_n20')}
OUT = ['% Generated by tables/src/build_macros_msca10.py (revision log 31) from tables/src/data/msca10_stats.csv and msca10_perseed.csv '
       '(PREREG_MSCA10). Do not edit by hand.']


def mac(n, v):
    assert re.fullmatch(r'[A-Za-z]+', n), n
    OUT.append(f'\\newcommand{{\\{n}}}{{{v}}}')


def sgn(x, nd=4):
    return f'{x:+.{nd}f}'.replace('-', '$-$').replace('+', '$+$')


def join(xs):
    xs = list(xs)
    if not xs:
        return 'none'
    return xs[0] if len(xs) == 1 else (' and '.join(xs) if len(xs) == 2 else ', '.join(xs[:-1]) + ', and ' + xs[-1])


def cnt(k):
    return 'none' if k == 0 else num_word(k)


def load():
    runs = {}
    for r in csv.DictReader(open(DATA / 'msca10_perseed.csv', newline='', encoding='utf-8')):
        assert r['gate_ok'] == '1', r
        runs[(r['model'], r['dataset'], int(r['seed']))] = r
    stats = {}
    for r in csv.DictReader(open(DATA / 'msca10_stats.csv', newline='', encoding='utf-8')):
        stats[(r['window'], r['fusion'], r['dataset'])] = r
    return runs, stats


def margins(runs, stats):
    """ten-seed margins MSCA + MES minus MSCA for base / F / mix and both metrics, with the two Holm families"""
    rows = []
    for fus, (kr, kn) in FUS.items():
        for metric, key in (('r20', kr), ('n20', kn)):
            res = {}
            for d in ALL:
                a = [float(runs[('MSCA+MES', d, s)][key]) for s in range(1, 11)]
                b = [float(runs[('MSCA', d, s)][key]) for s in range(1, 11)]
                r = sigtest.paired(a, b)
                r.update(fusion=fus, metric=metric, dataset=d, window='1-10')
                res[d] = r
            tun = sigtest.family([res[d] for d in TUNED])
            for r, pa in zip(tun, [r['p_holm'] for r in tun]):
                r['p_holm_tuned'] = pa
            allf = sigtest.family([res[d] for d in ALL])
            ph_all = {r['dataset']: r['p_holm'] for r in allf}
            ph_tun = {r['dataset']: r['p_holm_tuned'] for r in tun}
            for d in ALL:
                r = res[d]
                r['p_holm_all'] = ph_all[d]
                r['p_holm_tuned'] = ph_tun.get(d)
                r['family'] = 'tuned' if d in TUNED else 'aux'
                r['p_holm'] = r['p_holm_tuned'] if d in TUNED else r['p_holm_all']
                r['reject'] = int(r['p_holm'] <= sigtest.ALPHA)
                if metric == 'r20':       # cross-check against the archived verdict (Recall@20)
                    s = stats[('1-10', fus if fus != 'base' else 'base', d)] if ('1-10', fus, d) in stats else None
                    assert s is not None, (fus, d)
                    assert abs(r['diff'] - float(s['diff'])) < 5e-7, (fus, d, r['diff'], s['diff'])
                    assert abs(r['p'] - float(s['p'])) < 5e-4, (fus, d)
                    assert abs(r['p_holm_all'] - float(s['p_holm_all'])) < 1e-3, (fus, d)
                    if d in TUNED:
                        assert abs(r['p_holm_tuned'] - float(s['p_holm_tuned'])) < 1e-3, (fus, d)
                    r['tost_p'] = float(s['tost_p'])
                    r['tost_pass'] = int(s['tost_pass'])
                    r['mde'] = float(s['mde_80'])
                rows.append(r)
    return rows


def main():
    runs, stats = load()
    assert {k[2] for k in runs} == set(range(1, 11))
    R = margins(runs, stats)
    cols = ['window', 'fusion', 'metric', 'dataset', 'family', 'n', 'mean_a', 'mean_b', 'diff', 'ci_lo', 'ci_hi', 'p', 'p_holm_tuned',
            'p_holm_all', 'p_holm', 'reject', 'tost_p', 'tost_pass', 'mde']
    with open(DATA / 'msca10_margins.csv', 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, cols, lineterminator='\n', extrasaction='ignore')
        w.writeheader()
        for r in R:
            w.writerow({k: (f'{r[k]:.6g}' if isinstance(r.get(k), float) else ('' if r.get(k) is None else r.get(k))) for k in cols})

    def sel(fus, ds=TUNED, metric='r20'):
        return [r for r in R if r['fusion'] == fus and r['metric'] == metric and r['dataset'] in ds]

    mac('xnNSeeds', num_word(10))
    mac('xnNDs', num_word(len(TUNED)))
    mac('xnPower', '80')
    mac('xnMargin', '0.002')
    # unfused (context; post hoc for the unfused contrast)
    u = sel('base')
    mac('xnUnfNSig', cnt(sum(r['reject'] and r['diff'] > 0 for r in u)))
    mac('xnUnfNDs', num_word(len(u)))
    mac('xnUnfLo', sgn(min(r['diff'] for r in u)))
    mac('xnUnfHi', sgn(max(r['diff'] for r in u)))
    # F
    f = sel('F')
    mac('xnFNSig', cnt(sum(r['reject'] for r in f)))
    mac('xnFNSigPos', cnt(sum(r['reject'] and r['diff'] > 0 for r in f)))
    eq = [NAME[r['dataset']] for r in f if r['tost_pass']]
    noteq = [NAME[r['dataset']] for r in f if not r['tost_pass']]
    mac('xnFNEquiv', cnt(len(eq)))
    mac('xnFEquivDs', join(eq))
    mac('xnFNotEquivDs', join(noteq))
    mac('xnFDiffLo', sgn(min(r['diff'] for r in f)))
    mac('xnFDiffHi', sgn(max(r['diff'] for r in f)))
    mac('xnFPHolmMin', f"{min(r['p_holm'] for r in f):.3f}")
    mac('xnFMdeLo', f"{min(r['mde'] for r in f):.4f}")
    mac('xnFMdeHi', f"{max(r['mde'] for r in f):.4f}")
    mac('xnFMdeNotEquiv', join(f"{r['mde']:.4f}" for r in f if not r['tost_pass']))
    # mix
    m = sel('mix')
    neg = [r for r in m if r['reject'] and r['diff'] < 0]
    mac('xnMixNSigNeg', cnt(len(neg)))
    mac('xnMixNSigPos', cnt(sum(r['reject'] and r['diff'] > 0 for r in m)))
    mac('xnMixNegDs', join(NAME[r['dataset']] for r in neg))
    assert len(neg) == 1
    mac('xnMixNegDiff', sgn(neg[0]['diff']))
    mac('xnMixNegPHolm', f"{neg[0]['p_holm']:.3f}")
    mac('xnMixDiffLo', sgn(min(r['diff'] for r in m)))
    mac('xnMixDiffHi', sgn(max(r['diff'] for r in m)))
    mac('xnMixNEquiv', cnt(sum(r['tost_pass'] for r in m)))
    # NDCG@20 (post hoc: the preregistered tests cover Recall@20; same test and families, Holm over the four tuned datasets)
    fn = sel('F', TUNED, 'n20')
    mac('xnFNdcgNSigPos', cnt(sum(r['reject'] and r['diff'] > 0 for r in fn)))
    mac('xnFNdcgNSigNeg', cnt(sum(r['reject'] and r['diff'] < 0 for r in fn)))
    mac('xnFNdcgDs', join(NAME[r['dataset']] for r in fn if r['reject'] and r['diff'] > 0))
    mn = sel('mix', TUNED, 'n20')
    mac('xnMixNdcgNSigPos', cnt(sum(r['reject'] and r['diff'] > 0 for r in mn)))
    mac('xnMixNdcgNSigNeg', cnt(sum(r['reject'] and r['diff'] < 0 for r in mn)))
    mac('xnMixNdcgNegDs', join(NAME[r['dataset']] for r in mn if r['reject'] and r['diff'] < 0))
    # revision log 32: the NDCG@20 margins themselves (comma list in dataset order, as in Table IV), for the abstract, Introduction, and 4b
    mac('xnFNdcgDiffs', ', '.join(sgn(r['diff']) for r in fn if r['reject'] and r['diff'] > 0))
    mac('xnMixNdcgNegDiff', ', '.join(sgn(r['diff']) for r in mn if r['reject'] and r['diff'] < 0))
    # auxiliary family (tables only; named here so that the build records them)
    for fus, tag in (('base', 'Unf'), ('F', 'F'), ('mix', 'Mix')):
        for r in sel(fus, AUX):
            mac(f"xnAux{tag}{NAME[r['dataset']]}", sgn(r['diff']))
    mac('xnAuxNDs', num_word(len(AUX)))
    ua = [r for r in sel('base', AUX) if r['reject'] and r['diff'] > 0]
    mac('xnAuxUnfSigPhrase', 'both' if len(ua) == len(AUX) else f'{num_word(len(ua))} of the {num_word(len(AUX))}')
    for fus, tag in (('F', 'F'), ('mix', 'Mix')):
        mac(f'xnAux{tag}SigPos', join(NAME[r['dataset']] for r in sel(fus, AUX) if r['reject'] and r['diff'] > 0))
        mac(f'xnAux{tag}SigNeg', join(NAME[r['dataset']] for r in sel(fus, AUX) if r['reject'] and r['diff'] < 0))
    mac('xnAllNDs', num_word(len(ALL)))
    (ROOT / 'macros_msca10.tex').write_text('\n'.join(OUT) + '\n', encoding='utf-8', newline='\n')
    print('\n'.join(OUT))
    for r in R:
        if r['metric'] == 'r20':
            print(r['fusion'], r['dataset'], f"{1e3 * r['diff']:+.3f}", f"p_holm={r['p_holm']:.3f}", r['reject'], 'tost', r.get('tost_pass'), f"mde={1e3 * r['mde']:.3f}")


if __name__ == '__main__':
    main()
