def holm_family(res):
    return sigtest.family(res)


def macros():
    nd = len(E1A)
    mac('clNDsDone', cnt(nd))
    for d in DS9:
        if d in E1A:
            j = E1A[d]
            mac(f'clLam{NAME[d]}', str(int(j['ease_lam'])))
            mac(f'clLamEdge{NAME[d]}', 'yes' if j['ease_lam_at_edge'] else 'no')
            for r, _ in RK:
                mac(f'clR{MACN[r]}{NAME[d]}', f4(ranker_val(d, r)))
    done = [d for d in DS9 if d in E1A]
    # standalone comparisons (means of the deterministic values)
    def n_above(a, b):
        return sum(ranker_val(d, a) > ranker_val(d, b) for d in done)
    mac('clNEaseAboveCf', cnt(n_above('ease', 'icf')))
    mac('clNEaseAboveRp', cnt(n_above('ease', 'rp3b')))
    mac('clNEaseAboveF', cnt(n_above('ease', 'F')))
    mac('clNMixAboveF', cnt(n_above('mix', 'F')))
    mac('clNMixAboveEase', cnt(n_above('mix', 'ease')))
    mac('clNFAboveRp', cnt(n_above('F', 'rp3b')))
    # revision log 25: best unfused learned model of each dataset (the 'Best learned model (unfused)' row of Table I, Recall@20 means over
    # the gated seeds) and the datasets on which the best z-mix lies above it
    above_best = []
    for d in done:
        vv = [(mean_of_k(m, d, 'r20'), m) for m in MODELS]
        vv = [(round(v, 4), m) for v, m in vv if v is not None]
        if not vv:
            continue
        bv, bm = max(vv)
        mac(f'clRBestLearned{NAME[d]}', f4(bv)); mac(f'clBestLearnedModel{NAME[d]}', MLAB[bm])
        if round(ranker_val(d, 'mix'), 4) > bv:
            above_best.append(NAME[d])
    mac('clNMixAboveBestLearned', cnt(len(above_best)))
    mac('clMixAboveBestLearnedDs', ' and '.join(above_best) if len(above_best) <= 2 else ', '.join(above_best[:-1]) + ', and ' + above_best[-1])
    # learned unfused against the best z-mix (one-sample t over the learned seeds, Holm over the datasets of one (model, ranker))
    tot = {'up': 0, 'down': 0, 'pairs': 0}
    for rk in ('F', 'ease', 'mix'):
        for m in MODELS:
            res = []
            for d in done:
                s = seeds_of(m, d, 'base')
                if len(s) < 3:
                    continue
                x = [cell[(m, d, i)]['base'] for i in s]; c0 = ranker_val(d, rk)
                tt = stats.ttest_1samp(x, c0)
                res.append(dict(dataset=d, n=len(x), mean_a=st.mean(x), mean_b=c0, diff=st.mean(x) - c0, p=float(tt.pvalue), t=float(tt.statistic)))
            if not res:
                continue
            holm_family(res)
            for r in res:
                TESTS.append(dict(family='learned unfused vs classical (one-sample t)', contrast=f'{m} - {rk}', a=m, b=rk, dataset=r['dataset'], metric='r20',
                                  n=r['n'], mean_a=r['mean_a'], mean_b=r['mean_b'], diff=r['diff'], p=r['p'], m=r['m'], p_holm=r['p_holm'], reject=r['reject']))
            if rk == 'mix' or m in ('MSCA+MES', 'MSCA'):
                mac(f'clNAbove{MACN[rk]}{m.replace("+", "")}', cnt(sum(r['reject'] and r['diff'] > 0 for r in res)))
                mac(f'clNBelow{MACN[rk]}{m.replace("+", "")}', cnt(sum(r['reject'] and r['diff'] < 0 for r in res)))
                mac(f'clNDsT{MACN[rk]}{m.replace("+", "")}', cnt(len(res)))
            if rk == 'mix':
                tot['up'] += sum(r['reject'] and r['diff'] > 0 for r in res); tot['down'] += sum(r['reject'] and r['diff'] < 0 for r in res); tot['pairs'] += len(res)
    mac('clNLearnedAboveMix', cnt(tot['up'])); mac('clNLearnedBelowMix', cnt(tot['down'])); mac('clNLearnedMixPairs', cnt(tot['pairs']))
    # fusion: variant against unfused, and variant against F (paired t over the common seeds, Holm over the datasets of one model and variant)
    res_all = {}
    for v, _ in VAR[1:]:
        up = down = pairs = 0
        for m in MODELS:
            res = []
            for d in DS9:
                s = [i for i in SEEDS if (m, d, i) in cell and v in cell[(m, d, i)] and 'base' in cell[(m, d, i)]]
                if len(s) < 3:
                    continue
                r = sigtest.paired([cell[(m, d, i)][v] for i in s], [cell[(m, d, i)]['base'] for i in s]); r.update(dataset=d)
                res.append(r)
            if not res:
                continue
            holm_family(res)
            for r in res:
                TESTS.append(dict(family='fused vs unfused', contrast=f'{m} {v} - unfused', a=f'{m} {v}', b=m, dataset=r['dataset'], metric='r20', n=r['n'],
                                  mean_a=r['mean_a'], mean_b=r['mean_b'], diff=r['diff'], ci_lo=r['ci_lo'], ci_hi=r['ci_hi'], t=r['t'], p=r['p'], m=r['m'],
                                  p_holm=r['p_holm'], reject=r['reject'], wins_a=r['wins_a']))
            up += sum(r['reject'] and r['diff'] > 0 for r in res); down += sum(r['reject'] and r['diff'] < 0 for r in res); pairs += len(res)
        res_all[v] = (up, down, pairs)
        V = v.capitalize()
        mac(f'clN{V}RaiseSig', cnt(up)); mac(f'clN{V}LowerSig', cnt(down)); mac(f'clN{V}Pairs', cnt(pairs))
    for v in ('ease', 'icf', 'mix'):
        up = down = pairs = nmean_up = 0
        for m in MODELS:
            res = []
            for d in DS9:
                s = [i for i in SEEDS if (m, d, i) in cell and v in cell[(m, d, i)] and 'combo' in cell[(m, d, i)]]
                if len(s) < 3:
                    continue
                r = sigtest.paired([cell[(m, d, i)][v] for i in s], [cell[(m, d, i)]['combo'] for i in s]); r.update(dataset=d)
                res.append(r)
            if not res:
                continue
            holm_family(res)
            for r in res:
                TESTS.append(dict(family='fused variant vs F', contrast=f'{m} {v} - F', a=f'{m} {v}', b=f'{m} F', dataset=r['dataset'], metric='r20', n=r['n'],
                                  mean_a=r['mean_a'], mean_b=r['mean_b'], diff=r['diff'], ci_lo=r['ci_lo'], ci_hi=r['ci_hi'], t=r['t'], p=r['p'], m=r['m'],
                                  p_holm=r['p_holm'], reject=r['reject'], wins_a=r['wins_a']))
            up += sum(r['reject'] and r['diff'] > 0 for r in res); down += sum(r['reject'] and r['diff'] < 0 for r in res); pairs += len(res)
            nmean_up += sum(r['diff'] > 0 for r in res)
        V = v.capitalize()
        mac(f'clN{V}AboveFSig', cnt(up)); mac(f'clN{V}BelowFSig', cnt(down)); mac(f'clN{V}FPairs', cnt(pairs)); mac(f'clN{V}AboveFMean', cnt(nmean_up))
    # margin of MSCA + MES over MSCA after each fusion variant (same seeds, paired t, Holm over the datasets that hold both models)
    for v in ('base', 'combo', 'ease', 'icf', 'mix'):
        res = []
        for d in DS9:
            s = [i for i in SEEDS if ('MSCA+MES', d, i) in cell and ('MSCA', d, i) in cell and v in cell[('MSCA+MES', d, i)] and v in cell[('MSCA', d, i)]]
            if len(s) < 3:
                continue
            r = sigtest.paired([cell[('MSCA+MES', d, i)][v] for i in s], [cell[('MSCA', d, i)][v] for i in s]); r.update(dataset=d)
            res.append(r)
        holm_family(res)
        for r in res:
            TESTS.append(dict(family='MES margin over MSCA after fusion', contrast=f'MSCA+MES {v} - MSCA {v}', a=f'MSCA+MES {v}', b=f'MSCA {v}', dataset=r['dataset'],
                              metric='r20', n=r['n'], mean_a=r['mean_a'], mean_b=r['mean_b'], diff=r['diff'], ci_lo=r['ci_lo'], ci_hi=r['ci_hi'], t=r['t'], p=r['p'],
                              m=r['m'], p_holm=r['p_holm'], reject=r['reject'], wins_a=r['wins_a']))
        V = v.capitalize()
        mac(f'clMes{V}NSig', cnt(sum(r['reject'] and r['diff'] > 0 for r in res))); mac(f'clMes{V}NDs', cnt(len(res)))
        mac(f'clMes{V}Lo', f"{min(r['diff'] for r in res):+.4f}"); mac(f'clMes{V}Hi', f"{max(r['diff'] for r in res):+.4f}")
        mac(f'clMes{V}NPos', cnt(sum(r['diff'] > 0 for r in res)))
        # revision log 25: significantly negative margins (count, datasets, difference, Holm-adjusted p of the largest negative one)
        neg = sorted((r for r in res if r['reject'] and r['diff'] < 0), key=lambda r: r['diff'])
        mac(f'clMes{V}NNegSig', cnt(len(neg)))
        mac(f'clMes{V}NegDs', ', '.join(NAME[r['dataset']] for r in neg) or 'none')
        if neg:
            mac(f'clMes{V}NegDiff', f"{neg[0]['diff']:+.4f}".replace('-', '$-$').replace('+', '$+$'))   # text-mode sign, as \fpMarginMin
            mac(f'clMes{V}NegPHolm', f"{neg[0]['p_holm']:.3f}")
    # fidelity: the F recomputed here (tf_fuse_ce.py --combo) against the existing TABLE_FUSION F of the same checkpoint
    chk = [(k, v) for k, v in cell.items() if 'combo_old' in v and 'combo_new' in v]
    dif = [abs(v['combo_new'] - v['combo_old']) for _, v in chk]
    mac('clFRecomputeN', str(len(chk)))
    mac('clFRecomputeMaxDiff', f"{max(dif, default=0.0):.6f}")
    mac('clFRecomputeNEqual', str(sum(d < 5e-7 for d in dif)))
    # cell coverage
    L, rows = coverage()
    n_cells = sum(r['n_fused'] for r in rows)
    mac('clNFused', str(n_cells)); mac('clNUniverse', str(len(MODELS) * len(DS9) * len(SEEDS)))
    mac('clNMissing', str(len(MODELS) * len(DS9) * len(SEEDS) - n_cells))
    no_dump = sum(5 - r['n_fused'] for r in rows if r['reasons'] == 'no dump')
    mac('clNMissingNoDump', str(no_dump))
    # revision log 25: cells that have a dump but failed the TABLE_FUSION re-evaluation gate (classic_e1b_missing.tsv)
    mp = DATA / 'classic_e1b_missing.tsv'
    gate = [r for r in read_csv(mp, delimiter=chr(9)) if r['reason'] != 'no dump'] if mp.exists() else []
    mac('clNMissingGate', cnt(len(gate)))
    assert len(MODELS) * len(DS9) * len(SEEDS) - n_cells == no_dump + len(gate)
    mac('clMissingModelsNoDump', ', '.join(sorted({f"{MLAB[r['model']]} on {NAME[r['dataset']]}" for r in rows if r['reasons'] == 'no dump' and r['n_fused'] == 0})) or 'none')
    return L


