def cnt(k):
    return num_word(k) if k <= 10 else str(k)


def read_csv(p, **kw):
    return list(csv.DictReader(open(p, newline='', encoding='utf-8'), **kw))


E1A = {ds: json.load(open(DATA / f'classic_e1a_{ds}.json', encoding='utf-8')) for ds in DS9 if (DATA / f'classic_e1a_{ds}.json').exists()}
