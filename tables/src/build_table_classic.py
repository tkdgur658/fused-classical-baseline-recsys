cell = {}
for r in CELLS:
    if r['gate_ok'] != '1':
        continue
    k = (r['model'], r['dataset'], int(r['seed']))
    v = {'base': float(r['base_r20'])}
    for f in ('combo', 'ease', 'icf', 'mix'):
        if r.get(f'{f}_r20'):
            v[f] = float(r[f'{f}_r20'])
    if 'combo' in v:
        v['combo_new'] = v['combo']      # F recomputed by tf_fuse_ce.py (only with --combo)
    if k in OLD:      # the existing TABLE_FUSION F (and base) of the same checkpoint
        v['combo_old'] = float(OLD[k]['fused_r20']); v['base_old'] = float(OLD[k]['base_r20'])
        v['combo'] = v['combo_old'] if 'combo' not in v else v['combo']
    cell[k] = v
for k, r in OLD.items():       # old cells that this queue did not touch (none expected): keep F and base for completeness
    if k not in cell and r['model'] in MODELS:
        cell[k] = {'base': float(r['base_r20']), 'combo': float(r['fused_r20']), 'combo_old': float(r['fused_r20']), 'base_old': float(r['base_r20'])}


def seeds_of(m, d, var):
    return sorted(s for (mm, dd, s), v in cell.items() if mm == m and dd == d and var in v)


def mean_of(m, d, var):
    s = seeds_of(m, d, var)
    return (st.mean(cell[(m, d, x)][var] for x in s), len(s)) if s else (None, 0)


def f4(x):
    return f'{x:.4f}'


