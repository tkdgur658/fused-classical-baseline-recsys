def coverage():
    """seeds fused per (model, dataset) of the 8 x 9 x 5 universe, with the reason of every missing cell"""
    miss = {}
    mp = DATA / 'classic_e1b_missing.tsv'
    if mp.exists():
        for r in read_csv(mp, delimiter='\t'):
            miss[(r['model'], r['dataset'], int(r['seed']))] = r['reason']
    for r in CELLS:
        if r['gate_ok'] != '1':
            miss[(r['model'], r['dataset'], int(r['seed']))] = r.get('note') or 'gate fail'
    rows = []
    for m in MODELS:
        for d in DS9:
            n = sum((m, d, s) in cell and 'base' in cell[(m, d, s)] for s in SEEDS)
            reasons = sorted({miss.get((m, d, s), 'no dump') for s in SEEDS if (m, d, s) not in cell})
            rows.append(dict(model=m, dataset=d, n_fused=n, reasons='; '.join(reasons)))
    with open(DATA / 'classic_e1b_coverage.csv', 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, ['model', 'dataset', 'n_fused', 'reasons'], lineterminator='\n'); w.writeheader(); w.writerows(rows)
    L = ['\\begin{table}[t]',
         '\\caption{Number of seeds (of five) for which a fused result exists, per learned model and dataset. A missing cell has no stored dump, or its '
         'checkpoint did not reproduce the stored test Recall@20 and NDCG@20 within $5\\times10^{-4}$ on the CPU.}',
         '\\label{tab:classic_coverage}', '\\centering', '\\footnotesize', '\\setlength{\\tabcolsep}{3pt}',
         '\\begin{tabular}{l' + 'c' * len(DS9) + '}', '\\toprule', 'Model & ' + ' & '.join(NAME[d][:4] + '.' if len(NAME[d]) > 5 else NAME[d] for d in DS9) + ' \\\\', '\\midrule']
    for m in MODELS:
        L.append(f'{MLAB[m]} & ' + ' & '.join(str(next(r['n_fused'] for r in rows if r['model'] == m and r['dataset'] == d)) for d in DS9) + ' \\\\')
    L += ['\\bottomrule', '\\end{tabular}', '\\end{table}', '']
    return L, rows


