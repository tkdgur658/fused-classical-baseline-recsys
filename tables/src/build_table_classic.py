def run_set_note():
    '''revision log 29 (item 2): the learned rows of Table I are the fused cells' own unfused values (one run set with the fusion
    comparisons of Tables sota and fuse_added); the gap of MSCA to the MSCA row of Table sota is computed, not typed.'''
    import native_rows
    gaps = []
    for d in ('baby', 'pantry', 'scientific'):
        t2 = float(native_rows.native('MSCA', d)['r20_mean'])
        gaps.append(abs(round(mean_of_k('MSCA', d, 'r20'), 4) - round(t2, 4)))
    t2s = float(native_rows.native('MSCA', 'sports')['r20_mean'])
    assert round(mean_of_k('MSCA', 'sports', 'r20'), 4) == round(t2s, 4)      # Sports shares the checkpoints of Table sota
    return ('Learned rows are the unfused values of the fusion runs of Tables~\\ref{tab:sota} and~\\ref{tab:fuse_added}, so that each comparison '
            'stays within one run set: MSCA + MES everywhere and MSCA on Sports share the checkpoints of Table~\\ref{tab:sota}, whereas MSCA on Baby, '
            f'Pantry, and Scientific is a separate five-seed run set whose mean Recall@20 differs from Table~\\ref{{tab:sota}} by at most {max(gaps):.4f}.')


def mean_of_k(m, d, k):
    """mean of the unfused metric k in {r20, n20} over gated cells (n20 from the E1B csv)"""
    rows = [r for r in CELLS if r['model'] == m and r['dataset'] == d and r['gate_ok'] == '1' and r.get(f'base_{k}')]
    if not rows:
        old = [r for r in OLD.values() if r['model'] == m and r['dataset'] == d]
        if not old:
            return None
        return st.mean(float(r['base_r20' if k == 'r20' else 'base_n20']) for r in old)
    return st.mean(float(r[f'base_{k}']) for r in rows)


def learned_cell(m, d, k):
    rows = [r for r in CELLS if r['model'] == m and r['dataset'] == d and r['gate_ok'] == '1' and r.get(f'base_{k}')]
    if not rows:
        v = mean_of_k(m, d, k)
        return f'{v:.4f}' if v is not None else '--'
    s = f"{st.mean(float(r[f'base_{k}']) for r in rows):.4f}"
    return s + (f'\\,({len(rows)})' if len(rows) < 5 else '')


