"""SSM score-function grid extended by cosine training with inner-product ranking (reviewer question, E3, HOST_A).

Seed-1 validation Recall@20 / NDCG@20 of the nine SSM candidates per dataset (train/rank score in cos/cos, cos/dot,
dot/dot, tau in {0.1, 0.2, 0.5}) on MSCA. The selection rule of Table tab:main (max seed-1 valid R@20, ties valid N@20)
is applied here again; the winner must equal the SSM cell of Table tab:main (tables/hparams: score dot, tau 0.5).

  python -s tables/src/build_cosdot.py --from-text <collect_e3.py --out file>   parse the collector output into
                                                                               tables/cosdot_seed1.csv, then build
  python -s tables/src/build_cosdot.py                                         build from tables/cosdot_seed1.csv

Collector: <TOOLS>/hyp_figs_20261007/collect_e3.py (read only, ssh HOST_A).
Output: tables/macros_cosdot.tex (prefix cd, used in the Hyperparameters section of supplement.tex) and the lines
'cosdot:' of tables/claims_check.txt.
"""
import argparse
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CSV = ROOT / 'cosdot_seed1.csv'
DS = [('baby', 'Baby'), ('pantry', 'Pantry'), ('scientific', 'Scientific'), ('sports', 'Sports')]
SCORE = {'cos/cos': 'cosine', 'cos/dot': 'cosdot', 'dot/dot': 'dot'}
ORDER = ['cosine', 'cosdot', 'dot']   # tie order of the collector rule
COLS = ['dataset', 'score', 'tau', 'valid_r20', 'valid_n20', 'best_epoch', 'config', 'selected_in_table1']


def parse(text):
    rows, ds = [], None
    names = {D: d for d, D in DS}
    for line in text.splitlines():
        m = re.match(r'== SSM / (\w+)', line)
        if m:
            ds = names[m.group(1)]
            continue
        m = re.match(r'\s+(cos/cos|cos/dot|dot/dot) tau (\S+)\s+([\d.]+) / ([\d.]+)\s+ep\s+(\d+)\s+(\S+)(.*)$', line)
        if m and ds:
            rows.append(dict(dataset=ds, score=SCORE[m.group(1)], tau=m.group(2), valid_r20=m.group(3),
                             valid_n20=m.group(4), best_epoch=m.group(5), config=m.group(6),
                             selected_in_table1=int('[Table I]' in m.group(7))))
    # the collector prints its report twice (stdout and --out); keep the first copy of each (dataset, config)
    seen, out = set(), []
    for r in rows:
        if (r['dataset'], r['config']) not in seen:
            seen.add((r['dataset'], r['config']))
            out.append(r)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--from-text', default=None)
    a = ap.parse_args()
    if a.from_text:
        rows = parse(Path(a.from_text).read_text(encoding='utf-8'))
        with open(CSV, 'w', newline='', encoding='utf-8') as f:
            w = csv.DictWriter(f, fieldnames=COLS, lineterminator='\n')
            w.writeheader()
            w.writerows(rows)
    rows = list(csv.DictReader(open(CSV, encoding='utf-8')))
    out = ['% Generated by tables/src/build_cosdot.py from tables/cosdot_seed1.csv. Do not edit by hand.',
           '% SSM on MSCA, seed-1 validation Recall@20: best cosine-train / inner-product-rank candidate vs the selected one.']

    def mac(n, v):
        assert re.fullmatch(r'cd[A-Za-z]+', n), n
        out.append(f'\\newcommand{{\\{n}}}{{{v}}}')
    best_cd, sel, won_cd, claims = [], [], [], []
    for d, D in DS:
        g = [r for r in rows if r['dataset'] == d]
        assert len(g) == 9, (d, len(g))
        win = sorted(g, key=lambda r: (-float(r['valid_r20']), -float(r['valid_n20']), ORDER.index(r['score']),
                                       float(r['tau'])))[0]
        t1 = [r for r in g if int(r['selected_in_table1'])]
        assert len(t1) == 1 and t1[0]['config'] == win['config'], (d, win['config'], t1)   # Table I cell unchanged
        cd = max((r for r in g if r['score'] == 'cosdot'), key=lambda r: float(r['valid_r20']))
        best_cd.append(f"{float(cd['valid_r20']):.4f}")
        sel.append(f"{float(win['valid_r20']):.4f}")
        if win['score'] == 'cosdot':
            won_cd.append(D)
        mac(f'cdBest{D}', best_cd[-1])
        mac(f'cdSel{D}', sel[-1])
        claims.append(f"cosdot: {D} winner {win['config']} ({win['score']}, tau {win['tau']}, valid R@20 {sel[-1]}); "
                      f"best cos-dot {cd['config']} {best_cd[-1]}; Table I cell = winner: True")
    taus = sorted({r['tau'] for r in rows if int(r['selected_in_table1'])})
    scores = sorted({r['score'] for r in rows if int(r['selected_in_table1'])})
    mac('cdBestList', '\\slash '.join(best_cd))   # \slash: a breakable slash (justified supplement column)
    mac('cdSelList', '\\slash '.join(sel))
    mac('cdSelTau', taus[0] if len(taus) == 1 else '/'.join(taus))
    mac('cdSelScore', {'dot': 'inner product', 'cosine': 'cosine similarity', 'cosdot': 'cosine training'}[scores[0]]
        if len(scores) == 1 else 'per-dataset choice')
    mac('cdNSelected', ['no', 'one', 'two', 'three', 'four'][len(won_cd)])
    (ROOT / 'macros_cosdot.tex').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    claims.append(f"cosdot: supplement 'selected on cdNSelected dataset' -> cos-dot winners {won_cd}")
    cc = ROOT / 'claims_check.txt'
    keep = [x for x in (cc.read_text(encoding='utf-8').splitlines() if cc.exists() else []) if not x.startswith('cosdot:')]
    cc.write_text('\n'.join(keep + claims) + '\n', encoding='utf-8', newline='\n')
    print('\n'.join(out[2:]))


if __name__ == '__main__':
    main()
