"""revision log 18-N' (author decision, N' downgraded to an exploratory analysis): macros of the post hoc diagnosis of
the decoy null N3 on Instruments (CPU only, no training; server run study/DIAG_INST, analytic expectation of N3).
Reads tables/src/data/diag_inst.json (copy of HOST_A:<RUN_ROOT>/study/DIAG_INST/results/diag_inst.json,
script sha256 17c10679...) and writes tables/macros_diaginst.tex (prefix di). Every number is read from the JSON; a missing
key raises KeyError, and the values quoted in the author decision are asserted after formatting.
Usage: python -s tables/src/build_diag_inst_macros.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from numwords import k_of_n  # noqa: E402

T = Path(__file__).resolve().parents[1]
J = json.load(open(T / 'src' / 'data' / 'diag_inst.json', encoding='utf-8'))
INS = 'instruments'
OTHERS = [k for k in J['per_ds'] if k != INS]
assert len(J['per_ds']) == 8 and len(OTHERS) == 7, list(J['per_ds'])


def p(x, nd=1):
    return f'{100 * x:.{nd}f}'


def tag(ds, t):
    return J['per_ds'][ds]['tags'][t]


mes, nat, xre = (tag(INS, t) for t in ('mes', 'native', 'xre'))
assert J['per_ds'][INS]['Ctag'] == 'rp3b'  # the classical list on Instruments is RP3beta

# validation Recall@20, seed mean and the number of seeds with MES above MSCA (native)
vm, vn = J['valid'][INS]['mes']['valid'], J['valid'][INS]['native']['valid']
assert len(vm) == len(vn) == 5 and all(v is not None for v in vm + vn)
n_seed_up = sum(a > b for a, b in zip(vm, vn))

# ratio of the classical decoy rate to the MES decoy rate on the other seven datasets
ratio = [tag(d, 'mes')['null']['RC_null'] / tag(d, 'mes')['null']['RL_null'] for d in OTHERS]
# share of list slots on the 100 most frequent test items: classical list (C) on the other seven datasets
top_c_other = [tag(d, 'mes')['liststats']['slots_top100pool_C'] for d in OTHERS]

M = {
    # interval of the decoy null N3 (200 draws, five seeds) for MES on Instruments, and the headroom g_O
    'diNullLo': p(mes['sim_N3_lohi'][0]), 'diNullHi': p(mes['sim_N3_lohi'][1]), 'diGo': p(mes['g_O']),
    # decoy Recall@20 (%, analytic expectation) of the RP3beta list and the MES list
    'diRCNull': p(mes['null']['RC_null'], 2), 'diRLNull': p(mes['null']['RL_null'], 2),
    'diRatioMin': f'{min(ratio):.2f}', 'diRatioMax': f'{max(ratio):.2f}',
    # null g_null (analytic, %) by learned list L with the same classical list C, and the headroom of the MSCA list
    'diNullMES': p(mes['null']['g_null_analytic']), 'diNullMSCA': p(nat['null']['g_null_analytic']),
    'diNullXRE': p(xre['null']['g_null_analytic']), 'diGoMSCA': p(nat['g_O']),
    # validation Recall@20 (seed mean) of MES and MSCA, number of seeds with MES above MSCA
    'diValMES': f'{sum(vm) / 5:.4f}', 'diValMSCA': f'{sum(vn) / 5:.4f}', 'diValSeeds': k_of_n(n_seed_up, 5),
    # share (%) of list slots on the 100 most frequent test items
    'diTopC': p(mes['liststats']['slots_top100pool_C']), 'diTopCOtherMin': p(min(top_c_other)),
    'diTopCOtherMax': p(max(top_c_other)), 'diTopXRE': p(xre['liststats']['slots_top100pool'], 0),
    # decoy-null interval of the E + R + A design on Instruments (reproduction of the earlier run, difference 0.0)
    'diXreLo': p(J['repro']['xre']['N3']['lo']), 'diXreHi': p(J['repro']['xre']['N3']['hi']),
}
assert J['repro']['xre']['diff']['N3_lo'] == 0.0 and J['repro']['xre']['diff']['N3_hi'] == 0.0

# values quoted in the author decision (EDIT N' downgrade): the generated strings must equal them
EXPECT = {'diNullLo': '48.1', 'diNullHi': '54.0', 'diGo': '16.4', 'diRCNull': '2.39', 'diRLNull': '2.35',
          'diRatioMin': '0.26', 'diRatioMax': '0.58', 'diNullMES': '51.6', 'diNullMSCA': '55.7', 'diNullXRE': '10.4',
          'diGoMSCA': '20.3', 'diValMES': '0.1976', 'diValMSCA': '0.1891', 'diValSeeds': 'all five', 'diTopC': '36.8',
          'diTopCOtherMin': '2.2', 'diTopCOtherMax': '13.3', 'diTopXRE': '61', 'diXreLo': '9.8', 'diXreHi': '11.7'}
for k, v in EXPECT.items():
    assert M[k] == v, (k, M[k], v)
assert set(EXPECT) == set(M)

out = ['% Generated by tables/src/build_diag_inst_macros.py from tables/src/data/diag_inst.json (Instruments diagnosis of the decoy null,',
       '% post hoc, CPU only). Percent values carry no sign; validation Recall@20 is the seed mean. Do not edit.']
for k, v in M.items():
    out.append(f'\\newcommand{{\\{k}}}{{{v}}}')
(T / 'macros_diaginst.tex').write_text('\n'.join(out) + '\n', encoding='utf-8')
print('\n'.join(out))
