"""Prose macros of the F paragraph of Section IV-B (revision log 18-1, 2026-10-16): tables/macros_fusionprose.tex (prefix fp).
Replaces the numbers that 4b typed by hand from fusion_summary_9ds_mes.csv (the \\todo "move to macros").
Input: tables/src/data/fusion_summary_9ds_mes.csv (study/results copy, 50 model and dataset pairs on eight datasets, means over
the seeds listed in the file). The printed values are asserted against the values the text carried before 18-1.
Usage: python tables/src/build_fusion_prose_macros.py
"""
import csv
from collections import defaultdict
from pathlib import Path

from numwords import num_word

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'src' / 'data' / 'fusion_summary_9ds_mes.csv'
FOUR = ['baby', 'pantry', 'scientific', 'sports']
ADDED = ['clothing', 'instruments', 'arts', 'office']
NAMES = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports', 'clothing': 'Clothing',
         'instruments': 'Instruments', 'arts': 'Arts', 'office': 'Office'}
LAB = {'MSCA+MES': 'MSCA + MES', 'MSCA': 'MSCA', 'COHESION': 'COHESION', 'SMORE': 'SMORE', 'PGL': 'PGL', 'DiffMM': 'DiffMM',
       'LGMRec': 'LGMRec', 'FREEDOM': 'FREEDOM'}


def join(xs):
    xs = list(xs)
    return xs[0] if len(xs) == 1 else (' and '.join(xs) if len(xs) == 2 else ', '.join(xs[:-1]) + ', and ' + xs[-1])


def sgn(x):
    return f'{x:+.4f}'.replace('-', '$-$') if x < 0 else f'$+${x:.4f}'


def main():
    by = defaultdict(dict)
    for r in csv.DictReader(open(SRC, newline='', encoding='utf-8')):
        by[r['dataset']][r['model']] = {k: float(r[k]) for k in ('r20_mean', 'n20_mean', 'base_r20_mean')}
    for d, m in by.items():
        for k, v in m.items():
            assert v['r20_mean'] > v['base_r20_mean'], (d, k)          # F raises every pair
    pairs4 = sum(len(by[d]) for d in FOUR); pairs_add = sum(len(by[d]) for d in ADDED)
    # top fused model per dataset (Recall@20; NDCG@20 named when it differs)
    parts, groups = [], {}
    for d in FOUR:
        m = by[d]
        tr = max(m, key=lambda k: m[k]['r20_mean']); tn = max(m, key=lambda k: m[k]['n20_mean'])
        key = (tr, tn)
        groups.setdefault(key, []).append(d)
    for (tr, tn), dss in groups.items():
        s = f'{LAB[tr]} $\\oplus$ on {join(NAMES[d] for d in dss)}'
        if tn != tr:
            s += f' ({LAB[tn]} $\\oplus$ in NDCG@20)'
        parts.append(s)
    both = [d for d in FOUR + ADDED if 'MSCA+MES' in by[d] and 'MSCA' in by[d]]
    mg = {d: by[d]['MSCA+MES']['r20_mean'] - by[d]['MSCA']['r20_mean'] for d in both}
    pre = {d: by[d]['MSCA+MES']['base_r20_mean'] - by[d]['MSCA']['base_r20_mean'] for d in both}
    M = {'fpNPairsFour': str(pairs4), 'fpNPairsAdded': str(pairs_add), 'fpNPairs': str(pairs4 + pairs_add),
         'fpNDsF': num_word(len(FOUR + ADDED)), 'fpTopFour': join(parts),
         'fpNDsBoth': num_word(len(both)),
         'fpMarginMin': sgn(round(min(mg.values()), 4)), 'fpMarginMax': sgn(round(max(mg.values()), 4)),
         'fpMarginFourMin': sgn(round(min(mg[d] for d in FOUR), 4)), 'fpMarginFourMax': sgn(round(max(mg[d] for d in FOUR), 4)),
         'fpPreFourMin': sgn(round(min(pre[d] for d in FOUR), 4)), 'fpPreFourMax': sgn(round(max(pre[d] for d in FOUR), 4)),
         'fpPreClothing': sgn(round(pre['clothing'], 4)), 'fpPreInstruments': sgn(round(pre['instruments'], 4))}
    # values the text carried before revision log 18-1 (typed by hand from the same file)
    before = {'fpNPairsFour': '32', 'fpNPairsAdded': '18', 'fpNPairs': '50', 'fpMarginMin': '$-$0.0005', 'fpMarginMax': '$+$0.0011',
              'fpPreFourMin': '$+$0.0007', 'fpPreFourMax': '$+$0.0027', 'fpPreClothing': '$+$0.0028', 'fpPreInstruments': '$+$0.0041',
              'fpTopFour': 'MSCA $\\oplus$ on Baby, PGL $\\oplus$ on Pantry (FREEDOM $\\oplus$ in NDCG@20), and MSCA + MES $\\oplus$ on Scientific and Sports'}
    for k, v in before.items():
        assert M[k] == v, (k, M[k], v)
    L = ['% Generated by tables/src/build_fusion_prose_macros.py from tables/src/data/fusion_summary_9ds_mes.csv. Do not edit by hand.']
    L += [f'\\newcommand{{\\{k}}}{{{v}}}' for k, v in M.items()] + ['']
    (ROOT / 'macros_fusionprose.tex').write_text('\n'.join(L), encoding='utf-8', newline='\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
