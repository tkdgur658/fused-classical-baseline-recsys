"""Write tables/macros_analysis.tex: the numbers of the analysis paragraphs (self-message attenuation, gradient-direction
split of the exchange term, Recall@K profile). Every value is computed here from CSV files of tables/; nothing is typed.

Inputs
  tables/analysis_selfmsg.csv     (collect_analysis.py)  MSCA Native / XRE checkpoints of P04_listana (Baby, Pantry,
                                                         Scientific) and the Table I Sports runs, seeds 1-5
  tables/gradsplit_perseed.csv    (collect_analysis.py)  P04_prune arms + Native / A1 / XRE of the manuscript tables
  tables/recallk_listana.csv      (collect_recallk.py)   Recall@K, K = 5, 10, 20, 50, same checkpoints as the self-message
Conventions
  * "Min/Max" ranges run over the 20 (dataset, seed) cells of Baby, Pantry, Scientific and Sports, seeds 1-5 (the
    split* macros: Pantry and Scientific only, the datasets of P04_prune).
  * Shares and losses are percentages rounded to integers; ratios have two decimals.
  * smShare*: mean over training positives (s_up > 0) of S_up / s_up, the self-message share of the training score.
  * gradKeep*: E[w_full] / E[w_cav] (BPR positive weight with / without the self-message); gradLost* = 100 (1 - gradKeep).
  * gradRec*: E[w_full] of XRE / E[w_full] of Native, same seed, same pairs and negatives; gradRecBaby etc. are geometric
    means over the five seed pairs; gradRecPairs = "<pairs with ratio > 1>/<pairs>".
  * split<Arm><DS>{Delta,Wins,Losses,P}: same-seed paired difference of test Recall@20, arm minus E3 (or the named
    reference), mean over seeds 1-5 (signed, 4 dp), seeds where the arm is higher / lower, two-sided paired t-test p.
    Arm: Pos (raise positive only), Disp (lower boundary only), Rand (lower a random list item), Noanc (lower boundary
    without the anchor), Aone (anchor term alone), Xre (XRE); DS: Pantry, Sci.
  * recall<K><DS>: mean over seeds 1-5 of the same-seed relative change of Recall@K, XRE against Native (%, 1 dp);
    recall<K>Pos<DS>: seeds with a positive change.
The script stops if a macro name also appears in another tables/macros_*.tex file.
Usage: python -s tables/src/build_analysis_macros.py
"""
import csv
import math
import re
import statistics as st
import sys
from pathlib import Path

from scipy import stats

ROOT = Path(__file__).resolve().parents[2]
T = ROOT / 'tables'
OUT = T / 'macros_analysis.tex'
DS = [('baby', 'Baby'), ('pantry', 'Pantry'), ('scientific', 'Scientific'), ('sports', 'Sports')]
SEEDS = [1, 2, 3, 4, 5]


def read(name):
    with open(T / name, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def main():
    out = ['% Generated by tables/src/build_analysis_macros.py. Do not edit by hand.',
           '% Sources: tables/analysis_selfmsg.csv, tables/gradsplit_perseed.csv, tables/recallk_listana.csv.']

    def mac(name, val):
        out.append(f'\\newcommand{{\\{name}}}{{{val}}}')

    sgn = lambda x: '0.0000' if round(x, 4) == 0 else f'{x:+.4f}'.replace('-', '$-$')
    pfmt = lambda p: '$<$0.001' if p < 0.001 else f'{p:.3f}'
    i0 = lambda x: f'{x:.0f}'
    f2 = lambda x: f'{x:.2f}'

    # ---------------- self-message share and kept gradient
    sm = read('analysis_selfmsg.csv')
    cell = {(r['dataset'], r['arm'], int(r['seed']), r['bin']): r for r in sm}

    def vals(arm, b, key, ds_list=DS):
        return [float(cell[(d, arm, s, b)][key]) for d, _ in ds_list for s in SEEDS if (d, arm, s, b) in cell]

    def rng(name, xs, fmt):
        mac(f'{name}Min', fmt(min(xs)))
        mac(f'{name}Max', fmt(max(xs)))

    rng('smShare', [100 * x for x in vals('native', 'all', 'share_mean')], i0)
    rng('smShareXre', [100 * x for x in vals('xre', 'all', 'share_mean')], i0)
    rng('smShort', [100 * x for x in vals('native', 'le3', 'share_mean')], i0)
    rng('smLong', [100 * x for x in vals('native', 'ge16', 'share_mean')], i0)
    for d, D in DS:
        mac(f'smShare{D}', i0(100 * st.mean(vals('native', 'all', 'share_mean', [(d, D)]))))
        mac(f'smShort{D}', i0(100 * st.mean(vals('native', 'le3', 'share_mean', [(d, D)]))))
        mac(f'smLong{D}', i0(100 * st.mean(vals('native', 'ge16', 'share_mean', [(d, D)]))))
    rng('gradKeep', vals('native', 'all', 'wratio'), f2)
    rng('gradKeepXre', vals('xre', 'all', 'wratio'), f2)
    rng('gradLost', [100 * (1 - x) for x in vals('native', 'all', 'wratio')], i0)
    rng('gradLostXre', [100 * (1 - x) for x in vals('xre', 'all', 'wratio')], i0)
    rng('gradLostShort', [100 * (1 - x) for x in vals('native', 'le3', 'wratio')], i0)
    rng('gradLostLong', [100 * (1 - x) for x in vals('native', 'ge16', 'wratio')], i0)
    for d, D in DS:
        mac(f'gradLost{D}', i0(100 * (1 - st.mean(vals('native', 'all', 'wratio', [(d, D)])))))
    rec, n_up = [], 0
    for d, D in DS:
        r = [float(cell[(d, 'xre', s, 'all')]['Ewf']) / float(cell[(d, 'native', s, 'all')]['Ewf']) for s in SEEDS
             if (d, 'xre', s, 'all') in cell and (d, 'native', s, 'all') in cell]
        rec += r
        mac(f'gradRec{D}', f2(math.exp(st.mean(math.log(x) for x in r))))
    rng('gradRec', rec, f2)
    mac('gradRecPairs', f'{sum(x > 1 for x in rec)}/{len(rec)}')

    # ---------------- gradient-direction split (Pantry, Scientific)
    gp = {(r['dataset'], r['arm'], int(r['seed'])): float(r['r20']) for r in read('gradsplit_perseed.csv')}

    def paired(d, a, b):
        ss = [s for s in SEEDS if (d, a, s) in gp and (d, b, s) in gp]
        x, y = [gp[(d, a, s)] for s in ss], [gp[(d, b, s)] for s in ss]
        dd = [p - q for p, q in zip(x, y)]
        m = st.mean(dd)
        p = float(stats.ttest_rel(x, y).pvalue) if any(abs(e) > 1e-12 for e in dd) else 1.0
        return (m if abs(m) > 5e-9 else 0.0), sum(e > 1e-12 for e in dd), sum(e < -1e-12 for e in dd), p, len(ss)

    contrasts = [('Pos', 'pos', 'e3'), ('Disp', 'disp', 'e3'), ('Rand', 'bdrand', 'e3'), ('Noanc', 'bdnoanc', 'e3'),
                 ('Aone', 'A1', 'e3'), ('Xre', 'XRE', 'e3'), ('PosXre', 'pos', 'XRE'), ('DispXre', 'disp', 'XRE'),
                 ('RandDisp', 'bdrand', 'disp'), ('NoancNative', 'bdnoanc', 'Native'), ('NoancXre', 'bdnoanc', 'XRE'),
                 ('NoancDisp', 'bdnoanc', 'disp'), ('DispPos', 'disp', 'pos')]
    for d, D in [('pantry', 'Pantry'), ('scientific', 'Sci')]:
        for nm, a, b in contrasts:
            m, hi, lo, p, n = paired(d, a, b)
            mac(f'split{nm}{D}Delta', sgn(m))
            mac(f'split{nm}{D}Wins', hi)
            mac(f'split{nm}{D}Losses', lo)
            mac(f'split{nm}{D}P', pfmt(p))
        for arm, nm in [('e3', 'Ethree'), ('pos', 'Pos'), ('disp', 'Disp'), ('bdrand', 'Rand'), ('bdnoanc', 'Noanc')]:
            mac(f'split{nm}{D}Mean', f'{st.mean(gp[(d, arm, s)] for s in SEEDS):.4f}')
    mac('splitNSeeds', len(SEEDS))

    # ---------------- Recall@K profile
    rk = {(r['dataset'], r['arm'], int(r['seed']), int(r['k'])): float(r['recall']) for r in read('recallk_listana.csv')}
    for k, K in [(5, 'Five'), (10, 'Ten'), (20, 'Twenty'), (50, 'Fifty')]:
        for d, D in DS:
            rel = [100 * (rk[(d, 'XRE', s, k)] - rk[(d, 'Native', s, k)]) / rk[(d, 'Native', s, k)] for s in SEEDS
                   if (d, 'XRE', s, k) in rk and (d, 'Native', s, k) in rk]
            m = st.mean(rel)
            mac(f'recall{K}{D}', '0.0' if round(m, 1) == 0 else f'{m:.1f}'.replace('-', '$-$'))
            mac(f'recall{K}Pos{D}', sum(x > 0 for x in rel))

    # ---------------- name collisions with the other macro files
    mine = set(re.findall(r'\\newcommand\{\\([A-Za-z]+)\}', '\n'.join(out)))
    for f in T.glob('macros_*.tex'):
        if f.name == OUT.name:
            continue
        clash = mine & set(re.findall(r'\\newcommand\{\\([A-Za-z]+)\}', f.read_text(encoding='utf-8')))
        if clash:
            sys.exit(f'macro names also in {f.name}: {sorted(clash)}')
    OUT.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print('wrote', OUT, len(mine), 'macros')


if __name__ == '__main__':
    main()
