"""Prose macros of the near-duplicate paragraph of the supplement (Section supp:further) (revision log 18-1, 2026-10-16):
tables/macros_neardup.tex (prefix nd). Numbers are never typed by hand.
Inputs (copies of HOST_A <RUN_ROOT>/W2/results, sha256 in revision log 18-1):
  tables/src/data/w2_003.json  W2-003: new near-duplicate targets (text cosine >= 0.95 to a history item, at most two
      training edges); z.<ds>.n and frac_txt_linked; frac_classA_collapse (LightGCN, LGMRec, DiffMM cells that collapse),
      frac_classB_survive (FREEDOM, MENTOR cells that keep the targets), frac_P_survive_rel (MSCA variants); detail.<ds>.models
  tables/src/data/w2_002.json  W2-002: FREEDOM with its kNN-inheritance term scaled by s at inference; ratio = hits on
      targets with at most two training edges over random hits; s = 1 original, s = 0 removed
Usage: python tables/src/build_neardup_macros.py
"""
import json
from pathlib import Path

from numwords import num_word

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'src' / 'data'
ORDER = ['office', 'clothing', 'scientific', 'sports', 'arts', 'instruments', 'baby', 'pantry']
NAMES = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports', 'clothing': 'Clothing',
         'instruments': 'Instruments', 'arts': 'Arts', 'office': 'Office'}
CLASS_A, CLASS_B = ('lightgcn', 'lgmrec', 'diffmm'), ('freedom', 'mentor')


def main():
    w3 = json.load(open(DATA / 'w2_003.json', encoding='utf-8'))
    w2 = json.load(open(DATA / 'w2_002.json', encoding='utf-8'))
    z = w3['z']
    # recount the class fractions from the per-cell flags
    ca = [m for d in w3['detail'].values() for k, m in d.get('models', {}).items() if k in CLASS_A]
    cb = [m for d in w3['detail'].values() for k, m in d.get('models', {}).items() if k in CLASS_B]
    fa = sum(m['collapse'] for m in ca) / len(ca); fb = sum(m['survive'] for m in cb) / len(cb)
    assert abs(fa - w3['frac_classA_collapse']) < 1e-12 and abs(fb - w3['frac_classB_survive']) < 1e-12, (fa, fb)
    ns = sorted(((z[d]['n'], d) for d in z), key=lambda t: -t[0])
    lk = [z[d]['frac_txt_linked'] for d in z if z[d]['n']]
    S = w2['summary']
    fr = {d: (S[f'{d}__freedom']['scales']['1.0']['ratio'], S[f'{d}__freedom']['scales']['0.0']['ratio']) for d in ('arts', 'sports')}
    M = ['% Generated by tables/src/build_neardup_macros.py from tables/src/data/w2_003.json and w2_002.json. Do not edit by hand.',
         f'\\newcommand{{\\ndMax}}{{{ns[0][0]}}}',
         '\\newcommand{\\ndList}{' + ', '.join(f'{NAMES[d]} {num_word(n)}' for n, d in ns) + '}',
         f'\\newcommand{{\\ndLinkMin}}{{{100 * min(lk):.0f}}}',
         f'\\newcommand{{\\ndLinkMax}}{{{100 * max(lk):.0f}}}',
         f'\\newcommand{{\\ndCollapseA}}{{{100 * fa:.0f}}}',
         f'\\newcommand{{\\ndSurviveB}}{{{100 * fb:.0f}}}',
         f'\\newcommand{{\\ndSurviveP}}{{{100 * w3["frac_P_survive_rel"]:.0f}}}',
         f'\\newcommand{{\\ndFreedomArtsOn}}{{{fr["arts"][0]:.1f}}}',
         f'\\newcommand{{\\ndFreedomArtsOff}}{{{fr["arts"][1]:.2f}}}',
         f'\\newcommand{{\\ndFreedomSportsOn}}{{{fr["sports"][0]:.1f}}}',
         f'\\newcommand{{\\ndFreedomSportsOff}}{{{fr["sports"][1]:.2f}}}', '']
    (ROOT / 'macros_neardup.tex').write_text('\n'.join(M), encoding='utf-8', newline='\n')
    print('\n'.join(M))


if __name__ == '__main__':
    main()
