"""Supplementary table of the lambda x K choice of MES on MSCA (revision log 18-4, 2026-10-16). Numbers are never typed by hand.

Inputs
  tables/src/data/lamk_fixed_vs_tuned_s4.csv   per dataset: tuned (selected) and fixed (lambda 0.1, K 40) five-seed test Recall@20
                                               (tables/src/build_lamk_grid_s4.py)
  tables/src/data/lamk_grid_s4.csv             seed-1 validation Recall@20 of every scanned (lambda, K) setting per dataset
  tables/mes_perseed.csv                       per-seed test Recall@20 of rows MES (tuned) and MES_k40 (fixed) on MSCA; the
                                               post-hoc paired test over seeds 1-5 uses tables/src/sigtest.py (Holm over datasets)
Outputs
  tables/appendix_lamk.tex   table tab:lamk (one column): tuned row and fixed row per dataset, difference, p and Holm-adjusted p
  tables/macros_lamk.tex     prose macros of the table sentence and of the selection description of the supplement
Selection (stated in the text, counted here): seed-1 validation Recall@20, one setting varied at a time around lambda 0.1 and
K 40, not a full grid; a tie is a second setting within 1e-4 of the best seed-1 validation Recall@20.
Usage: python -s tables/src/build_table_lamk.py
"""
import csv
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import sigtest                      # noqa: E402
from numwords import num_word       # noqa: E402

D = ROOT / 'src' / 'data'
DS = ['baby', 'pantry', 'scientific', 'sports']
NAME = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports'}
TIE = 1e-4


def join(xs):
    xs = list(xs)
    if not xs:
        return 'none of the datasets'
    if len(xs) == 1:
        return xs[0]
    if len(xs) == 2:
        return f'{xs[0]} and {xs[1]}'
    return ', '.join(xs[:-1]) + f', and {xs[-1]}'


def fnum(x):
    return f'{x:g}'


def main():
    fv = {r['dataset']: r for r in csv.DictReader(open(D / 'lamk_fixed_vs_tuned_s4.csv', encoding='utf-8'))}
    grid = defaultdict(list)
    for r in csv.DictReader(open(D / 'lamk_grid_s4.csv', encoding='utf-8')):
        grid[r['dataset']].append(r)
    ps = defaultdict(dict)
    for r in csv.DictReader(open(ROOT / 'mes_perseed.csv', encoding='utf-8')):
        if r['backbone'] == 'MSCA' and r['row'] in ('MES', 'MES_k40'):
            ps[(r['row'], r['dataset'])][int(r['seed'])] = float(r['r20'])
    tuned = {d: ps[('MES', d)] for d in DS}
    fixed = {d: ps[('MES_k40', d)] for d in DS}
    res = sigtest.contrast(tuned, fixed, DS, fam='lamk', name='tuned - fixed', a='MES tuned', b='MES lambda 0.1 K 40', metric='r20')
    for r in res:    # agreement with the CSV of build_lamk_grid_s4.py
        c = fv[r['dataset']]
        assert abs(r['p'] - float(c['p_two_sided_post_hoc'])) < 6e-5, (r['dataset'], r['p'], c['p_two_sided_post_hoc'])
        assert abs(r['mean_a'] - float(c['tuned_mean5'])) < 6e-6 and abs(r['mean_b'] - float(c['fixed_mean5'])) < 6e-6

    cells = {d: len(grid[d]) for d in DS}
    assert len(set(cells.values())) == 1, cells
    n_set = cells[DS[0]]
    lams = sorted({float(r['lam']) for d in DS for r in grid[d]})
    ks = sorted({int(r['K']) for d in DS for r in grid[d]})
    ties = []
    for d in DS:
        v = {(r['lam'], r['K']): float(r['seed1_valid_r20']) for r in grid[d]}
        best = max(v.values())
        n_near = sum(1 for x in v.values() if round(best - x, 6) <= TIE + 1e-9) - 1   # settings other than the best one
        if n_near > 0:
            ties.append(d)
    higher_fixed = [NAME[r['dataset']] for r in res if r['diff'] < 0]
    ps_raw = [r['p'] for r in res]
    n_sig = sum(r['reject'] for r in res)
    n_sig_raw = sum(r['p'] < 0.05 for r in res)

    def row_tuned(r):
        c = fv[r['dataset']]
        return (f"{NAME[r['dataset']]} & Tuned & {fnum(float(c['tuned_lam']))} & {c['tuned_K']} & "
                f"{r['mean_a']:.4f}{{\\tiny$\\pm$.{round(float(c['tuned_sd5']) * 1e4):04d}}} & & \\\\")

    def row_fixed(r):
        c = fv[r['dataset']]
        return (f" & Fixed & {fnum(float(c['fixed_lam']))} & {c['fixed_K']} & "
                f"{r['mean_b']:.4f}{{\\tiny$\\pm$.{round(float(c['fixed_sd5']) * 1e4):04d}}} & "
                f"${r['diff']:+.4f}$ & {r['p']:.2f} ({r['p_holm']:.2f}) \\\\")

    cap = ('Test Recall@20 of MES on MSCA with the setting selected on seed-1 validation (tuned, used in the main text) and with '
           '$\\lambda=0.1$ and $K=40$ (fixed), as the mean over seeds 1--5 with the standard deviation over seeds. '
           'Diff.: tuned minus fixed mean. '
           '$p$: post hoc two-sided paired $t$-test over seeds 1--5, with the Holm-adjusted value over the four datasets in parentheses.')
    lines = [
        '% Generated by tables/src/build_table_lamk.py from tables/src/data/lamk_fixed_vs_tuned_s4.csv, lamk_grid_s4.csv and tables/mes_perseed.csv '
        '(test: tables/src/sigtest.py, post hoc). Do not edit numbers by hand.',
        '\\begin{table}[t]',
        f'\\caption{{{cap}}}',
        '\\label{tab:lamk}',
        '\\centering',
        '\\scriptsize',
        '\\setlength{\\tabcolsep}{3pt}',
        '\\begin{tabular}{@{}llccccc@{}}',
        '\\toprule',
        'Dataset & Row & $\\lambda$ & $K$ & Recall@20 & Diff. & $p$ (Holm) \\\\',
        '\\midrule',
    ]
    for i, r in enumerate(res):
        lines += [row_tuned(r), row_fixed(r)]
        if i < len(res) - 1:
            lines.append('\\addlinespace[1pt]')
    lines += ['\\bottomrule', '\\end{tabular}', '\\end{table}', '']
    (ROOT / 'appendix_lamk.tex').write_text('\n'.join(lines), encoding='utf-8', newline='\n')

    pmin, pmax = min(ps_raw), max(ps_raw)
    mac = [
        '% Generated by tables/src/build_table_lamk.py (revision log 18-4). Do not edit by hand.',
        '% lambda x K choice of MES on MSCA: tuned (seed-1 validation) against fixed (lambda 0.1, K 40), post hoc paired test over seeds 1-5.',
        f'\\newcommand{{\\lkNDs}}{{{num_word(len(DS))}}}',
        f'\\newcommand{{\\lkNSettings}}{{{num_word(n_set)}}}',
        f'\\newcommand{{\\lkLamList}}{{{", ".join(fnum(x) for x in lams)}}}',
        f'\\newcommand{{\\lkKList}}{{{", ".join(str(x) for x in ks)}}}',
        f'\\newcommand{{\\lkTieN}}{{{num_word(len(ties))}}}',
        f'\\newcommand{{\\lkTieDs}}{{{join(NAME[d] for d in ties)}}}',
        f'\\newcommand{{\\lkFixedHigherDs}}{{{join(higher_fixed)}}}',
        f'\\newcommand{{\\lkNSig}}{{{num_word(n_sig) if n_sig else "none"}}}',
        f'\\newcommand{{\\lkNSigRaw}}{{{num_word(n_sig_raw) if n_sig_raw else "none"}}}',
        f'\\newcommand{{\\lkPMin}}{{{pmin:.2f}}}',
        f'\\newcommand{{\\lkPMax}}{{{pmax:.2f}}}',
        f'\\newcommand{{\\lkPMinNoZero}}{{{pmin:.2f}'.replace('0.', '.') + '}',
        f'\\newcommand{{\\lkPMaxNoZero}}{{{pmax:.2f}'.replace('0.', '.') + '}',
        f'\\newcommand{{\\lkPHolmMin}}{{{min(r["p_holm"] for r in res):.2f}}}',
    ]
    (ROOT / 'macros_lamk.tex').write_text('\n'.join(mac) + '\n', encoding='utf-8', newline='\n')
    print('\n'.join(lines))
    print('\n'.join(mac))
    print('ties', ties, 'higher fixed', higher_fixed, 'n_sig', n_sig, 'raw', n_sig_raw, [(r['dataset'], round(r['p'], 4), round(r['p_holm'], 4)) for r in res])


if __name__ == '__main__':
    main()
