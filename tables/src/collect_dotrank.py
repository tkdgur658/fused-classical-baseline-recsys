"""Macros for the score-function diagnostic of the MSCA top-K rows (internal review 2, R2 W3 / AE B2): cosine training with
inner-product ranking (objx_score cosine_dotrank, IR-Benchmark with --norm off), next to cosine training and ranking and
inner-product training and ranking, at the same temperature. Baby, seed 1, validation Recall@20 (best_valid_primed), as
run in P04_topk step 2 (README.txt of <RUN_ROOT_B>/P04_topk, branch topk; diagnostic configs outside the grid).
Configs: SSM tau 0.5 (baby_ssm_t050{,_dot,_dotrank}), SL@K tau 0.2 (baby_slk_t020{,_dot,_dotrank}); lr 0.001 = MSCA.
Eligible run: status SUCCESS, mode train, test_eval best_primed, seed 1; exactly one run per config.
Output: tables/macros_dotrank.tex. Usage (repository root): python -s tables/src/collect_dotrank.py
"""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'tables' / 'macros_dotrank.tex'
CFG = {('ssm', 'cos'): 'baby_ssm_t050', ('ssm', 'dot'): 'baby_ssm_t050_dot', ('ssm', 'cdr'): 'baby_ssm_t050_dotrank',
       ('slk', 'cos'): 'baby_slk_t020', ('slk', 'dot'): 'baby_slk_t020_dot', ('slk', 'cdr'): 'baby_slk_t020_dotrank'}
REMOTE = r'''
import glob, json, sys
for cfg in sys.argv[1:]:
    out = []
    for f in glob.glob('<RUN_ROOT_B>/P04_topk/runs_*/objx_s/objx_s__%s__baby__s1__train__*/result.json' % cfg):
        r = json.load(open(f))
        if (r.get('status') == 'SUCCESS' and r.get('mode') == 'train' and r.get('test_eval') == 'best_primed'
                and int(r.get('seed', 0)) == 1 and r.get('config') == cfg):
            out.append(r['best_valid_primed']['recall@20'])
    print(json.dumps({'cfg': cfg, 'vals': out}))
'''


def main():
    res = subprocess.run(['ssh', '-o', 'BatchMode=yes', 'HOST_A', 'python3 - ' + ' '.join(CFG.values())], input=REMOTE,
                         capture_output=True, text=True, check=True).stdout.splitlines()
    val = {}
    for line in res:
        j = json.loads(line)
        assert len(j['vals']) == 1, j
        val[j['cfg']] = j['vals'][0]
    name = {'ssm': 'Ssm', 'slk': 'Slk'}
    var = {'cos': 'Cos', 'dot': 'Dot', 'cdr': 'CosDot'}
    lines = ['% Generated by tables/src/collect_dotrank.py. Do not edit by hand.']
    for (loss, v), cfg in CFG.items():
        lines.append(f'\\newcommand{{\\dr{name[loss]}{var[v]}}}{{{val[cfg]:.4f}}}')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print('wrote', OUT, val)


if __name__ == '__main__':
    main()
