"""Build the appendix table of the official-code reproduction on FREEDOM-Baby. Numbers are never typed by hand.

Inputs (produced by collect_official_repro.py, see its docstring):
  tables/official_repro_combos.tsv    one row per finished grid combination of the released code
  tables/official_repro_reported.csv  values printed in the papers (checked against the paper text)
Outputs:
  tables/appendix_official_repro.tex        (label tab:official_repro)
  tables/appendix_official_repro_cells.csv  (selected combinations and gains, for the text and for checking)
Selection rules, applied separately to the native grid and to the plug-in grid of each seed:
  test-selected       = argmax of the test value of the early-stopping metric (the rule of the released quick_start)
  validation-selected = argmax of the validation value of the same metric
The metric shown is the one the paper reports for FREEDOM-Baby. Seed 999 (the seed fixed in every released
configuration) is always shown, flagged as partial while its grid is unfinished. Other seeds are listed only when
both grids are complete.
Usage: python tables/src/build_table_official_repro.py
"""
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMBOS = ROOT / 'official_repro_combos.tsv'
REPORTED = ROOT / 'official_repro_reported.csv'
OUT = ROOT / 'appendix_official_repro.tex'
OUT_CELLS = ROOT / 'appendix_official_repro_cells.csv'

# (key, printed plug-in label, backbone label). Order of the table rows.
ROWS = [('MG', 'MG', 'FREEDOM'), ('MDVT-D', 'MDVT (D)', 'FREEDOM'),
        ('DA-MRS', 'DA-MRS$^{\\S}$', 'LightGCN')]
MLABEL = {'recall@5': 'R@5', 'recall@10': 'R@10', 'recall@20': 'R@20'}
REPO = {'MG': 'Qrange-group/Mirror-Gradient @ a28908d', 'MDVT-D': 'Jinfeng-Xu/MDVT @ 20df977',
        'VI-MMRec': 'Jinfeng-Xu/VI-MMRec @ b793b90', 'DA-MRS': 'XMUDM/DA-MRS @ 7dee19e'}
NOTE_FIXED = {
    'VI-MMRec': 'Repository holds a README and one module, without a training entry point or FREEDOM integration',
    'DA-MRS': 'LightGCN backbone, since the paper reports no FREEDOM result',
}


def load():
    with open(COMBOS, newline='') as f:
        combos = list(csv.DictReader(f, delimiter='\t'))
    with open(REPORTED, newline='') as f:
        reported = {r['plugin']: r for r in csv.DictReader(f)}
    grids = {}
    for r in combos:
        grids.setdefault((r['plugin'], r['seed'], r['arm']), []).append(r)
    return grids, reported


def select(rows, split):
    vm = rows[0]['sel_metric']
    return max(rows, key=lambda r: float(r[f'{split}_{vm}']))


def gain(a, b):
    return 100.0 * (b / a - 1.0)


def arrow(a, b):
    g = f'{gain(a, b):+.1f}'.replace('-', '$-$')
    return f'{a:.4f} $\\rightarrow$ {b:.4f} ({g}\\%)'


def main():
    grids, reported = load()
    lines = [
        f'% Generated by tables/src/build_table_official_repro.py from tables/official_repro_combos.tsv '
        f'(sha256 {hashlib.sha256(COMBOS.read_bytes()).hexdigest()[:16]}) and tables/official_repro_reported.csv '
        f'(sha256 {hashlib.sha256(REPORTED.read_bytes()).hexdigest()[:16]}). Do not edit numbers by hand.',
        '\\begin{table*}[t]',
        '\\caption{Reported gains on FREEDOM--Baby and results of the released code of each plug-in, run with the '
        'repository scripts, configurations, grids, and seed 999, with MG also run on seeds 1--4. '
        'The only edits are library-compatibility fixes, a data-file name alignment for DA-MRS, and removal of an '
        'unused import in the DA-MRS LightGCN file. '
        'Each cell reads backbone $\\rightarrow$ +plug-in (relative gain). '
        'Test-selected: within each backbone or plug-in grid, the combination with the highest test value of the early-stopping metric, which the '
        'released scripts print as the best result. '
        'Validation-selected: the combination with the highest validation value of the same metric '
        '(Recall@5 for MG, Recall@20 for MDVT and DA-MRS). '
        'Reported values are from the arXiv versions of the papers. '
        '$^{\\S}$On the LightGCN baseline of the DA-MRS repository, run with the configuration of the released author log. '
        'Repositories: ' + ', '.join(f'\\texttt{{{REPO[k]}}}' for k, _, _ in ROWS) + '.}',
        '\\label{tab:official_repro}',
        '\\centering',
        '\\footnotesize',
        '\\setlength{\\tabcolsep}{3pt}',
        '\\begin{tabular}{lcccc>{\\raggedright\\arraybackslash}p{4.2cm}}',
        '\\toprule',
        ' & & \\multicolumn{3}{c}{Backbone $\\rightarrow$ +plug-in (gain)} & \\\\',
        '\\cmidrule(lr){3-5}',
        'Plug-in & Metric & Reported & Test-selected & Validation-selected & Note \\\\',
        '\\midrule',
    ]
    cells = []
    for key, label, bb in ROWS:
        rep = reported[key]
        m = rep['metric']
        rep_cell = arrow(float(rep['native']), float(rep['plugin_value']))
        seeds = sorted({s for (p, s, _) in grids if p == key}, key=lambda s: (s != '999', int(s)))
        shown = False
        for s in seeds:
            nat, plug = grids.get((key, s, 'native')), grids.get((key, s, 'plugin'))
            if not nat or not plug:
                continue
            n_exp, p_exp = int(nat[0]['expected']), int(plug[0]['expected'])
            complete = len(nat) == n_exp and len(plug) == p_exp
            if s != '999' and not complete:
                continue
            ts = (select(nat, 'test'), select(plug, 'test'))
            vs = (select(nat, 'valid'), select(plug, 'valid'))
            t_cell = arrow(float(ts[0][f'test_{m}']), float(ts[1][f'test_{m}']))
            v_cell = arrow(float(vs[0][f'test_{m}']), float(vs[1][f'test_{m}']))
            notes = [f'Seed {s}'] if (s != '999' or len(seeds) > 1) else []
            if complete and s != '999':
                pass  # other seeds repeat the seed-999 grid, so their note names only the seed
            elif complete:
                notes.append(f'Grid of {n_exp} backbone and {p_exp} plug-in combination' + ('s' if p_exp > 1 else ''))
            else:
                notes.append(f'Partial: {len(plug)} of {p_exp} plug-in and {len(nat)} of {n_exp} backbone combinations')
            for name, sel in (('test', ts[1]), ('validation', vs[1])):
                sw = json.loads(sel['params']).get('s_weight')
                if sw is not None and float(sw) == 0.0:
                    notes.append(f'The {name}-selected plug-in combination sets s\\_weight to 0, '
                                 'which removes the MDVT loss term')
            if key in NOTE_FIXED:
                notes.append(NOTE_FIXED[key])
            grid = f'{len(plug)}/{p_exp}'
            lines.append(f'{label if not shown else ""} & '
                         f'{MLABEL[m] if not shown else ""} & {rep_cell if not shown else ""} & {t_cell} & {v_cell} & '
                         + ('. '.join(notes) + '.' if notes else '') + ' \\\\')
            cells.append([key, bb, m, s, rep['native'], rep['plugin_value'], ts[0][f'test_{m}'], ts[1][f'test_{m}'],
                          vs[0][f'test_{m}'], vs[1][f'test_{m}'], len(nat), n_exp, len(plug), p_exp,
                          ts[0]['params'], ts[1]['params'], vs[0]['params'], vs[1]['params']])
            shown = True
        if not shown:
            note = NOTE_FIXED.get(key, 'Not run')
            lines.append(f'{label} & {MLABEL[m]} & {rep_cell} & -- & -- & {note}. \\\\')
            cells.append([key, bb, m, '', rep['native'], rep['plugin_value']] + [''] * 12)
    lines += ['\\bottomrule', '\\end{tabular}', '\\end{table*}', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    with open(OUT_CELLS, 'w', newline='') as f:
        w = csv.writer(f, lineterminator='\n')
        w.writerow(['plugin', 'backbone', 'metric', 'seed', 'reported_native', 'reported_plugin', 'testsel_native',
                    'testsel_plugin', 'validsel_native', 'validsel_plugin', 'native_done', 'native_total',
                    'plugin_done', 'plugin_total', 'testsel_native_params', 'testsel_plugin_params',
                    'validsel_native_params', 'validsel_plugin_params'])
        w.writerows(cells)
    print('wrote', OUT, OUT_CELLS)


if __name__ == '__main__':
    main()
