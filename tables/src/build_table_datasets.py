"""Build tables/appendix_datasets.tex (dataset statistics of all nine datasets) and tables/macros_datasets.tex from
tables/dataset_stats.csv (collect_dataset_stats.py, read-only scan of canonical_v2 on HOST_A).
Numbers are never typed by hand.  Usage: python tables/src/build_table_datasets.py
revision log 18-1 (2026-10-16): nine datasets (before: Baby, Pantry, Scientific, Sports), a source column, the feature
dimensions of every modality in one column (image/text, plus video for MicroLens), stacked as two panels (the four
datasets of the main comparisons, then the five added for F, C, and N') instead of shrinking the table.
Sources (verified on HTML pages, see references.bib comments): Baby, Sports, Clothing = Amazon domains distributed with
MMRec [zhou2023mmrec] (4,096-d image, 384-d text features); Pantry, Scientific, Instruments, Arts, Office = the
downstream Amazon domains of MISSRec [wang2023missrec] (512-d CLIP-B/32 image and text features); MicroLens =
[ni2023microlens] (image, text, and video features).
"""
import csv
import hashlib
import math
from pathlib import Path

from numwords import num_word

ROOT = Path(__file__).resolve().parents[1]
CSV = ROOT / 'dataset_stats.csv'
NAMES = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports', 'clothing': 'Clothing',
         'instruments': 'Instruments', 'arts': 'Arts', 'office': 'Office', 'microlens': 'MicroLens'}
PANELS = [('Datasets of the main comparisons', ['baby', 'pantry', 'scientific', 'sports']),
          ('Datasets added for F, C, and N$\'$', ['clothing', 'instruments', 'arts', 'office', 'microlens'])]
SRC = {'baby': '\\cite{zhou2023mmrec}', 'sports': '\\cite{zhou2023mmrec}', 'clothing': '\\cite{zhou2023mmrec}',
       'pantry': '\\cite{wang2023missrec}', 'scientific': '\\cite{wang2023missrec}', 'instruments': '\\cite{wang2023missrec}',
       'arts': '\\cite{wang2023missrec}', 'office': '\\cite{wang2023missrec}', 'microlens': '\\cite{ni2023microlens}'}
COLS = [('users', 'Users'), ('items', 'Items'), ('interactions', 'Inter.'), ('density', 'Density'),
        ('train', 'Train'), ('valid', 'Valid'), ('test', 'Test'), ('dims', 'Features'), ('image_filled', 'Filled')]
NPRIME_DS = ['baby', 'pantry', 'scientific', 'sports', 'clothing', 'instruments', 'arts', 'office']   # N' with MES (R2NULL3)


def main():
    rows = {r['dataset']: r for r in csv.DictReader(open(CSV, newline='', encoding='utf-8'))}
    assert set(NAMES) <= set(rows), sorted(set(NAMES) - set(rows))
    sha = hashlib.sha256(CSV.read_bytes()).hexdigest()[:16]

    def v(r, k):
        if k == 'density':
            return f"{100 * float(r[k]):.3f}\\%"
        if k == 'dims':
            d = [f"{int(r['image_dim']):,}", f"{int(r['text_dim']):,}"] + ([f"{int(r['video_dim']):,}"] if r['video_dim'] else [])
            return '/'.join(d)
        return f"{int(r[k]):,}"
    for r in rows.values():                                    # consistency of the scan
        assert int(r['train']) + int(r['valid']) + int(r['test']) == int(r['interactions']), r['dataset']
        assert abs(float(r['density']) - int(r['interactions']) / (int(r['users']) * int(r['items']))) < 1e-6
    ncol = 2 + len(COLS)
    lines = [f'% Generated by tables/src/build_table_datasets.py from tables/dataset_stats.csv (sha256 {sha}). Do not edit numbers by hand.',
             '\\begin{table*}[t]',
             '\\caption{Dataset statistics of the nine datasets, with the source of each. Train, Valid, and Test count the '
             'interactions per split. Features gives the dimensions of the frozen image and text item features, and of the '
             'video features for MicroLens. Filled counts the items whose all-zero image feature vector is replaced by the '
             'mean of the nonzero vectors.}',
             '\\label{tab:datasets}', '\\centering', '\\scriptsize', '\\setlength{\\tabcolsep}{2.6pt}',
             '\\begin{tabular}{ll' + 'r' * len(COLS) + '}', '\\toprule',   # no \resizebox (lab rule); panels stacked
             'Dataset & Source & ' + ' & '.join(n for _, n in COLS) + ' \\\\']
    for title, dss in PANELS:
        lines += ['\\midrule', f'\\multicolumn{{{ncol}}}{{l}}{{\\emph{{{title}}}}} \\\\']
        for ds in dss:
            lines.append(f"{NAMES[ds]} & {SRC[ds]} & " + ' & '.join(v(rows[ds], k) for k, _ in COLS) + ' \\\\')
    lines += ['\\bottomrule', '\\end{tabular}', '\\end{table*}', '']
    (ROOT / 'appendix_datasets.tex').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    # share of test users with exactly one test target, over the datasets of N' (MES as the learned ranker)
    shares = {ds: int(rows[ds]['test_users_one']) / int(rows[ds]['test_users']) for ds in NPRIME_DS}
    lo = min(shares.values())
    m = ['% Generated by tables/src/build_table_datasets.py from tables/dataset_stats.csv. Do not edit by hand.',
         f'% share of test users with one test target (N\' datasets): ' + ', '.join(f'{d} {100 * s:.2f}' for d, s in shares.items()),
         f'\\newcommand{{\\dsOnePosMin}}{{{math.floor(1000 * lo) / 10:.1f}}}',      # floor: "at least"
         f'\\newcommand{{\\dsOnePosMinDs}}{{{NAMES[min(shares, key=shares.get)]}}}',
         f'\\newcommand{{\\dsNAll}}{{{num_word(len(NAMES))}}}',
         f'\\newcommand{{\\dsUsersMin}}{{{min(int(r["users"]) for d, r in rows.items() if d in NAMES):,}}}',
         f'\\newcommand{{\\dsUsersMax}}{{{max(int(r["users"]) for d, r in rows.items() if d in NAMES):,}}}', '']
    (ROOT / 'macros_datasets.tex').write_text('\n'.join(m), encoding='utf-8', newline='\n')
    print('wrote appendix_datasets.tex, macros_datasets.tex; one-positive share min', round(100 * lo, 2))


if __name__ == '__main__':
    main()
