"""revision log 29 (journal review round 2, author decision): prose macros of the nine-dataset F count, the mix margins,
the same-checkpoint seed-1 check, and the public CSV of the fused cells.  Writes tables/macros_rev2.tex (prefix rv),
tables/src/data/rev2_pairs.csv, tables/src/data/rev2_margins.csv and supplementary_data_classic_fusion.csv (repository root).
Numbers are never typed by hand; counts 0-10 are spelled out.

Universe (items 4 and 5 of revision log 29).  The fused cells of the CLASSIC step (build_table_classic.cell: the TABLE_FUSION/MES9 F of
every gated checkpoint, plus the F recomputed by tf_fuse_ce.py --combo on Arts, Office and MicroLens, where the four tuned datasets keep
the TABLE_FUSION values, max difference of the recomputed cells 0).  A (model, dataset) pair enters when at least one seed holds the
unfused and the F-fused Recall@20; a pair is tested only with at least MIN_SEEDS seeds (the rule of build_table_classic.py, which gives
the 65 pairs of the mix counts), with sigtest.paired and Holm over the datasets of one model (family 'fused vs unfused').
Same-checkpoint check (item 2): tables/src/data/rev2_msca_t2_s1.csv = HOST_A study/REV2/rev2_msca_t2_s1.csv (tf_fuse_ce.py --combo,
unchanged, on the Table-II MSCA seed-1 checkpoints of Baby, Pantry and Scientific, the only Table-II MSCA checkpoints stored there;
its F column equals study/REFUSE fusion_cells_s4.csv, asserted).
Usage: python -s tables/src/build_rev2.py
"""
import csv
import re
import statistics as st
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import sigtest  # noqa: E402
from numwords import num_word  # noqa: E402
import build_table_classic as bc  # noqa: E402   (module import: reads the cells, does not write anything)

ROOT = HERE.parent
REPO = ROOT.parent
DATA = HERE / 'data'
MIN_SEEDS = 3
DS9 = bc.DS9
NAME = bc.NAME
MLAB = bc.MLAB
FOUR = ['baby', 'pantry', 'scientific', 'sports']
OUT = ['% Generated by tables/src/build_rev2.py (revision log 29) from the CLASSIC fused cells (build_table_classic.cell), '
       'rev2_msca_t2_s1.csv and fusion_cells_s4.csv. Do not edit by hand.']


def mac(n, v):
    assert re.fullmatch(r'[A-Za-z]+', n), n
    OUT.append(f'\\newcommand{{\\{n}}}{{{v}}}')


def cnt(k):
    return num_word(k)


def join(xs):
    xs = list(xs)
    if not xs:
        return 'none'
    return xs[0] if len(xs) == 1 else (' and '.join(xs) if len(xs) == 2 else ', '.join(xs[:-1]) + ', and ' + xs[-1])


def sgn(x, nd=4):
    s = f'{x:+.{nd}f}'
    return s.replace('-', '$-$').replace('+', '$+$')


def seeds(m, d, *vs):
    return [s for s in bc.SEEDS if (m, d, s) in bc.cell and all(v in bc.cell[(m, d, s)] for v in vs)]


def f_universe():
    """every (model, dataset) pair with at least one seed holding base and F"""
    pairs = []
    for m in bc.MODELS:
        for d in DS9:
            s = seeds(m, d, 'base', 'combo')
            if s:
                b = st.mean(bc.cell[(m, d, i)]['base'] for i in s)
                f = st.mean(bc.cell[(m, d, i)]['combo'] for i in s)
                pairs.append(dict(model=m, dataset=d, n=len(s), seeds='/'.join(map(str, s)), base=b, F=f, up=int(f > b)))
    # tests: paired t over the seeds, Holm over the datasets of one model, pairs with >= MIN_SEEDS seeds
    for m in bc.MODELS:
        res = []
        for p in pairs:
            if p['model'] == m and p['n'] >= MIN_SEEDS:
                s = [int(x) for x in p['seeds'].split('/')]
                r = sigtest.paired([bc.cell[(m, p['dataset'], i)]['combo'] for i in s], [bc.cell[(m, p['dataset'], i)]['base'] for i in s])
                r['pair'] = p
                res.append(r)
        sigtest.family(res)
        for r in res:
            r['pair'].update(tested=1, p=r['p'], p_holm=r['p_holm'], reject=r['reject'], diff=r['diff'])
    for p in pairs:
        p.setdefault('tested', 0)
    return pairs


def margins():
    """MSCA + MES minus MSCA after each fusion variant (Recall@20 and NDCG@20), the CLASSIC family (Holm over the datasets with both rows)"""
    out = []
    for v in ('base', 'combo', 'mix'):
        for k in ('r20', 'n20'):
            res = []
            for d in DS9:
                s = [i for i in bc.SEEDS if all((m, d, i) in bc.cell and v in bc.cell[(m, d, i)] for m in ('MSCA+MES', 'MSCA'))]
                if len(s) < MIN_SEEDS:
                    continue
                key = v if k == 'r20' else f'{v}_n20'
                a = [val(('MSCA+MES', d, i), v, k) for i in s]
                b = [val(('MSCA', d, i), v, k) for i in s]
                r = sigtest.paired(a, b)
                r.update(variant=v, metric=k, dataset=d, n=len(s), key=key)
                res.append(r)
            sigtest.family(res)
            out += res
    return out


N20 = {}
for r in bc.CELLS:
    if r['gate_ok'] == '1':
        k = (r['model'], r['dataset'], int(r['seed']))
        N20[k] = {'base': float(r['base_n20'])}
        for f in ('combo', 'ease', 'icf', 'mix'):
            if r.get(f'{f}_n20'):
                N20[k][f] = float(r[f'{f}_n20'])
for k, r in bc.OLD.items():      # TABLE_FUSION cells keep their own N@20 (F and base) where the queue did not recompute F
    N20.setdefault(k, {})
    N20[k].setdefault('base', float(r['base_n20']))
    if 'combo' not in N20[k] and r.get('fused_n20'):
        N20[k]['combo'] = float(r['fused_n20'])


def val(key, v, k):
    return bc.cell[key][v] if k == 'r20' else N20[key][v]


def seed1_check():
    t2 = {r['dataset']: r for r in csv.DictReader(open(DATA / 'rev2_msca_t2_s1.csv', newline='', encoding='utf-8'))}
    refuse = {(r['model'], r['dataset'], r['seed']): r for r in csv.DictReader(open(DATA / 'fusion_cells_s4.csv', newline='', encoding='utf-8'))}
    rows = []
    for d in ('baby', 'pantry', 'scientific'):
        r = t2[d]
        assert r['gate_ok'] == '1'
        assert abs(float(r['combo_r20']) - float(refuse[('MSCA', d, '1')]['fused_r20'])) < 1e-6, d    # REFUSE F reused, identical (csv rounded to 6 decimals)
        mes = bc.cell[('MSCA+MES', d, 1)]
        fs = bc.cell[('MSCA', d, 1)]
        rows.append(dict(dataset=d, t2_base=float(r['base_r20']), fs_base=fs['base'], t2_F=float(r['combo_r20']), fs_F=fs['combo'],
                         t2_mix=float(r['mix_r20']), fs_mix=fs['mix'],
                         mF_t2=mes['combo'] - float(r['combo_r20']), mF_fs=mes['combo'] - fs['combo'],
                         mM_t2=mes['mix'] - float(r['mix_r20']), mM_fs=mes['mix'] - fs['mix']))
    return rows


def main():
    pairs = f_universe()
    n = len(pairs)
    assert all(p['up'] for p in pairs), [p for p in pairs if not p['up']]
    tested = [p for p in pairs if p['tested']]
    five = [p for p in pairs if p['n'] == 5]
    low = [p for p in pairs if p['n'] < 5]
    mac('rvFNPairs', str(n))
    mac('rvFNDs', cnt(len({p['dataset'] for p in pairs})))
    mac('rvFNUp', str(sum(p['up'] for p in pairs)))
    mac('rvMinSeeds', cnt(MIN_SEEDS))
    mac('rvFNTested', str(len(tested)))
    mac('rvFNSig', str(sum(p['reject'] and p['diff'] > 0 for p in tested)))
    mac('rvFNSigDown', cnt(sum(p['reject'] and p['diff'] < 0 for p in tested)))
    mac('rvFNFive', str(len(five)))
    mac('rvFNFiveSig', str(sum(p.get('reject', 0) and p['diff'] > 0 for p in five)))
    mac('rvFNLow', cnt(len(low)))
    mac('rvFNUntested', cnt(n - len(tested)))
    by_m = {}
    for p in low:
        by_m.setdefault(p['model'], []).append(f"{NAME[p['dataset']]} ({p['n']})")
    mac('rvLowList', join(f"{MLAB[m]} on {', '.join(v)}" for m, v in by_m.items()))
    mac('rvUntestedList', join(f"{MLAB[p['model']]} on {NAME[p['dataset']]}" for p in pairs if not p['tested']))
    micro = [p for p in pairs if p['dataset'] == 'microlens']
    mac('rvFNPairsMicro', cnt(len(micro)))
    mac('rvFMicroModels', join(MLAB[p['model']] for p in micro))
    mac('rvFNPairsFour', str(sum(p['dataset'] in FOUR for p in pairs)))
    mac('rvFNPairsOther', str(sum(p['dataset'] not in FOUR for p in pairs)))
    t4 = [p for p in tested if p['dataset'] in FOUR]
    mac('rvFNTestedFour', str(len(t4))); mac('rvFNSigFour', str(sum(p['reject'] and p['diff'] > 0 for p in t4)))
    # consistency with the CLASSIC macros (same cells): tested F pairs = mix pairs
    assert len(tested) == int(re.search(r'\\clNComboPairs\}\{(\d+)\}', (ROOT / 'macros_classic.tex').read_text(encoding='utf-8')).group(1))
    with open(DATA / 'rev2_pairs.csv', 'w', newline='', encoding='utf-8') as f:
        cols = ['model', 'dataset', 'n', 'seeds', 'base', 'F', 'up', 'tested', 'diff', 'p', 'p_holm', 'reject']
        w = csv.DictWriter(f, cols, lineterminator='\n', extrasaction='ignore'); w.writeheader()
        for p in pairs:
            w.writerow({k: (f'{p[k]:.6g}' if isinstance(p.get(k), float) else p.get(k, '')) for k in cols})

    # MES margins (base, F, mix), the family of build_table_classic.py extended to NDCG@20
    M = margins()
    with open(DATA / 'rev2_margins.csv', 'w', newline='', encoding='utf-8') as f:
        cols = ['variant', 'metric', 'dataset', 'n', 'mean_a', 'mean_b', 'diff', 'ci_lo', 'ci_hi', 'p', 'm', 'p_holm', 'reject']
        w = csv.DictWriter(f, cols, lineterminator='\n', extrasaction='ignore'); w.writeheader()
        for r in M:
            w.writerow({k: (f'{r[k]:.6g}' if isinstance(r.get(k), float) else r.get(k, '')) for k in cols})
    mixr = [r for r in M if r['variant'] == 'mix' and r['metric'] == 'r20']
    mac('rvMixMarginNDs', cnt(len(mixr)))
    mac('rvMixMarginLo', sgn(min(r['diff'] for r in mixr))); mac('rvMixMarginHi', sgn(max(r['diff'] for r in mixr)))
    mac('rvMixMarginNSigPos', cnt(sum(r['reject'] and r['diff'] > 0 for r in mixr)))
    mac('rvMixMarginNSigNeg', cnt(sum(r['reject'] and r['diff'] < 0 for r in mixr)))
    # cross-check against the CLASSIC macros (same family, Recall@20)
    cl = (ROOT / 'macros_classic.tex').read_text(encoding='utf-8')
    neg = [r for r in mixr if r['reject'] and r['diff'] < 0]
    assert len(neg) == 1 and f"{neg[0]['p_holm']:.3f}" in cl and NAME[neg[0]['dataset']] in cl

    # same-checkpoint seed-1 check of the Table-II MSCA checkpoints
    S1 = seed1_check()
    with open(DATA / 'rev2_seed1_check.csv', 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, list(S1[0].keys()), lineterminator='\n'); w.writeheader()
        for r in S1:
            w.writerow({k: (f'{v:.6f}' if isinstance(v, float) else v) for k, v in r.items()})
    lst = lambda key: '/'.join(f"{1e3 * r[key]:+.1f}".replace('-', '$-$').replace('+', '$+$') for r in S1)   # noqa: E731
    mac('rvSoneFTwo', lst('mF_t2')); mac('rvSoneFFs', lst('mF_fs'))
    mac('rvSoneMixTwo', lst('mM_t2')); mac('rvSoneMixFs', lst('mM_fs'))
    mac('rvSoneBaseDiffMax', f"{max(abs(r['t2_base'] - r['fs_base']) for r in S1):.4f}")
    mac('rvSoneFDiffMax', f"{max(abs(r['t2_F'] - r['fs_F']) for r in S1):.4f}")
    mac('rvSoneMixDiffMax', f"{max(abs(r['t2_mix'] - r['fs_mix']) for r in S1):.4f}")
    mac('rvSoneNSignSame', cnt(sum((r['mF_t2'] > 0) == (r['mF_fs'] > 0) for r in S1) + sum((r['mM_t2'] > 0) == (r['mM_fs'] > 0) for r in S1)))
    mac('rvSoneNComp', cnt(2 * len(S1)))

    # public CSV of every fused cell of the supplementary data (no server paths)
    cols = ['model', 'dataset', 'seed', 'base_r20', 'base_n20', 'F_r20', 'F_n20', 'ease_r20', 'ease_n20', 'cf_r20', 'cf_n20', 'mix_r20', 'mix_n20']
    with open(REPO / 'supplementary_data_classic_fusion.csv', 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f, lineterminator='\n'); w.writerow(cols)
        for (m, d, s) in sorted(bc.cell, key=lambda k: (bc.MODELS.index(k[0]), DS9.index(k[1]), k[2])):
            c, n2 = bc.cell[(m, d, s)], N20.get((m, d, s), {})
            row = [m, d, s]
            for v in ('base', 'combo', 'ease', 'icf', 'mix'):
                row += [f'{c[v]:.6f}' if v in c else '', f'{n2[v]:.6f}' if v in n2 else '']
            w.writerow(row)
    mac('rvNCsvCells', str(len(bc.cell)))
    (ROOT / 'macros_rev2.tex').write_text('\n'.join(OUT) + '\n', encoding='utf-8', newline='\n')
    print('\n'.join(OUT))


if __name__ == '__main__':
    main()
