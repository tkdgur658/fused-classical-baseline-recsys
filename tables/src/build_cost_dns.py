"""Cost of XRE against the anchor term with masked DNS on MSCA (reviewer question, E5, HOST_A).

Input: tables/e5_cost.tsv, a copy of HOST_A <RUN_ROOT_B>/P04_e4e5/e5_cost.tsv (collect_e4e5.py). Profiling runs
are separate from the result runs: epoch time = mean of epochs 1-3 after one warm-up epoch (epoch_sec_mean_e1_3), memory
= peak allocated memory (peak_alloc_mib), Baby / Pantry / Scientific.

  scp HOST_A:<RUN_ROOT_B>/P04_e4e5/e5_cost.tsv tables/e5_cost.tsv
  python -s tables/src/build_cost_dns.py

Output: tables/macros_costdns.tex (prefix cq, Section IV-A c)) and the lines 'costdns:' of tables/claims_check.txt.
"""
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DS = [('baby', 'Baby'), ('pantry', 'Pantry'), ('scientific', 'Scientific')]
XRE, DNS, NAT = 'MSCA + XRE', 'MSCA + A + masked DNS', 'MSCA'


def main():
    rows = list(csv.DictReader(open(ROOT / 'e5_cost.tsv', encoding='utf-8'), delimiter='\t'))
    v = {(r['dataset'], r['method']): r for r in rows}
    out = ['% Generated by tables/src/build_cost_dns.py from tables/e5_cost.tsv. Do not edit by hand.',
           '% XRE against A + masked DNS on MSCA, one GPU: epoch time (mean of epochs 1-3) and peak allocated memory.']

    def mac(n, val):
        assert re.fullmatch(r'cq[A-Za-z]+', n), n
        out.append(f'\\newcommand{{\\{n}}}{{{val}}}')
    slower, lessmem, claims = [], [], []
    for d, D in DS:
        x, m = v[(d, XRE)], v[(d, DNS)]
        if x['gpu'] != m['gpu']:   # device check (non-fatal): both profiling runs of a dataset should share one device
            print(f'WARNING {d}: the two profiling runs report different devices', file=sys.stderr)
        t = 100 * (float(x['epoch_sec_mean_e1_3']) / float(m['epoch_sec_mean_e1_3']) - 1)   # XRE slower by t %
        mm = 100 * (1 - float(x['peak_alloc_mib']) / float(m['peak_alloc_mib']))         # XRE needs mm % less memory
        slower.append(t)
        lessmem.append(mm)
        mac(f'cqTime{D}', f'{t:.0f}')
        mac(f'cqMem{D}', f'{mm:.0f}')
        claims.append(f"costdns: {D} epoch s XRE {x['epoch_sec_mean_e1_3']} vs A+mDNS {m['epoch_sec_mean_e1_3']} "
                      f"(XRE {t:+.1f}%), peak MiB XRE {x['peak_alloc_mib']} vs A+mDNS {m['peak_alloc_mib']} "
                      f"(XRE {-mm:+.1f}%); ratios vs MSCA time {x['ratio_time']}/{m['ratio_time']}, "
                      f"mem {x['ratio_mem']}/{m['ratio_mem']}")
    assert all(t > 0 for t in slower) and all(mm > 0 for mm in lessmem), (slower, lessmem)   # wording of c)
    names = [D for _, D in DS]
    mac('cqDs', ', '.join(names[:-1]) + ', and ' + names[-1])
    mac('cqTimeMin', f'{min(slower):.0f}')
    mac('cqTimeMax', f'{max(slower):.0f}')
    mac('cqMemMin', f'{min(lessmem):.0f}')
    mac('cqMemMax', f'{max(lessmem):.0f}')
    (ROOT / 'macros_costdns.tex').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    claims.append(f"costdns: c) 'XRE runs cqTimeMin-cqTimeMax % longer per epoch than A + masked DNS, using cqMemMin-cqMemMax "
                  f"% less peak memory' holds on every dataset: True")
    cc = ROOT / 'claims_check.txt'
    keep = [x for x in (cc.read_text(encoding='utf-8').splitlines() if cc.exists() else []) if not x.startswith('costdns:')]
    cc.write_text('\n'.join(keep + claims) + '\n', encoding='utf-8', newline='\n')
    print('\n'.join(out[2:]))


if __name__ == '__main__':
    main()
