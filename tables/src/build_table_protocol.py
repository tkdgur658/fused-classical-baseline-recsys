"""Build the appendix training-protocol tables from per-run files. Numbers are never typed by hand.

Inputs (produced by the collectors in this folder, see their docstrings):
  tables/protocol_runs.tsv       <- collect_protocol_runs.py (HOST_A): Table-1 rows on MSCA and FREEDOM, 3 protocols
  tables/protocol_sota_runs.tsv  <- collect_protocol_sota_runs.py (HOST_D): Table-2 baselines, 2 batch-2048 protocols
  tables/table1_cells.csv, table1_runs.tsv <- collect_table1.py: protocol C = the Table II runs (seeds 1-5)
Outputs:
  tables/appendix_protocol.tex       (label tab:protocol)
  tables/appendix_protocol_sota.tex  (label tab:protocol_sota)
  tables/appendix_protocol_cells.csv (the aggregated cells, for the text and for checking)
A run is marked as stopped early when its best validation epoch is <= COLLAPSE_EPOCH. Each cell reports the mean test
Recall@20 over the available seeds, the number of seeds in parentheses, and a superscript k when k of those runs stopped early
(a single-character superscript, user math rule 2026-10-06; formerly ^{*k}).
Usage: python tables/src/build_table_protocol.py
"""
import csv
import hashlib
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / 'protocol_runs.tsv'
SOTA = ROOT / 'protocol_sota_runs.tsv'
T1 = ROOT / 'table1_cells.csv'
T1_RUNS = ROOT / 'table1_runs.tsv'
OUT = ROOT / 'appendix_protocol.tex'
OUT_SOTA = ROOT / 'appendix_protocol_sota.tex'
OUT_CELLS = ROOT / 'appendix_protocol_cells.csv'
COLLAPSE_EPOCH = 2

BACKBONES = ['MSCA', 'FREEDOM']
ROWS = [('INA', 'INA-style'), ('MDVT', 'MDVT'), ('MG', 'MG'),   # printed labels as Table I (2026-10-06)
        ('DA-MRS', 'DA-MRS'), ('UltraGCN-LI', 'UltraGCN $\\mathcal{L}_I$'), ('Native', None)]  # newest first, Native last
SOTA_MODELS = ['MSCA', 'COHESION', 'SMORE', 'PGL', 'DiffMM', 'LGMRec', 'FREEDOM']   # MENTOR removed from the compared models (2026-10-05)
DATASETS = [('baby', 'Baby'), ('pantry', 'Pantry'), ('scientific', 'Scientific')]
PROTOCOLS = [('common', 'C'), ('b2048', 'B'), ('plugin', 'P')]


def read_tsv(path):
    with open(path, newline='') as f:
        return list(csv.DictReader(f, delimiter='\t'))


def aggregate(rows, keys):
    cells = {}
    for r in rows:
        cells.setdefault(tuple(r[k] for k in keys), []).append(r)
    out = {}
    for k, rr in cells.items():
        eps = [int(r['best_epoch']) for r in rr]
        out[k] = {'n': len(rr), 'r20': st.mean(float(r['test_r20']) for r in rr),
                  'n20': st.mean(float(r['test_n20']) for r in rr),
                  'collapsed': sum(e <= COLLAPSE_EPOCH for e in eps), 'best_epochs': '/'.join(map(str, eps)),
                  'seeds': '/'.join(r['seed'] for r in rr), 'config': rr[0].get('config')}
    return out


def fmt(c):
    if c is None:
        return '--'
    s = f"{c['r20']:.4f}\\,({c['n']})"
    if c['collapsed']:
        s += f"$^{{{c['collapsed']}}}$"
    return s


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16]


def common_from_table1(cells):
    """Protocol C = the Table II runs (tables/table1_runs.tsv, chosen runs, seeds 1-5), so every C cell, including
    Native, prints the Table II value. B and P keep only runs whose configuration is the Table II configuration of the
    row (source column of table1_cells.csv, with the protocol suffix removed); other B/P cells print '--'."""
    with open(T1, newline='') as f:
        t1 = {(r['backbone'], r['row'], r['dataset']): r for r in csv.DictReader(f)}
    runs = [r for r in read_tsv(T1_RUNS) if r['chosen'] == '1']
    for k in [k for k in cells if k[0] == 'common']:
        del cells[k]
    for k in [k for k in cells if k[0] != 'common']:
        ref = t1.get(k[1:])
        if not ref or cells[k]['config'] != ref['source'].split('/', 1)[1]:
            del cells[k]
    common = aggregate([dict(r, protocol='common') for r in runs], ['protocol', 'backbone', 'row', 'dataset'])
    for k, c in common.items():
        ref = t1[k[1:]]
        assert f"{c['r20']:.4f}" == f"{float(ref['r20_mean']):.4f}" and c['n'] == int(ref['n']), k
        if c['n'] == 5:
            cells[k] = c


def build_main(cells):
    ncol = 1 + len(PROTOCOLS) * len(DATASETS)
    lines = [
        f'% Generated by tables/src/build_table_protocol.py from tables/protocol_runs.tsv (sha256 {sha(RUNS)}) and '
        f'tables/table1_runs.tsv (sha256 {sha(T1_RUNS)}). Do not edit numbers by hand.',
        '\\begin{table*}[t]',
        '\\caption{Test Recall@20 of the plug-in and backbone rows of Table~\\ref{tab:main} on MSCA and of '
        'Table~\\ref{tab:transfer} on FREEDOM under three training protocols. '
        'C: the common protocol of Section~\\ref{supp:settings} (batch 256, AdamW, cosine schedule, 100 epochs, patience 10). '
        'B: batch 2048, 1000 epochs, and patience 20, with the cosine horizon set to 1000 epochs and the other '
        'settings of C. '
        'P: default training settings of MMRec, on which the released code of MG, MDVT, and DA-MRS builds '
        '(batch 2048, Adam, constant learning rate, full precision, 1000 epochs, patience 20). '
        'Each cell reports the mean over the available seeds, with the number of seeds in parentheses. '
        'Column C repeats these rows (seeds 1--5), and B and P use seeds 1--3. '
        '--: not run under this protocol. '
        f'A superscript $k$: in $k$ of these seeds, validation Recall@20 peaked within {COLLAPSE_EPOCH} epochs '
        'and did not exceed it in the next 20 epochs, so early stopping ended training.}',
        '\\label{tab:protocol}',
        '\\centering',
        '\\footnotesize',
        '\\setlength{\\tabcolsep}{3.5pt}',
        '\\begin{tabular}{l' + 'ccc' * len(DATASETS) + '}',
        '\\toprule',
        ' & ' + ' & '.join(f'\\multicolumn{{3}}{{c}}{{{name}}}' for _, name in DATASETS) + ' \\\\',
        ''.join(f'\\cmidrule(lr){{{2 + 3 * i}-{4 + 3 * i}}}' for i in range(len(DATASETS))),
        'Objective & ' + ' & '.join(' & '.join(p for _, p in PROTOCOLS) for _ in DATASETS) + ' \\\\',
    ]
    for b in BACKBONES:
        lines += ['\\midrule', f'\\multicolumn{{{ncol}}}{{l}}{{\\textit{{Backbone: {b}}}}} \\\\']
        for row, label in ROWS:
            vals = [fmt(cells.get((p, b, row, d))) if (p, b, row, d) in cells or p != 'common' else '\\todo{pending}'
                    for d, _ in DATASETS for p, _ in PROTOCOLS]
            lines.append(f"{label or f'Backbone ({b})'} & " + ' & '.join(vals) + ' \\\\')   # backbone row: backbone name
    lines += ['\\bottomrule', '\\end{tabular}', '\\end{table*}', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')


def build_sota(cells):
    prot = PROTOCOLS[1:]
    lines = [
        f'% Generated by tables/src/build_table_protocol.py from tables/protocol_sota_runs.tsv (sha256 {sha(SOTA)}). '
        'Do not edit numbers by hand.',
        '\\begin{table*}[t]',
        '\\caption{Test Recall@20 of the compared multimodal recommenders under protocols B and P of '
        'Table~\\ref{tab:protocol}, each with its author configuration. '
        'Each cell reports the mean over the available seeds, with the number of seeds in parentheses. '
        'The MSCA and FREEDOM cells come from runs separate from those of Table~\\ref{tab:protocol} and can '
        'differ from it. A superscript $k$ is defined as in Table~\\ref{tab:protocol}.}',
        '\\label{tab:protocol_sota}',
        '\\centering',
        '\\footnotesize',
        '\\begin{tabular}{l' + 'cc' * len(DATASETS) + '}',
        '\\toprule',
        ' & ' + ' & '.join(f'\\multicolumn{{2}}{{c}}{{{name}}}' for _, name in DATASETS) + ' \\\\',
        ''.join(f'\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}' for i in range(len(DATASETS))),
        'Model & ' + ' & '.join(' & '.join(p for _, p in prot) for _ in DATASETS) + ' \\\\',
        '\\midrule',
    ]
    for m in SOTA_MODELS:
        vals = [fmt(cells.get((p, m, d))) for d, _ in DATASETS for p, _ in prot]
        lines.append(f'{m} & ' + ' & '.join(vals) + ' \\\\')
    lines += ['\\bottomrule', '\\end{tabular}', '\\end{table*}', '']
    OUT_SOTA.write_text('\n'.join(lines), encoding='utf-8', newline='\n')


def main():
    cells = aggregate(read_tsv(RUNS), ['protocol', 'backbone', 'row', 'dataset'])
    common_from_table1(cells)
    sota = aggregate(read_tsv(SOTA), ['protocol', 'model', 'dataset'])
    build_main(cells)
    build_sota(sota)
    with open(OUT_CELLS, 'w', newline='') as f:
        w = csv.writer(f, lineterminator='\n')
        w.writerow(['block', 'protocol', 'model', 'row', 'dataset', 'n', 'r20_mean', 'n20_mean', 'n_stopped_le2',
                    'seeds', 'best_epochs'])
        for (p, b, row, d), c in sorted(cells.items()):
            w.writerow(['table1_rows', p, b, row, d, c['n'], f"{c['r20']:.4f}", f"{c['n20']:.4f}", c['collapsed'],
                        c['seeds'], c['best_epochs']])
        for (p, m, d), c in sorted(sota.items()):
            w.writerow(['sota', p, m, 'Native', d, c['n'], f"{c['r20']:.4f}", f"{c['n20']:.4f}", c['collapsed'],
                        c['seeds'], c['best_epochs']])
    print('wrote', OUT, OUT_SOTA, OUT_CELLS)


if __name__ == '__main__':
    main()
