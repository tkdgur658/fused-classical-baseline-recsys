"""Build tables/macros_mesc.tex and tables/appendix_mesc.tex: the MES-C result of PREREG_MESC (H_C verdict, test Recall@20,
seeds 1-5; gamma selection and K1 gate on seed-1 validation). Added 2026-10-16 (revision log 21).
Sources (copies of study/results/mesc, written by study/MESC/code/mesc_verdict.py sha fc036d40 and mesc_gamma_select.py):
  tables/src/data/hc_verdict.json, tables/src/data/gamma_selected.json. Numbers are never typed by hand.
Rules fixed here (not read from the files):
  - classical-miss gain = stratum B difference above zero while stratum A is below zero (post hoc strata of MES-C + F minus MES + F);
  - near-tie of the K1 gate = validation margin of MES-C + F over MES + F of at most 2e-4 (TIE_TOL, as in the verdict note).
Usage: python tables/src/build_macros_mesc.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'src' / 'data'
DS = ['baby', 'pantry', 'scientific', 'sports']
NAME = {'baby': 'Baby', 'pantry': 'Pantry', 'scientific': 'Scientific', 'sports': 'Sports'}
WORD = ['none', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten']
BS = chr(92)
TIE_TOL = 2e-4


def m(name, val):
    return BS + 'newcommand{' + BS + name + '}{' + val + '}'


def signed(x, nd=4):
    return f'${x:+.{nd}f}$'


def tsigned(x, nd=4):
    """Table style: sign outside math mode, as in appendix_complement.tex."""
    return ('$+$' if x >= 0 else '$-$') + f'{abs(x):.{nd}f}'


def join(items):
    return items[0] if len(items) == 1 else ', '.join(items[:-1]) + (',' if len(items) > 2 else '') + ' and ' + items[-1]


def gnum(g):
    return f'{g:g}'.replace('0.', '0.', 1)


def main():
    v = json.load(open(DATA / 'hc_verdict.json', encoding='utf-8'))
    g = json.load(open(DATA / 'gamma_selected.json', encoding='utf-8'))
    rows = {r['ds']: r for r in v['rows']}
    assert sorted(rows) == DS and v['H_C'] == 'FAIL' and g['K1'] == 'PASS' and g['complete']
    sig = [d for d in DS if rows[d]['sig_pos']]
    ge = [d for d in DS if rows[d]['ge_mes_f']]
    assert len(sig) == v['n_sig'] and len(ge) == v['n_ge_mes_f']
    alone = v['mesc_alone_vs_mes']
    within = [d for d in DS if not alone[d]['outside_1sd']]
    sd_ratio = max(abs(alone[d]['diff']) / alone[d]['sd_mes'] for d in DS)
    gam = {d: g['per_ds'][d]['chosen_gamma'] for d in DS}
    grid = sorted(float(k) for k in g['detail']['baby'])
    margin = {d: g['per_ds'][d]['best_fused_val'] - g['per_ds'][d]['mes_fused_val'] for d in DS}
    n_beat = sum(g['per_ds'][d]['beats'] for d in DS)
    assert n_beat == g['n_beat']
    ties = [d for d in DS if 0 < margin[d] <= TIE_TOL]
    st = v['strata_fused_minus_mesF']
    miss_gain = [d for d in DS if st[d]['B'] > 0 > st[d]['A']]
    out = ['% Generated by tables/src/build_macros_mesc.py from hc_verdict.json and gamma_selected.json. Do not edit by hand.',
           m('mcNSig', WORD[v['n_sig']]),
           m('mcSigDs', join([NAME[d] for d in sig])),
           m('mcPHolmSig', f"{min(rows[d]['p_holm'] for d in sig):.4f}"),
           m('mcNGeMesF', WORD[v['n_ge_mes_f']]),
           m('mcDiffMscaList', join([signed(rows[d]['d_msca']) for d in DS])),
           m('mcDiffMesList', join([signed(rows[d]['d_mes']) for d in DS])),
           m('mcNAloneWithin', WORD[len(within)]),
           m('mcAloneMaxSd', f'{sd_ratio:.2f}'),
           m('mcNNdcgSame', WORD[v['ndcg_same_direction']]),
           m('mcGammaList', join([gnum(gam[d]) for d in DS])),
           m('mcGrid', ', '.join(gnum(x) for x in grid)),
           m('mcKNBeat', WORD[n_beat]),
           m('mcKMarginMin', f'{min(margin.values()):.4f}'),
           m('mcKMarginMax', f'{max(margin.values()):.4f}'),
           m('mcKNTie', WORD[len(ties)]),
           m('mcKTol', f'{TIE_TOL:.4f}'),
           m('mcStrataHitList', join([signed(st[d]['A']) for d in DS])),
           m('mcStrataMissList', join([signed(st[d]['B']) for d in DS])),
           m('mcNMissGain', WORD[len(miss_gain)]),
           m('mcMissGainDs', join([NAME[d] for d in miss_gain])),
           '']
    (ROOT / 'macros_mesc.tex').write_text('\n'.join(out), encoding='utf-8', newline='\n')

    cap = ('Test Recall@20 of MES-C with fusion, the preregistered verdict on the four tuned datasets, mean over seeds 1--5. '
           'MES-C $\\oplus$ is MES-C with the fused classical score of F added after training, with the weight chosen on validation as for MSCA $\\oplus$ and MES $\\oplus$, and $\\gamma$ is chosen per dataset on seed-1 validation.'
           '$\\Delta_{\\mathrm{MSCA}}$ and $\\Delta_{\\mathrm{MES}}$ give the mean difference of MES-C $\\oplus$ to MSCA $\\oplus$ and MES $\\oplus$, with the Holm-adjusted $p_H$ of the two-sided paired $t$-test over seeds 1--5 for the former and Wins the number of seeds above MSCA $\\oplus$. '
           f"MES-C $\\oplus$ is significantly above MSCA $\\oplus$ on {WORD[v['n_sig']]} of four datasets and at or above MES $\\oplus$ on {WORD[v['n_ge_mes_f']]} of four, "
           'whereas the preregistered criterion required three and four, respectively.')
    tab = ['% Generated by tables/src/build_macros_mesc.py from tables/src/data/hc_verdict.json and gamma_selected.json. Do not edit numbers by hand.',
           BS + 'begin{table*}[t]', BS + 'caption{' + cap + '}', BS + 'label{tab:mesc}', BS + 'centering', BS + 'footnotesize',
           BS + 'setlength{' + BS + 'tabcolsep}{5pt}',
           BS + 'begin{tabular}{lrrrrrrrr}', BS + 'toprule',
           'Dataset & $\\gamma$ & MES-C $\\oplus$ & MSCA $\\oplus$ & MES $\\oplus$ & $\\Delta_{\\mathrm{MSCA}}$ & $\\Delta_{\\mathrm{MES}}$ & $p_H$ & Wins \\\\',
           BS + 'midrule']
    for d in DS:
        r = rows[d]
        tab.append(f"{NAME[d]} & {gnum(gam[d])} & {r['mesc_f']:.4f} & {r['msca_f']:.4f} & {r['mes_f']:.4f} & {tsigned(r['d_msca'])} & "
                   f"{tsigned(r['d_mes'])} & {r['p_holm']:.4f} & {r['wins']}/5 " + BS + BS)
    tab += [BS + 'bottomrule', BS + 'end{tabular}', BS + 'end{table*}', '']
    (ROOT / 'appendix_mesc.tex').write_text('\n'.join(tab), encoding='utf-8', newline='\n')
    print('\n'.join(out))
    print('\n'.join(tab))


if __name__ == '__main__':
    main()
